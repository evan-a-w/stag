open! Import
module Measure = Stag_measure

let config =
  { Measure.Config.quick with
    samples = 5
  ; min_samples = 5
  ; warm_up = Time_ns.Span.of_int_us 1
  ; measurement_time = Time_ns.Span.of_int_us 5
  }
;;

let benches ?files source =
  match
    Driver.check_files
      ~limits:Source_helpers.limits
      [ { Source_file.path = "t.stag"; contents = source } ]
  with
  | Error error ->
    List.iter error ~f:(fun error -> print_s [%sexp (error : Driver.Error.t)]);
    None
  | Ok driver ->
    Driver.eval ~limits:Source_helpers.limits driver |> ok_exn;
    (match Bench_runner.benches ?files driver with
     | Error diagnostic ->
       print_s [%sexp (diagnostic : Diagnostic.t)];
       None
     | Ok benches -> Some benches)
;;

(* The names of the benches, and the result of an iteration of each, by
   running it once. *)
let print_benches ?files source =
  let print name (routine : Measure.Routine.t) =
    let outcome =
      match routine with
      | Plain run ->
        (match run () with
         | Ok () -> "ok"
         | Error error -> Error.to_string_hum error)
      | Batched _ -> "batched"
    in
    print_s [%message name (outcome : string)]
  in
  Option.iter (benches ?files source) ~f:(fun benches ->
    List.iter benches ~f:(function
      | Single { name; routine } -> print name routine
      | Parameterised { name; args } ->
        List.iter args ~f:(fun arg ->
          match arg () with
          | Ok (label, routine) -> print (name ^ "/" ^ label) routine
          | Error error -> print_s [%message name (error : Error.t)])))
;;

let%expect_test
    "benches are collected in order, parameterised ones per argument"
  =
  print_benches
    {|
let fib n = match Int.lt n 2 with
  | true -> n
  | false -> Int.add (fib (Int.sub n 1)) (fib (Int.sub n 2))
let%bench "fib" = fib 10
module M = struct
  let%bench "in a module" = ()
end
let%bench "fib" n in [1; Int.add 2 3] = fib n
let%bench "strings" s in ["a"; "b c"] = String.length s
let%bench "fails" = Int.div 1 0
let%expect_test "not a bench" = ()
|};
  [%expect
    {|
    (fib (outcome ok))
    ("in a module" (outcome ok))
    (fib/1 (outcome ok))
    (fib/5 (outcome ok))
    ("strings/\"a\"" (outcome ok))
    ("strings/\"b c\"" (outcome ok))
    (fails
     (outcome "(\"Uncaught exception Division_by_zero\" @ t.stag:11:20-31)"))
    |}]
;;

let%expect_test "bench bodies are typechecked, at level 0, and may use any type"
  =
  print_benches {|let%bench "x" = Int.add 1 "a"|};
  print_benches {|let%bench "x" n in [1; "a"] = n|};
  print_benches {|let%bench "x" n in [1] = String.length n|};
  print_benches {|let%bench "x" = .<1>.|};
  print_benches {|let%bench "x" = .~(.<1>.)|};
  print_benches {|let%bench "x" = unbound|};
  print_benches
    {|let%bench "x" n in [1] = n
let y = n|};
  [%expect
    {|
    (Typecheck
     ((Unification_error
       (Type_mismatch (TCon int ()) (TCon string ())
        (Base_types_not_equal int string)))
      @ t.stag:1:26-29))
    (Typecheck
     ((Unification_error
       (Type_mismatch (TCon int ()) (TCon string ())
        (Base_types_not_equal int string)))
      @ t.stag:1:23-26))
    (Typecheck
     ((Unification_error
       (Type_mismatch (TCon string ()) (TCon int ())
        (Base_types_not_equal string int)))
      @ t.stag:1:39-40))
    (x (outcome ok))
    (x (outcome ok))
    (Typecheck ((Not_in_scope unbound) @ t.stag:1:16-23))
    (Typecheck ((Not_in_scope n) @ t.stag:2:8-9))
    |}]
;;

let%expect_test "names" =
  print_benches
    {|
let%bench "a" = 1
let%bench "a" = 2
|};
  print_benches
    {|
let%bench "a" n in [1; 1] = n
|};
  print_benches
    {|
let%bench "a/1" = 1
let%bench "a" n in [1] = n
|};
  print_benches
    {|
let%bench "" = 1
|};
  [%expect
    {|
    ((loc t.stag:3:10-13) (whole_file false)
     (message "Two benchmarks are named \"a\"")
     (notes (((loc t.stag:2:10-13) (message "The other is here")))))
    (a/1 (outcome ok))
    (a
     (error
      ("Two benchmarks are named \"a/1\", the other at t.stag:2:10-13" @
       t.stag:2:10-13)))
    (a/1 (outcome ok))
    (a
     (error
      ("Two benchmarks are named \"a/1\", the other at t.stag:2:10-15" @
       t.stag:3:10-13)))
    ("" (outcome ok))
    |}]
;;

let%expect_test "benches generated by declaration splices" =
  print_benches
    {|
let%bench "written" = ()
include .~(Cons
  (Stag.Toplevel.Bench
     { `name = "generated"
     ; `param =
         (let p = ("n", Cons (Stag.Expr.int 1, Cons (Stag.Expr.int 2, Nil))) in Some p)
     ; `body = Stag.Expr.App (Stag.Expr.var "Int.to_string", Stag.Expr.var "n") },
   Nil))
let%bench "after" = ()
|};
  print_benches
    {|
include .~(Cons
  (Stag.Toplevel.Bench
     { `name = "bad"
     ; `param = None
     ; `body = Stag.Expr.App (Stag.Expr.var "Int.to_string", Stag.Expr.string "a") },
   Nil))
|};
  print_benches
    {|
include .~(Cons
  (Stag.Toplevel.Bench
     { `name = "none"; `param = (let p = ("n", Nil) in Some p); `body = Stag.Expr.var "n" },
   Nil))
|};
  [%expect
    {|
    (written (outcome ok))
    (generated/1 (outcome ok))
    (generated/2 (outcome ok))
    (after (outcome ok))
    (Typecheck
     ((In_generated_declaration (declaration "let%bench \"bad\"")
       (generated
        ((Bench (name (bad @ t.stag:2:0-7:8)) (param ())
          (body
           ((App ((Var Int.to_string ()) @ t.stag:2:0-7:8)
             ((Lit (String a)) @ t.stag:2:0-7:8))
            @ t.stag:2:0-7:8)))
         @ t.stag:2:0-7:8))
       (error
        (Unification_error
         (Type_mismatch (TCon int ()) (TCon string ())
          (Base_types_not_equal int string)))))
      @ t.stag:2:0-7:8))
    (Typecheck
     ((Malformed_declarations
       "Malformed syntax: expected a parameter with at least one argument, got (\"n\", Nil), within element 0 > Stag.Toplevel.Bench > field `param")
      @ t.stag:2:0-5:8))
    |}]
;;

