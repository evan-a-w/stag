let%expect_test "measuring with a fake clock" =
  Option.iter
    (benches
       {|
let%bench "unit" = ()
let%bench "fails" = Int.div 1 0
let%bench "after" n in [1; 2] = n
|})
    ~f:(fun benches ->
      let clock =
        Measure.Clock.Fake.clock
          (Measure.Clock.Fake.create ~tick:(Time_ns.Span.of_int_ns 100) ())
      in
      List.iter
        (Measure.Suite.run ~filters:[ "fail"; "after/2" ] config clock benches)
        ~f:(fun { Measure.Suite.Outcome.name; entry } ->
          match entry with
          | Error error -> print_s [%message name (error : Error.t)]
          | Ok entry -> print_string (Measure.Report.human config entry)));
  [%expect
    {|
    (fails (error ("Uncaught exception Division_by_zero" @ t.stag:3:20-31)))
    after/2
      time:      [0.1000 ns 0.1000 ns 0.1000 ns] (mean, 95% CI)
      median:    0.1000 ns   stddev: 0.000 ns   MADN: 0.000 ns
      range:     [0.1000 ns 0.1000 ns]   p90: 0.1000 ns   p99: 0.1000 ns
      samples:   5 x 1000 iterations (warm-up: 1023 iterations in 1.000 us)
      outliers:  none
    |}]
