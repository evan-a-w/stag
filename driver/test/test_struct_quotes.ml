open! Import

let check = File_check.check

let%expect_test "a struct quote is its declarations as data" =
  check
    ~run:true
    {|
let point = .< struct
  type t = {x : int; y : int}
  let origin = {x = 0; y = 0}
  let show p = Int.to_string p.x
end >.

module P = .~point

let shown = print_endline (P.show P.origin)
|};
  [%expect {|
    module A : sig
      val point : list[Stag.Toplevel.t]
      module P : sig
        type t = { x : int; y : int }
        val origin : t
        val show : t -> string
      end
      val shown : unit
    end
    --- output ---
    0
    |}]
;;

let%expect_test "antiquotes in each position" =
  check
    ~run:true
    {|
let variants names = Stag.Type_decl.Kind.Variant (Stag.map (fun name -> (name, Nil)) names)
let int = Stag.Type_expr.con "int" Nil

let make names extra =
  .< struct
    type t = .~(variants names)
    type boxed = {value : .~int}
    let f (x : .~int) = .~(Stag.Expr.var "x")
    include .~extra
    module Inner = .~extra
  end >.

include .~(make (Cons ("A", Cons ("B", Nil))) .< struct let y = 2 end >.)

let shown = print_endline (Int.to_string (Int.add (f y) Inner.y))
|};
  [%expect {|
    module A : sig
      val variants : list[string] -> Stag.Type_decl.Kind.t
      val int : Stag.Type_expr.t
      val make : list[string] -> list[Stag.Toplevel.t] -> list[Stag.Toplevel.t]
      type t = A | B
      type boxed = { value : int }
      val f : int -> int
      val y : int
      module Inner : sig
        val y : int
      end
      val shown : unit
    end
    --- output ---
    4
    |}]
;;

let%expect_test "printing a struct quote's value" =
  check
    ~run:true
    {|
let names = .< struct let x = .~(Stag.Expr.int 1) end >.
let shown =
  match names with
  | Cons (Stag.Toplevel.Let (name, _, _, _), Nil) -> print_endline name
  | _ -> print_endline "?"
|};
  [%expect {|
    module A : sig
      val names : list[Stag.Toplevel.t]
      val shown : unit
    end
    --- output ---
    x
    |}]
;;

let%expect_test "nested quotes are quoted" =
  check
    ~run:true
    {|
let quoted = .< struct
  let code = .< Int.add 1 .~(Stag.Expr.int 2) >.
  let decls = .< struct let z = .~(Stag.Expr.int 3) end >.
end >.

let shown =
  match quoted with
  | Cons (Stag.Toplevel.Let (_, _, _, Stag.Expr.Quote _), Cons (Stag.Toplevel.Let (_, _, _, Stag.Expr.Struct_quote _), Nil)) ->
    print_endline "quoted"
  | _ -> print_endline "?"
|};
  [%expect {|
    module A : sig
      val quoted : list[Stag.Toplevel.t]
      val shown : unit
    end
    --- output ---
    quoted
    |}]
;;

let%expect_test "an antiquote of the wrong type" =
  check {|
let bad = .< struct let x = .~1 end >.
|};
  [%expect {|
    File "a.stag", line 2, characters 30-31:
    2 | let bad = .< struct let x = .~1 end >.
                                      ^
    Error: This expression has type int but an expression was expected of type Stag.Expr.t
    |}]
;;

