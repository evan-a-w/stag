    |}]
;;

let%expect_test "type splices in declarations" =
  check
    ~run:true
    {|
let int = Stag.Type_expr.Con (Stag.Path.Name "int", Nil)
let fields names =
  Stag.Type_decl.Kind.Record (Stag.map (fun name -> (name, int)) names)

type point = .~(fields (Cons ("x", Cons ("y", Nil))))

let x : .~int = 1
let two = 2
let p = {x = x; y = (two : .~int)}
let f (q : point) : .~int = Int.add q.x q.y
type pair = (.~int * .~int)
let pair : pair = (1, 2)
exception E of .~int

let shown = print_endline (Int.to_string (f p))
|};
  [%expect
    {|
    module A : sig
      val int : Stag.Type_expr.t
      val fields : list[string] -> Stag.Type_decl.Kind.t
      type point = { x : int; y : int }
      val x : int
      val two : int
      val p : point
      val f : point -> int
      type pair = int * int
      val pair : int * int
      exception E of int
      val shown : unit
    end
    --- output ---
    3
    |}]
;;

let%expect_test "errors in type splices" =
  check
    {|
let x : .~1 = 1
|};
  [%expect
    {|
    File "a.stag", line 2, characters 10-11:
    2 | let x : .~1 = 1
                  ^
    Error: This expression has type int but an expression was expected of type Stag.Type_expr.t
    |}];
  check
    {|
let ty = Stag.Type_expr.Con (Stag.Path.Name "string", Nil)
let x : .~ty = 1
|};
  [%expect
    {|
    File "a.stag", line 3, characters 15-16:
    3 | let x : .~ty = 1
                       ^
    Error: This expression has type int but an expression was expected of type string
    |}];
  check
    {|
let ty = Stag.Type_expr.Con (Stag.Path.Name "nope", Nil)
type t = list[.~ty]
|};
  [%expect
    {|
    File "a.stag", line 3, characters 14-18:
    3 | type t = list[.~ty]
                      ^^^^
    Error: In the type this type splice gave: Unbound type nope
    Note: The type splice gave the type: nope
    |}];
  check
    {|
let ty = Stag.Type_expr.Con (Stag.Path.Name "int", Nil)
let one = 1
let quoted = .< (one : .~ty) >.
|};
  [%expect
    {|
    File "a.stag", line 4, characters 23-27:
    4 | let quoted = .< (one : .~ty) >.
                               ^^^^
    Error: A type splice runs at compile time, so it may be in a declaration, but not within a quote or a compile-time expression
    |}];
  check
    {|
let kind = Stag.Type_decl.Kind.Splice (Stag.Expr.int 1)
type t = .~kind
|};
  [%expect
    {|
    File "a.stag", line 3, characters 9-15:
    3 | type t = .~kind
                 ^^^^^^
    Error: This type splice gave a definition that is itself a splice, `Stag.Type_decl.Kind.Splice`
    |}]
;;
