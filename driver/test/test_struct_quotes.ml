let%expect_test "an error in quoted declarations is reported where spliced" =
  check
    {|
let decls = .< struct let x : int = "no" end >.
include .~decls
|};
  [%expect {|
    File "a.stag", line 3, characters 0-15:
    3 | include .~decls
        ^^^^^^^^^^^^^^^
    Error: In the declaration `let x` generated by this splice: This expression has type string but an expression was expected of type int
    Note: The generated declaration is:
      let x : int = "no"
    |}]
;;

let%expect_test "free names resolve where spliced; root paths and erased code don't" =
  check
    ~run:true
    {|
let helper = "generator's"
let decls = .< struct
  let a = helper
  let b = .A.helper
  let c = .~(Stag.Code.erase .<helper>.)
end >.

module M = struct
  let helper = "splice site's"
  include .~decls
end

let shown = print_endline M.a
let shown_b = print_endline M.b
let shown_c = print_endline M.c
|};
  [%expect {|
    module A : sig
      val helper : string
      val decls : list[Stag.Toplevel.t]
      module M : sig
        val helper : string
        val a : string
        val b : string
        val c : string
      end
      val shown : unit
      val shown_b : unit
      val shown_c : unit
    end
    --- output ---
    splice site's
    generator's
    generator's
    |}]
;;
