(* A declaration generated by a declaration splice, whose errors are reported
   at the splice, naming the declaration. *)
module Generated = struct
  type t =
    { splice : Loc.t
    ; declaration : string
    ; generated : Syntax.Toplevel.t [@sexp.opaque]
    }
  [@@deriving sexp_of]

  let create splice (toplevel : Syntax.Toplevel.t) =
    let declaration =
      match toplevel.txt with
      | Let (name, _, _, _) -> "let " ^ name.txt
      | Type decl -> "type " ^ decl.name.txt
      | Exception (name, _) -> "exception " ^ name.txt
      | Module (name, _) | Module_splice (name, _) -> "module " ^ name.txt
      | Include _ -> "include"
      | Expect_test { name; _ } -> sprintf "let%%expect_test %S" name.txt
      | Bench { name; _ } -> sprintf "let%%bench %S" name.txt
    in
    { splice = Module_scope.Splice.loc splice
    ; declaration
    ; generated = toplevel
    }
  ;;

  (* Errors in generated code are at the splice. Others, eg. of written
     declarations it uses, are left as they are. *)
  let wrap_error t (error : Typecheck_error.t) =
    match error.kind with
    | In_generated_declaration _ -> error
    | _ when not (Loc.equal error.loc t.splice) -> error
    | kind ->
      { error with
        loc = t.splice
      ; kind =
          In_generated_declaration
            { declaration = t.declaration
            ; generated = t.generated
            ; error = kind
            }
      }
  ;;

  let wrap_result t result =
    match t with
    | None -> result
    | Some t -> Result.map_error result ~f:(wrap_error t)
  ;;
end

module Toplevel = struct
  module State = struct
    type t =
      | Unchecked
      | In_progress of
          { index : int
          ; ty : Type.ty
          ; args : Typed.Ident.t list
          ; mutable body : Typed.Expr.t option
          ; mutable recursive : bool
          }
      | Done of
          { entry : Env.Entry.t
          ; typed : Typed.Toplevel.t
          }
    [@@deriving sexp_of]
  end

  type t =
    { ident : Typed.Ident.t
    ; module_ : Module_scope.t
    ; args : Syntax.Binding.t list
    ; annot : Syntax.Type_expr.t option
    ; expr : Syntax.Expr.t
    ; generated : Generated.t option
    ; mutable state : State.t
    }
  [@@deriving sexp_of]

  let is_function t = not (List.is_empty t.args)
end

type t =
  { fresh : Fresh.t
  ; interpreter : Treewalk.t
  }

let create
      ?(interpreter = Treewalk.create ~stamps:(Stamp_counter.create ()) ())
      ()
  =
  { fresh = Fresh.create (); interpreter }
;;

let lift ~loc result =
  Result.map_error result ~f:(Typecheck_error.unification_error ~loc)
;;

let error ~loc kind = Error (Typecheck_error.create ~loc kind)

(* Toplevels are checked on demand, so strongly connected components are found
   with Tarjan's algorithm as we go. [pending] are the visited toplevels whose
   component is not yet complete. *)
module Scc_frame = struct
  type t =
    { mutable lowlink : int
    ; mutable pending : Toplevel.t list
    }
end

(* What one call of [typecheck] checks. *)
module Program_env = struct
  type t =
    { type_env : Type_env.t
    ; toplevels : Toplevel.t Lazy.t String.Table.t
      (** By canonical name. The prelude's are made when first used, so that
          those unused take no idents. *)
    ; interpreter : Treewalk.t
    ; mutable ident_info : Typed.Ident_info.t Typed.Ident.Map.t
    ; sccs : Typed.Scc.t Queue.t
    ; declaration_splices : Typed.Expr.t Queue.t
    ; unusable_in_quotes : Typecheck_error.Unusable_in_quote.t String.Table.t
      (** The latest free variable of a quote that a binding of its name,
          unusable there, did not bind, to explain an error if the code is
          spliced where the name is unbound. *)
    ; unfinished : Type.ty Stack.t
      (** The types of the toplevels and binders of components not yet
          finished. Code checked later can reach them, so once their
          component is finished, the variables not generalized are lowered to
          rank 0, so that later components don't generalize them. *)
    }

  let fresh_ident t name =
    Typed.Ident.fresh (Treewalk.stamps t.interpreter) name
  ;;

  let find_toplevel t name =
    Hashtbl.find t.toplevels name |> Option.map ~f:force
  ;;

  let toplevel t name = force (Hashtbl.find_exn t.toplevels name)

  let add_info t ident ~ty ~level =
    let info = { Typed.Ident_info.ty; level } in
    t.ident_info <- Map.add_exn t.ident_info ~key:ident ~data:info;
    Treewalk.add_ident_info t.interpreter ~ident ~info
  ;;

  (* Generated code's binders keep their idents, but get their info anew. *)
  let bind t (binder : Source.Binder.t) ty ~level =
    let ident =
      match binder with
      | Name name -> fresh_ident t name.txt
      | Ident ident -> ident
    in
    add_info t ident ~ty ~level;
    Stack.push t.unfinished ty;
    ident
  ;;

  (* Values a toplevel splice's code embedded in its code. *)
  let embedded t ident =
    Treewalk.global_info t.interpreter ~ident
    |> Option.map ~f:(fun info ->
      t.ident_info <- Map.set t.ident_info ~key:ident ~data:info;
      info)
  ;;
end

(* Carries why reflection failed, eg. a cycle, through the evaluation, to be
   the error of that evaluation. *)
exception Reflection_failed of Typecheck_error.t [@@deriving sexp_of]

(* Evaluates at compile time, reflecting on the program's types. *)
let at_compile_time (program : Program_env.t) f ~error =
  let reflect name =
    let%bind.Result decl = Type_env.reflect program.type_env name in
    let%map.Result decl_type =
      Type_env.record_type
        program.type_env
        (Prelude_path.canonical "Stag.Type.Decl.t")
    in
    Syntax_value.reflected_decl decl ~decl_type
  in
  let reflect name =
    reflect name
    |> Result.map_error ~f:(fun error -> Error.of_exn (Reflection_failed error))
  in
  f ~reflect
  |> Result.map_error ~f:(fun runtime_error ->
    match Error.to_exn runtime_error with
    | Reflection_failed reflection_error -> reflection_error
    | _ -> error runtime_error)
;;

module Scope = struct
  type t =
    { program : Program_env.t
    ; level : Env.Level.t
    ; rank : Type.rank
    ; locals : Env.t
    ; quote : quote option
    ; module_ : Module_scope.t
    ; scc : Scc_frame.t
    ; annotation_vars : Type_env.Annotation_vars.t
    ; in_expect_test : bool
    }

  and quote =
    { id : int
    ; context : Type.row
    ; outside : t
    }

  let quote_id t = Option.map t.quote ~f:(fun quote -> quote.id)

  let entry t ~ident ~scheme ~persistent =
    { Env.Entry.scheme
    ; level = t.level
    ; quote_id = quote_id t
    ; persistent
    ; binder = Local ident
    }
  ;;

  let fresh_ty ids t = Type.TVar (Fresh.var ids ~rank:t.rank)
  let fresh_row ids t = Type.RVar (Fresh.var ids ~rank:t.rank)
  let fresh_presence ids t = Type.PVar (Fresh.var ids ~rank:t.rank)
  let instantiate ids t = Scheme.instantiate ids ~rank:t.rank

  let elaborate_resolved t annot =
    Type_env.elaborate t.program.type_env t.module_ t.annotation_vars annot
  ;;

  let elaborate t annot = elaborate_resolved t annot |> Result.map ~f:fst
end

(* Where a name is used, given its entry if it has one. *)
module Resolution = struct
  type t =
    | Local of Env.Entry.t
    (** Usable, and bound in the enclosing quote if there is one. *)
    | Outside_quote of
        { quote : Scope.quote
        ; usable : Env.Entry.t option
        ; unusable : Env.Entry.t option
        }
    (** Not bound in the enclosing [quote], so a free variable of it, unless
        used directly while [usable]. Splices never capture the name.
        [unusable] is the entry of the name, if it has one that isn't
        [usable]. *)
    | Unusable of Typecheck_error.Kind.t (** The error if the name is used. *)

  let of_entry (scope : Scope.t) ~name (entry : Env.Entry.t option) =
    let usable entry =
      Env.Entry.is_allowed_at
        entry
        ~used_at:scope.level
        ~quote_id:(Scope.quote_id scope)
    in
    match scope.quote, entry with
    | None, Some entry when usable entry -> Local entry
    | Some quote, Some entry
      when [%equal: int option] entry.quote_id (Some quote.id) -> Local entry
    | Some quote, Some entry when entry.level <= scope.level ->
      let usable = usable entry in
      Outside_quote
        { quote
        ; usable = Option.some_if usable entry
        ; unusable = Option.some_if (not usable) entry
        }
    | Some quote, None ->
      Outside_quote { quote; usable = None; unusable = None }
    | _, Some entry ->
      Unusable
        (Variable_used_at_wrong_level
           { name; var_level = entry.level; used_at = scope.level })
    | None, None -> Unusable (Not_in_scope (Path (Syntax.Path.of_string name)))
  ;;
end

(* Errs at the second occurrence of the first name repeated. *)
let check_no_duplicates (names : Syntax.Name.t list) ~error:kind =
  List.fold_result names ~init:String.Set.empty ~f:(fun seen { txt; loc } ->
    if Set.mem seen txt then error ~loc (kind txt) else Ok (Set.add seen txt))
  |> Result.ignore_m
;;

module Function_type = struct
  type t =
    { args : (Typed.Ident.t * Type.ty) list
    ; annots : (Typed.Ident.t * Syntax.Type_expr.t) list
    ; result_annot : Syntax.Type_expr.t option
    ; res_ty : Type.ty
    ; ty : Type.ty
    }
end

let function_type
      t
      (scope : Scope.t)
      ~(args : (Source.Binder.t * Syntax.Type_expr.t option) list)
      ~annot
  =
  let%bind.Result () =
    check_no_duplicates
      (List.filter_map args ~f:(fun ((binder : Source.Binder.t), _) ->
         match binder with
         | Name name when not (String.equal name.txt "_") -> Some name
         | Name _ | Ident _ -> None))
      ~error:(fun name -> Duplicate_parameter name)
  in
  let annot_type = function
    | None -> Ok (Scope.fresh_ty t scope, None)
    | Some annot ->
      let%map.Result ty, resolved = Scope.elaborate_resolved scope annot in
      ty, Some resolved
  in
  let%bind.Result args =
    List.map args ~f:(fun (binder, annot) ->
      let%map.Result ty, resolved = annot_type annot in
      binder, ty, resolved)
    |> Result.all
  in
  let%map.Result res_ty, result_annot = annot_type annot in
  let ty =
    List.fold_right args ~init:res_ty ~f:(fun (_, arg_ty, _) ty ->
      Type.TArrow (arg_ty, ty))
  in
  let args, annots =
    List.map args ~f:(fun (binder, ty, resolved) ->
      let ident = Program_env.bind scope.program binder ty ~level:scope.level in
      (ident, ty), Option.map resolved ~f:(fun resolved -> ident, resolved))
    |> List.unzip
  in
  { Function_type.args
  ; annots = List.filter_opt annots
  ; result_annot
  ; res_ty
  ; ty
  }
;;

let constructor_ref (constructor : Type_env.Constructor.t) =
  { Typed.Constructor_ref.type_name = constructor.type_name
  ; name = constructor.name
  ; index = constructor.index
  }
;;

let field_ref (field : Type_env.Field.t) =
  { Typed.Field_ref.record = field.record_type; index = field.index }
;;

(* Type-directed lookup: the declared type a constructor or field is known to
   be of, by its canonical name, and its members. *)
module Known = struct
  type 'member t =
    { type_name : string
    ; members : 'member list
    }

  let find
        (scope : Scope.t)
        (ty : Type.ty option)
        ~(members : Type_env.t -> string -> ('m list option, _) Result.t)
    =
    match Option.map ty ~f:Type.canonical_ty with
    | Some (TCon (type_name, _)) ->
      let%map.Result members = members scope.program.type_env type_name in
      Option.map members ~f:(fun members -> { type_name; members })
    | Some _ | None -> Ok None
  ;;

  let record scope ty = find scope ty ~members:Type_env.record_fields
  let variant scope ty = find scope ty ~members:Type_env.variant_constructors

  (* Only an unqualified name is looked up in the known type: a qualified one
     or a ref names its declaration. *)
  let unqualified : Syntax.Decl_path.t Located.t -> string option = function
    | { txt = Path path; loc = _ } ->
      (match (path :> string list) with
       | [ name ] -> Some name
       | _ -> None)
    | { txt = Root _ | Resolved _; loc = _ } -> None
  ;;

  let unqualified_field : Source.Field.t -> string option = function
    | Path path -> unqualified path
    | Ref _ -> None
  ;;

  let has t name ~member_name =
    List.exists t.members ~f:(fun member ->
      String.equal (Prelude_path.short_name (member_name member)) name)
  ;;

  let member t ~name ~member_name ~loc ~missing =
    match
      List.find t.members ~f:(fun member ->
        String.equal (Prelude_path.short_name (member_name member)) name)
    with
    | Some member -> Ok member
    | None -> error ~loc (missing ~type_name:t.type_name name)
  ;;
end

let find_constructor (scope : Scope.t) ~loc ~known : Source.Constructor.t -> _
  = function
  | Path path ->
    (match Known.unqualified path, known with
     | Some name, Some (known : _ Known.t) ->
       Known.member
         known
         ~name
         ~member_name:(fun (constructor : Type_env.Constructor.t) ->
           constructor.name)
         ~loc:path.loc
         ~missing:(fun ~type_name constructor ->
           No_such_constructor { type_name; constructor })
     | _ -> Type_env.find_constructor scope.program.type_env scope.module_ path)
  | Ref { name; _ } -> Type_env.constructor scope.program.type_env name ~loc
;;

(* Generated code's fields are at [loc], its node's. *)
let field_loc ~loc : Source.Field.t -> Loc.t = function
  | Path path -> path.loc
  | Ref _ -> loc
;;

let find_field (scope : Scope.t) ~loc ~known (field : Source.Field.t) =
  match field with
  | Path path ->
    (match Known.unqualified path, known with
     | Some name, Some (known : _ Known.t) ->
       Known.member
         known
         ~name
         ~member_name:Type_env.Field.name
         ~loc:path.loc
         ~missing:(fun ~type_name field -> No_such_field { type_name; field })
     | _ -> Type_env.find_field scope.program.type_env scope.module_ path)
  | Ref field ->
    Type_env.field scope.program.type_env (Typed.Field_ref.name field) ~loc
;;

(* Unifies [ty], a fresh instance of a declared type, with [expected] if that
   is known to be the same type, so that what is inside is known too. As
   [expected] is always unified with what has [ty] later, it fails only where
   that would. *)
let unify_known t ~expected ty ~loc =
  match Option.map expected ~f:Type.canonical_ty, Type.canonical_ty ty with
  | Some (TCon (known, _) as expected), TCon (name, _)
    when String.equal known name ->
    Unify.unify_ty t ~ty1:ty ~ty2:expected |> lift ~loc
  | _ -> Ok ()
;;

(* Pairs each of [args] with its instantiated type, along with the
   constructor and the result type. Several [args] of a constructor declared
   with one are a tuple ([tuple]), as in OCaml. *)
let constructor_types
      t
      (scope : Scope.t)
      constructor
      ~args
      ~tuple
      ~expected
      ~loc
  =
  let%bind.Result known = Known.variant scope expected in
  let%bind.Result (constructor : Type_env.Constructor.t) =
    find_constructor scope constructor ~loc ~known
  in
  let args =
    match args, constructor.args with
    | _ :: _ :: _, [ _ ] -> [ tuple args ]
    | _ -> args
  in
  match List.zip args constructor.args with
  | Unequal_lengths ->
    error
      ~loc
      (Constructor_arity_mismatch
         { constructor = constructor.name
         ; expected = List.length constructor.args
         ; got = List.length args
         })
  | Ok args ->
    let inst = Scope.instantiate t scope in
    let result = inst constructor.result in
    let%map.Result () = unify_known t ~expected result ~loc in
    ( constructor_ref constructor
    , List.map args ~f:(fun (arg, ty) -> arg, inst ty)
    , result )
;;

(* The record type [fields] (not empty) are of: [expected] if it is known to
   be a record type, else that of the first qualified field (or ref), else the
   first of the unqualified fields' types in scope that has all of them. *)
let record_type (scope : Scope.t) fields ~expected ~loc =
  let of_field field =
    let%bind.Result (field : Type_env.Field.t) =
      find_field scope field ~loc ~known:None
    in
    let%map.Result known = Known.record scope (Some field.record) in
    Option.value_exn known
  in
  match%bind.Result Known.record scope expected with
  | Some known -> Ok known
  | None ->
    (match
       List.find fields ~f:(fun (field, _) ->
         Option.is_none (Known.unqualified_field field))
     with
     | Some (field, _) -> of_field field
     | None ->
       let names =
         List.filter_map fields ~f:(fun (field, _) ->
           Known.unqualified_field field)
       in
       let has_all known =
         List.for_all
           names
           ~f:(Known.has known ~member_name:Type_env.Field.name)
       in
       (match
          List.find_map fields ~f:(fun (field, _) ->
            match of_field field with
            | Ok known when has_all known -> Some known
            | Ok _ | Error _ -> None)
        with
        | Some known -> Ok known
        | None -> of_field (fst (List.hd_exn fields))))
;;

let is_given fields (member : Type_env.Field.t) =
  List.exists fields ~f:(fun ((field : Type_env.Field.t), _, _) ->
    field.index = member.index)
;;

(* The record type of [fields], and each field with its location and its
   [x]. *)
let resolve_record_fields (scope : Scope.t) fields ~all_required ~expected ~loc =
  let%bind.Result () =
    if List.is_empty fields then error ~loc Empty_record else Ok ()
  in
  let%bind.Result (known : Type_env.Field.t Known.t) =
    record_type scope fields ~expected ~loc
  in
  let find (field, x) =
    let%bind.Result (found : Type_env.Field.t) =
      find_field scope field ~loc ~known:(Some known)
    in
    let loc = field_loc field ~loc in
    if String.equal found.record_type.name known.type_name
    then Ok (found, loc, x)
    else
      error
        ~loc
        (Fields_of_different_types
           { field = Type_env.Field.name found
           ; expected_type = known.type_name
           ; actual_type = found.record_type.name
           })
  in
  (* A qualified field of another type is the error, rather than an
     unqualified one the type lacks. *)
  let%bind.Result (_ : _ list) =
    List.filter fields ~f:(fun (field, _) ->
      Option.is_none (Known.unqualified_field field))
    |> List.map ~f:find
    |> Result.all
  in
  let%bind.Result fields = List.map fields ~f:find |> Result.all in
  let%bind.Result () =
    check_no_duplicates
      (List.map fields ~f:(fun (field, loc, _) ->
         { Located.txt = Prelude_path.short_name (Type_env.Field.name field)
         ; loc
         }))
      ~error:(fun name -> Repeated_field name)
  in
  let%map.Result () =
    match List.find known.members ~f:(Fn.non (is_given fields)) with
    | Some member when all_required ->
      error ~loc (Missing_field (Type_env.Field.name member))
    | Some _ | None -> Ok ()
  in
  known, fields
;;

let declared_record (known : Type_env.Field.t Known.t) =
  (List.hd_exn known.members).record
;;

(* Returns the instantiated record type, and each field with its [x] paired
   with its type. *)
let record_fields t (scope : Scope.t) fields ~all_required ~expected ~loc =
  let%bind.Result known, fields =
    resolve_record_fields scope fields ~all_required ~expected ~loc
  in
  let inst = Scope.instantiate t scope in
  let record = inst (declared_record known) in
  let%map.Result () = unify_known t ~expected record ~loc in
  let fields =
    List.map fields ~f:(fun ((field : Type_env.Field.t), _, x) ->
      field_ref field, (x, inst field.ty))
  in
  record, fields
;;

(* Returns the field, the instantiated record type and the field's type. *)
let field_type t (scope : Scope.t) field ~record ~loc =
  let%bind.Result known = Known.record scope record in
  let%map.Result (field : Type_env.Field.t) =
    find_field scope field ~loc ~known
  in
  let inst = Scope.instantiate t scope in
  let ty = inst field.ty in
  field_ref field, inst field.record, ty
;;

(* Rows of polymorphic records and variants, whose entries are [Present]. *)
module Poly_row = struct
  let present entries ~tail =
    List.fold_right entries ~init:tail ~f:(fun (label, ty) rest ->
      Type.RExtend (label, Present, ty, rest))
  ;;

  (* [entries] before a fresh tail, which is also returned. *)
  let open_ t scope entries =
    let tail = Scope.fresh_row t scope in
    present entries ~tail, tail
  ;;

  let variant t scope ~tag ~arg =
    Fresh.variant t (fst (open_ t scope [ tag, arg ]))
  ;;

  let check_distinct_labels entries =
    check_no_duplicates (List.map entries ~f:fst) ~error:(fun label ->
      Duplicate_row_entry label)
  ;;
end

module Pattern_var = struct
  type t =
    { ident : Typed.Ident.t
    ; ty : Type.ty
    ; loc : Loc.t
    }

  let bindings = List.map ~f:(fun t -> t.ident, t.ty)
end

(* The components of [expected], if it is known to be a tuple of [n]. *)
let tuple_components (expected : Type.ty option) n =
  match Option.map expected ~f:Type.canonical_ty with
  | Some (TTuple tys) when List.length tys = n -> List.map tys ~f:Option.some
  | Some _ | None -> List.init n ~f:(fun _ -> None)
;;

(* The type of [label] in [expected], if it is known to be a polymorphic
   record ([`Record]) or variant ([`Variant]) with it. *)
let row_entry (expected : Type.ty option) kind ~label =
  let rec find (row : Type.row) =
    match Type.canonical_row row with
    | RExtend (label', _, ty, rest) ->
      if String.equal label label' then Some ty else find rest
    | REmpty | RVar _ -> None
  in
  match Option.map expected ~f:Type.canonical_ty, kind with
  | Some (TRecord { row; _ }), `Record | Some (TVariant { row; _ }), `Variant ->
    find row
  | _ -> None
;;

(* [ty] if it is known, else [fallback]. *)
let either_known ty fallback =
  match Type.canonical_ty ty with
  | TVar _ -> fallback
  | _ -> Some ty
;;

(* [expected] is the type the pattern or expression is known to have where it
   is (it is not unified with it here): constructors and fields are looked up
   in it when it is a nominal type (see [Known]). *)
let rec pattern_type ?expected t (scope : Scope.t) ~(pattern : Source.Pattern.t)
  : (Typed.Pattern.t * Pattern_var.t list, Typecheck_error.t) Result.t
  =
  let loc = Source.Pattern.loc pattern in
  let node desc ty = { Typed.Pattern.desc; ty; loc } in
  let bind binder ty =
    let ident = Program_env.bind scope.program binder ty ~level:scope.level in
    ( ident
    , { Pattern_var.ident; ty; loc = Source.Binder.loc binder ~enclosing:loc } )
  in
  (* Each pattern of type [ty], known to be of [expected] (by default
     [ty]). *)
  let sub_patterns ?expected patterns =
    let expected =
      Option.value
        expected
        ~default:(List.map patterns ~f:(fun (_, ty) -> Some ty))
    in
    let%map.Result typed, bindings =
      List.fold_result
        (List.zip_exn patterns expected)
        ~init:([], [])
        ~f:(fun (typed, bindings) ((pattern, ty), expected) ->
          let%bind.Result pattern, bindings' =
            pattern_type t scope ~pattern ?expected
          in
          let%map.Result () =
            Unify.unify_ty t ~ty1:ty ~ty2:pattern.ty |> lift ~loc:pattern.loc
          in
          pattern :: typed, bindings @ bindings')
    in
    List.rev typed, bindings
  in
  match Source.Pattern.view pattern with
  | Any -> Ok (node Any (Scope.fresh_ty t scope), [])
  | Var binder ->
    let ty = Scope.fresh_ty t scope in
    let ident, var = bind binder ty in
    Ok (node (Var ident) ty, [ var ])
  | Lit lit -> Ok (node (Lit lit) (Syntax.Lit.ty lit), [])
  | Tuple patterns ->
    let types = List.map patterns ~f:(fun _ -> Scope.fresh_ty t scope) in
    let%map.Result patterns, bindings =
      sub_patterns
        (List.zip_exn patterns types)
        ~expected:(tuple_components expected (List.length patterns))
    in
    node (Tuple patterns) (Type.TTuple types), bindings
  | Construct (constructor, args) ->
    let%bind.Result constructor, args, result =
      constructor_types
        t
        scope
        constructor
        ~args
        ~tuple:Source.Pattern.tuple
        ~expected
        ~loc
    in
    let%map.Result args, bindings = sub_patterns args in
    node (Construct (constructor, args)) result, bindings
  | Record fields ->
    let%bind.Result record, fields =
      record_fields t scope fields ~all_required:false ~expected ~loc
    in
    let%map.Result patterns, bindings = sub_patterns (List.map fields ~f:snd) in
    ( node (Record (List.zip_exn (List.map fields ~f:fst) patterns)) record
    , bindings )
  | Poly_variant (tag, arg) ->
    let%map.Result arg, bindings =
      match arg with
      | None -> Ok (None, [])
      | Some pattern ->
        let%map.Result pattern, bindings =
          pattern_type
            t
            scope
            ~pattern
            ?expected:(row_entry expected `Variant ~label:tag)
        in
        Some pattern, bindings
    in
    let arg_ty =
      Option.value_map arg ~default:Type.unit ~f:(fun pattern -> pattern.ty)
    in
    ( node (Poly_variant (tag, arg)) (Poly_row.variant t scope ~tag ~arg:arg_ty)
    , bindings )
  | Poly_record { fields; rest } ->
    let%bind.Result () = Poly_row.check_distinct_labels fields in
    let%map.Result fields, bindings =
      List.fold_result
        fields
        ~init:([], [])
        ~f:(fun (fields, bindings) (label, pattern) ->
          let%map.Result pattern, bindings' =
            pattern_type
              t
              scope
              ~pattern
              ?expected:(row_entry expected `Record ~label:label.txt)
          in
          (label.txt, pattern) :: fields, bindings @ bindings')
    in
    let fields = List.rev fields in
    let tail, rest, rest_bindings =
      match rest with
      | Closed -> Type.REmpty, Typed.Pattern.Rest.Closed, []
      | Open -> Scope.fresh_row t scope, Open, []
      | Bind binder ->
        let tail = Scope.fresh_row t scope in
        let ident, var = bind binder (Fresh.record t tail) in
        tail, Bind ident, [ var ]
    in
    let row =
      Poly_row.present
        (List.map fields ~f:(fun (label, (pattern : Typed.Pattern.t)) ->
           label, pattern.ty))
        ~tail
    in
    ( node (Poly_record { fields; rest }) (Fresh.record t row)
    , bindings @ rest_bindings )
  | Exception _ -> error ~loc Misplaced_exception_pattern
;;

(* Closing of the scrutinee and residuals of catch-alls in matches on
   polymorphic variants. *)
module Variant_match = struct
  (* The tags handled irrefutably by the cases so far, in order, each once. *)
  type t = string list

  let empty = []

  (* A top level variable pattern matches what the handled tags' cases have
     not: the scrutinee without their first entries. *)
  let pattern_type
        t
        (scope : Scope.t)
        handled
        ~(pattern : Source.Pattern.t)
        ~scrutinee
    =
    match Source.Pattern.view pattern, handled with
    | Var binder, _ :: _ ->
      let row, rest =
        Poly_row.open_
          t
          scope
          (List.map handled ~f:(fun tag -> tag, Scope.fresh_ty t scope))
      in
      let rest = Fresh.variant t rest in
      let ident =
        Program_env.bind scope.program binder rest ~level:scope.level
      in
      Ok
        ( { Typed.Pattern.desc = Var ident
          ; ty = Fresh.variant t row
          ; loc = Source.Pattern.loc pattern
          }
        , [ { Pattern_var.ident
            ; ty = rest
            ; loc =
                Source.Binder.loc binder ~enclosing:(Source.Pattern.loc pattern)
            }
          ] )
    | _ -> pattern_type t scope ~pattern ~expected:scrutinee
  ;;

  let add_case handled ({ desc; ty = _; loc = _ } : Typed.Pattern.t) =
    match desc with
    | Poly_variant (tag, arg)
      when Option.for_all arg ~f:Typed.Pattern.is_irrefutable
           && not (List.mem handled tag ~equal:String.equal) ->
      handled @ [ tag ]
    | _ -> handled
  ;;

  let is_empty_nominal (scope : Scope.t) scrutinee =
    match Type.canonical_ty scrutinee with
    | TCon (name, _) -> Type_env.is_empty_variant scope.program.type_env name
    | _ -> Ok false
  ;;

  (* Without a top level catch-all, a variant scrutinee may only have the tags
     of the cases, and an empty match's none, unless the scrutinee is already
     known to be an empty nominal type. *)
  let close
        t
        (scope : Scope.t)
        ~scrutinee
        ~loc
        (patterns : Typed.Pattern.t list)
    =
    let patterns =
      List.map patterns ~f:(fun (pattern : Typed.Pattern.t) -> pattern.desc)
    in
    let tags =
      List.filter_map patterns ~f:(function
        | Poly_variant (tag, _) -> Some tag
        | _ -> None)
      |> List.stable_dedup ~compare:String.compare
    in
    let has_catch_all =
      List.exists patterns ~f:(function
        | Var _ | Any -> true
        | _ -> false)
    in
    let%bind.Result open_ =
      match patterns with
      | [] -> is_empty_nominal scope scrutinee
      | _ :: _ -> Ok (has_catch_all || List.is_empty tags)
    in
    if open_
    then Ok ()
    else (
      let closed =
        Poly_row.present
          (List.map tags ~f:(fun tag -> tag, Scope.fresh_ty t scope))
          ~tail:REmpty
      in
      Unify.unify_ty t ~ty1:(Fresh.variant t closed) ~ty2:scrutinee |> lift ~loc)
  ;;
end

(* [name] is the context entry the variable is provided as, if it becomes a
   free variable of the quote: a local's name or a toplevel's canonical name. *)
let resolution_type t (scope : Scope.t) ~name ~toplevel ~loc : Resolution.t -> _
  = function
  | Local entry ->
    Ok (Scope.instantiate t scope entry.scheme, Typed.Var_ref.Bound entry.binder)
  | Outside_quote { usable = Some entry; _ } ->
    Ok (Scope.instantiate t scope entry.scheme, Persistent entry.binder)
  | Outside_quote { quote; usable = None; unusable } ->
    Option.iter unusable ~f:(fun entry ->
      Hashtbl.set
        scope.program.unusable_in_quotes
        ~key:name
        ~data:{ loc; var_level = entry.level; used_at = scope.level });
    let%map.Result ty =
      Unify.present_entry t ~row:quote.context ~name ~rank:quote.outside.rank
      |> lift ~loc
    in
    ty, if toplevel then Typed.Var_ref.Free_toplevel name else Free name
  | Unusable kind -> error ~loc kind
;;

let finish_scc t (program : Program_env.t) (members : Toplevel.t list) =
  let persistent = List.for_all members ~f:Toplevel.is_function in
  let recursive =
    List.exists members ~f:(fun member ->
      match member.state with
      | In_progress { recursive; _ } -> recursive
      | Unchecked | Done _ -> false)
  in
  (* Like OCaml's [let rec], a recursive non-function is not generalized. *)
  let generalize =
    List.for_all members ~f:(fun member ->
      Toplevel.is_function member
      ||
      match member.state with
      | In_progress { body = Some body; _ } -> Typed.Expr.is_value body
      | In_progress { body = None; _ } | Unchecked | Done _ -> false)
    && (persistent || not recursive)
  in
  if generalize
  then
    Scheme.generalize
      t
      ~rank:0
      (List.map members ~f:(fun member ->
         match member.state with
         | In_progress { ty; _ } -> ty
         | Unchecked | Done _ ->
           raise_s
             [%message "finish_scc: member not checked" (member : Toplevel.t)]));
  let members =
    List.map members ~f:(fun member ->
      match member.state with
      | In_progress { index; ty; args; body = Some body; _ } ->
        Program_env.add_info program member.ident ~ty ~level:0;
        let typed =
          { Typed.Toplevel.ident = member.ident; args; scheme = ty; body }
        in
        member.state
        <- Done
             { entry =
                 Env.Entry.toplevel ~ident:member.ident ~scheme:ty ~persistent
             ; typed
             };
        index, typed
      | In_progress { body = None; _ } | Unchecked | Done _ ->
        raise_s
          [%message "finish_scc: member not checked" (member : Toplevel.t)])
    |> List.sort ~compare:(Comparable.lift Int.compare ~f:fst)
    |> List.map ~f:snd
  in
  let idents =
    Typed.Ident.Set.of_list
      (List.map members ~f:(fun (member : Typed.Toplevel.t) -> member.ident))
  in
  let scc =
    { Typed.Scc.members
    ; recursive =
        List.exists members ~f:(fun member ->
          Typed.Expr.refers_to member.body ~f:(function
            | Toplevel ident -> Set.mem idents ident
            | Local _ -> false))
    }
  in
  Queue.enqueue program.sccs scc;
  Treewalk.add_scc program.interpreter scc
;;

let intrinsic_type t scope intrinsic =
  Intrinsic.ty
    intrinsic
    ~var:(fun () -> Scope.fresh_ty t scope)
    ~row:(fun () -> Scope.fresh_row t scope)
;;

let rec var_type t (scope : Scope.t) ~(path : Syntax.Decl_path.t) ~loc =
  let resolve ~name entry =
    resolution_type
      t
      scope
      ~name
      ~toplevel:false
      ~loc
      (Resolution.of_entry scope ~name entry)
  in
  let local =
    match path with
    | Path path ->
      (match (path :> string list) with
       | [ name ] ->
         Env.find scope.locals name |> Option.map ~f:(fun entry -> name, entry)
       | _ -> None)
    | Root _ | Resolved _ -> None
  in
  match local with
  | Some (name, entry) -> resolve ~name (Some entry)
  | None ->
    (match%bind.Result Module_scope.find_value scope.module_ path ~loc with
     | Toplevel name ->
       toplevel_type t scope (Program_env.toplevel scope.program name) ~loc
     | Prim prim -> Ok (Prim.ty prim, Typed.Var_ref.Prim prim)
     | Intrinsic intrinsic ->
       Ok (intrinsic_type t scope intrinsic, Typed.Var_ref.Intrinsic intrinsic)
     | Unbound ->
       (match scope.quote with
        | Some _ -> resolve ~name:(Syntax.Decl_path.to_string path) None
        | None -> Error (Module_scope.unbound_value scope.module_ path ~loc)))

and toplevel_type t scope (toplevel : Toplevel.t) ~loc =
  let%bind.Result entry = toplevel_entry t scope toplevel ~loc in
  let name = toplevel.ident.name in
  resolution_type
    t
    scope
    ~name
    ~toplevel:true
    ~loc
    (Resolution.of_entry scope ~name (Some entry))

(* A [Stag.Value_ref.t]'s canonical name, resolved where the code it was
   erased from was checked, so not looked up in [scope]. *)
and resolved_value_type t (scope : Scope.t) name ~loc =
  match
    Prim.of_canonical_name name, Program_env.find_toplevel scope.program name
  with
  | Some prim, _ -> Ok (Prim.ty prim, Typed.Var_ref.Prim prim)
  | None, Some toplevel -> toplevel_type t scope toplevel ~loc
  | None, None -> error ~loc (Not_in_scope (Path (Syntax.Path.of_string name)))

(* Generated code's variables are already resolved, so are found by binder
   rather than by name, which may be shadowed. *)
and var_ref_type t (scope : Scope.t) (var_ref : Typed.Var_ref.t) ~loc =
  let resolve ~name ~toplevel entry =
    resolution_type
      t
      scope
      ~name
      ~toplevel
      ~loc
      (Resolution.of_entry scope ~name (Some entry))
  in
  let not_in_scope name =
    error ~loc (Not_in_scope (Path (Syntax.Path.of_string name)))
  in
  match var_ref with
  | Prim prim -> Ok (Prim.ty prim, var_ref)
  | Intrinsic intrinsic -> Ok (intrinsic_type t scope intrinsic, var_ref)
  | (Free name | Free_toplevel name) as var_ref ->
    (match scope.quote with
     | Some quote ->
       resolution_type
         t
         scope
         ~name
         ~toplevel:
           (match var_ref with
            | Free_toplevel _ -> true
            | _ -> false)
         ~loc
         (Outside_quote { quote; usable = None; unusable = None })
     | None -> not_in_scope name)
  | Bound (Toplevel ident) | Persistent (Toplevel ident) ->
    let%bind.Result entry =
      toplevel_entry
        t
        scope
        (Program_env.toplevel scope.program ident.name)
        ~loc
    in
    resolve ~name:ident.name ~toplevel:true entry
  | Bound (Local ident as binder) | Persistent (Local ident as binder) ->
    (match Env.find_binder scope.locals binder ~name:ident.name with
     | Some entry -> resolve ~name:ident.name ~toplevel:false entry
     | None ->
       (match Program_env.embedded scope.program ident with
        | Some info ->
          Ok (Scope.instantiate t scope info.ty, Typed.Var_ref.Persistent binder)
        | None -> not_in_scope ident.name))

(* Toplevels may be used from code run at compile time, as if bound at its
   level, once they can be evaluated. *)
and toplevel_entry t (scope : Scope.t) (toplevel : Toplevel.t) ~loc =
  let at_scope_level (entry : Env.Entry.t) =
    { entry with level = Int.min entry.level scope.level }
  in
  match toplevel.state with
  | Done { entry; _ } -> Ok (at_scope_level entry)
  | In_progress in_progress ->
    let entry =
      Env.Entry.toplevel
        ~ident:toplevel.ident
        ~scheme:in_progress.ty
        ~persistent:false
    in
    (match scope.quote with
     | Some _ ->
       (* Not persistent, so a free variable of the quote: the quote's value
          doesn't depend on [toplevel]. *)
       Ok (at_scope_level entry)
     | None when scope.level < 0 ->
       error
         ~loc
         (Compile_time_use_of_toplevel_being_checked toplevel.ident.name)
     | None ->
       (* [toplevel] is in the component being checked, so this is a
          recursive reference. *)
       in_progress.recursive <- true;
       scope.scc.lowlink <- Int.min scope.scc.lowlink in_progress.index;
       Ok entry)
  | Unchecked
    when Option.is_some scope.quote && not (Toplevel.is_function toplevel) ->
    (* A free variable of the quote, like an [In_progress] toplevel. A function
       is checked, as it is persistent once its component is. *)
    Ok
      (at_scope_level
         (Env.Entry.toplevel
            ~ident:toplevel.ident
            ~scheme:(Scope.fresh_ty t scope)
            ~persistent:false))
  | Unchecked ->
    let%bind.Result scc = check_toplevel t scope.program toplevel in
    scope.scc.lowlink <- Int.min scope.scc.lowlink scc.lowlink;
    scope.scc.pending <- scc.pending @ scope.scc.pending;
    toplevel_entry t scope toplevel ~loc

and check_toplevel t program (toplevel : Toplevel.t)
  : (Scc_frame.t, Typecheck_error.t) Result.t
  =
  Generated.wrap_result
    toplevel.generated
    (check_toplevel_unwrapped t program toplevel)
  |> Result.map_error ~f:(Module_scope.within toplevel.module_)

and check_toplevel_unwrapped t program (toplevel : Toplevel.t) =
  let index = Fresh.id t in
  let scc = { Scc_frame.lowlink = index; pending = [ toplevel ] } in
  let unfinished = Stack.length program.unfinished in
  let rank = 1 in
  let scope =
    { Scope.program
    ; level = 0
    ; rank
    ; locals = Env.create ()
    ; quote = None
    ; module_ = toplevel.module_
    ; scc
    ; annotation_vars = Type_env.Annotation_vars.create t ~rank
    ; in_expect_test = false
    }
  in
  let%bind.Result { args; res_ty; ty; annots = _; result_annot = _ } =
    function_type
      t
      scope
      ~args:
        (List.map toplevel.args ~f:(fun (name, annot) ->
           Source.Binder.Name name, annot))
      ~annot:toplevel.annot
  in
  Stack.push program.unfinished ty;
  toplevel.state
  <- In_progress
       { index
       ; ty
       ; args = List.map args ~f:fst
       ; body = None
       ; recursive = false
       };
  let%map.Result body =
    check_body t scope ~args ~res_ty ~body:(Source.Expr.Syntax toplevel.expr)
  in
  (match toplevel.state with
   | In_progress in_progress -> in_progress.body <- Some body
   | Unchecked | Done _ ->
     raise_s
       [%message "check_toplevel: not in progress" (toplevel : Toplevel.t)]);
  if scc.lowlink = index
  then (
    finish_scc t program scc.pending;
    scc.pending <- [];
    while Stack.length program.unfinished > unfinished do
      Unify.lower_ty ~rank:0 (Stack.pop_exn program.unfinished)
    done);
  scc

and check_body t (scope : Scope.t) ~args ~res_ty ~body =
  with_monomorphic_bindings scope args ~f:(fun () ->
    check_expr t scope ~expr:body ~ty:res_ty)

and with_monomorphic_bindings (scope : Scope.t) bindings ~f =
  Env.with_bindings
    scope.locals
    (List.map bindings ~f:(fun ((ident : Typed.Ident.t), ty) ->
       ident.name, Scope.entry scope ~ident ~scheme:ty ~persistent:false))
    ~f

and expr_type ?expected t (scope : Scope.t) ~(expr : Source.Expr.t)
  : (Typed.Expr.t, Typecheck_error.t) Result.t
  =
  let loc = Source.Expr.loc expr in
  let node desc ty = { Typed.Expr.desc; ty; loc } in
  let tys = List.map ~f:(fun (expr : Typed.Expr.t) -> expr.ty) in
  let labelled_tys =
    List.map ~f:(fun (label, (expr : Typed.Expr.t)) -> label, expr.ty)
  in
  match Source.Expr.view expr with
  | Lit l -> Ok (node (Lit l) (Syntax.Lit.ty l))
  | Expect expected ->
    (* Only where it runs as part of the test: not at compile time nor in
       code. *)
    if scope.in_expect_test && scope.level = 0 && Option.is_none scope.quote
    then Ok (node (Expect expected) Type.unit)
    else error ~loc Expect_outside_expect_test
  | Type ty ->
    let%map.Result elaborated, resolved =
      Type_env.elaborate
        scope.program.type_env
        scope.module_
        (Type_env.Annotation_vars.create t ~rank:scope.rank)
        ty
    in
    node
      (Type resolved)
      (TCon (Prelude_path.canonical "Stag.Type.t", [ ATy elaborated ]))
  | Var (Path (path, annot)) ->
    let%bind.Result ty, var_ref =
      match path with
      | Path _ | Root _ -> var_type t scope ~path ~loc
      | Resolved name -> resolved_value_type t scope name ~loc
    in
    (match annot with
     | None -> Ok (node (Var var_ref) ty)
     | Some annot ->
       let%bind.Result annot_ty, resolved =
         Scope.elaborate_resolved scope annot
       in
       let%map.Result () =
         Unify.unify_ty t ~ty1:ty ~ty2:annot_ty |> lift ~loc
       in
       node
         (Annotated ({ Typed.Expr.desc = Var var_ref; ty; loc }, resolved))
         ty)
  | Var (Ref var_ref) ->
    let%map.Result ty, var_ref = var_ref_type t scope var_ref ~loc in
    node (Var var_ref) ty
  | App (f, x) ->
    let a = Scope.fresh_ty t scope in
    let b = Scope.fresh_ty t scope in
    let%bind.Result f = check_expr t scope ~expr:f ~ty:(TArrow (a, b)) in
    let%map.Result x = check_expr t scope ~expr:x ~ty:a in
    node (App (f, x)) b
  | Let { binder; args; annot; body; in_ } ->
    let inner = { scope with rank = scope.rank + 1 } in
    let%bind.Result { args = arg_types; annots; result_annot; res_ty; ty } =
      function_type t inner ~args ~annot
    in
    let ident = Program_env.bind scope.program binder ty ~level:scope.level in
    let name = Source.Binder.name binder in
    let%bind.Result body =
      Env.with_bindings
        scope.locals
        [ name, Scope.entry scope ~ident ~scheme:ty ~persistent:false ]
        ~f:(fun () -> check_body t inner ~args:arg_types ~res_ty ~body)
    in
    let persistent = not (List.is_empty args) in
    let args = List.map arg_types ~f:fst in
    let generalized = Typed.Expr.binding_is_value ~ident ~args ~body in
    if generalized
    then Scheme.generalize t ~rank:scope.rank [ ty ]
    else Unify.lower_ty ~rank:scope.rank ty;
    let%map.Result in_ =
      Env.with_bindings
        scope.locals
        [ name, Scope.entry scope ~ident ~scheme:ty ~persistent ]
        ~f:(fun () -> expr_type t scope ~expr:in_ ?expected)
    in
    node
      (Let { ident; args; annots; result_annot; body; in_; generalized })
      in_.ty
  | Fun { args; body } ->
    let%bind.Result { args; annots; result_annot = _; res_ty; ty } =
      function_type t scope ~args ~annot:None
    in
    let%map.Result body = check_body t scope ~args ~res_ty ~body in
    node (Fun { args = List.map args ~f:fst; annots; body }) ty
  | Quote expr ->
    let quote =
      { Scope.id = Fresh.id t
      ; context = Scope.fresh_row t scope
      ; outside = scope
      }
    in
    let expected =
      match Option.map expected ~f:Type.canonical_ty with
      | Some (TCode { inner; context = _ }) -> Some inner
      | Some _ | None -> None
    in
    let%map.Result inner =
      expr_type
        t
        { scope with level = scope.level + 1; quote = Some quote }
        ~expr
        ?expected
    in
    node (Quote inner) (TCode { inner = inner.ty; context = quote.context })
  | Splice { code; subs } ->
    (match scope.quote, expr with
     | None, Generated _ ->
       raise_s [%message "Generated code has a splice outside any quote"]
     | None, Syntax _ | Some _, _ -> ());
    let outside : Scope.t =
      match scope.quote with
      | Some quote -> { quote.outside with rank = scope.rank }
      | None -> { scope with level = scope.level - 1 }
    in
    let inner = Scope.fresh_ty t scope in
    let context = Scope.fresh_row t scope in
    let%bind.Result code =
      check_expr
        t
        outside
        ~expr:code
        ~ty:(TCode { inner; context })
        ?expected:
          (Option.map expected ~f:(fun inner ->
             Type.TCode { inner; context = Scope.fresh_row t outside }))
    in
    let%bind.Result subs =
      match subs with
      | Implicit ->
        let%map.Result captures =
          substitute_from_scope t scope ~context ~loc ~may_capture:(fun _ _ ->
            true)
        in
        Typed.Expr.Subs.Implicit captures
      | Providers providers ->
        let%map.Result captures =
          substitute_from_scope
            t
            scope
            ~context
            ~loc
            ~may_capture:(fun name binder ->
              [%equal: Typed.Binder.t option]
                (Map.find providers name)
                (Some binder))
        in
        Typed.Expr.Subs.Implicit captures
      | Explicit subs ->
        let%map.Result subs =
          substitute_explicitly t scope ~context ~subs ~loc
        in
        Typed.Expr.Subs.Explicit subs
    in
    (match scope.quote with
     | Some _ -> Ok (node (Splice { code; subs }) inner)
     | None ->
       let%map.Result expansion = expand t scope ~code ~subs ~ty:inner ~loc in
       node (Toplevel_splice { code; expansion }) inner)
  | Tuple exprs ->
    let%map.Result exprs =
      List.map2_exn
        exprs
        (tuple_components expected (List.length exprs))
        ~f:(fun expr expected -> expr_type t scope ~expr ?expected)
      |> Result.all
    in
    node (Tuple exprs) (Type.TTuple (tys exprs))
  | Construct (constructor, args) ->
    let%bind.Result constructor, args, result =
      constructor_types
        t
        scope
        constructor
        ~args
        ~tuple:Source.Expr.tuple
        ~expected
        ~loc
    in
    let%map.Result args = check_exprs t scope args in
    node (Construct (constructor, args)) result
  | Record fields ->
    let%bind.Result record, fields =
      record_fields t scope fields ~all_required:true ~expected ~loc
    in
    let%map.Result exprs = check_exprs t scope (List.map fields ~f:snd) in
    node (Record (List.zip_exn (List.map fields ~f:fst) exprs)) record
  | Field (expr, field) when Option.is_some (Known.unqualified_field field) ->
    let%bind.Result expr = expr_type t scope ~expr in
    let%bind.Result field, record, field_ty =
      field_type t scope field ~record:(Some expr.ty) ~loc
    in
    let%map.Result () =
      Unify.unify_ty t ~ty1:record ~ty2:expr.ty |> lift ~loc:expr.loc
    in
    node (Field (expr, field)) field_ty
  | Field (expr, field) ->
    let%bind.Result field, record, field_ty =
      field_type t scope field ~record:None ~loc
    in
    let%map.Result expr = check_expr t scope ~expr ~ty:record in
    node (Field (expr, field)) field_ty
  | Record_update (expr, fields) ->
    (* As in OCaml, the result's type parameters are those of [expr]'s type
       but for the ones only in the updated fields' types. *)
    let%bind.Result known_expected = Known.record scope expected in
    let%bind.Result expr =
      expr_type
        t
        scope
        ~expr
        ?expected:
          (Option.map known_expected ~f:(fun known ->
             Scope.instantiate t scope (declared_record known)))
    in
    let%bind.Result known, fields =
      resolve_record_fields
        scope
        fields
        ~all_required:false
        ~expected:(either_known expr.ty expected)
        ~loc
    in
    let inst_in = Scope.instantiate t scope in
    let inst_out = Scope.instantiate t scope in
    let%bind.Result () =
      Unify.unify_ty t ~ty1:(inst_in (declared_record known)) ~ty2:expr.ty
      |> lift ~loc:expr.loc
    in
    let record = inst_out (declared_record known) in
    let%bind.Result () = unify_known t ~expected record ~loc in
    let%bind.Result () =
      List.filter known.members ~f:(Fn.non (is_given fields))
      |> List.fold_result ~init:() ~f:(fun () (member : Type_env.Field.t) ->
        Unify.unify_ty t ~ty1:(inst_in member.ty) ~ty2:(inst_out member.ty)
        |> lift ~loc)
    in
    let%map.Result exprs =
      check_exprs
        t
        scope
        (List.map fields ~f:(fun ((field : Type_env.Field.t), _, expr) ->
           expr, inst_out field.ty))
    in
    node
      (Record_update
         ( expr
         , List.zip_exn
             (List.map fields ~f:(fun (field, _, _) -> field_ref field))
             exprs ))
      record
  | Match { scrutinee = expr; cases; exception_cases } ->
    let%bind.Result scrutinee = expr_type t scope ~expr in
    let result = Scope.fresh_ty t scope in
    (* A case of [pattern], typed with its [bindings], of type [ty]. *)
    let case ~ty ((pattern : Typed.Pattern.t), bindings) body =
      let%bind.Result () =
        check_no_duplicates
          (List.map bindings ~f:(fun (var : Pattern_var.t) ->
             { Located.txt = var.ident.name; loc = var.loc }))
          ~error:(fun name -> Duplicate_pattern_variable name)
      in
      let%bind.Result () =
        Unify.unify_ty t ~ty1:ty ~ty2:pattern.Typed.Pattern.ty
        |> lift ~loc:pattern.loc
      in
      let%map.Result body =
        with_monomorphic_bindings
          scope
          (Pattern_var.bindings bindings)
          ~f:(fun () ->
            check_expr
              t
              scope
              ~expr:body
              ~ty:result
              ?expected:(either_known result expected))
      in
      pattern, body
    in
    let%bind.Result () =
      match cases, exception_cases with
      | [], _ :: _ -> error ~loc Match_without_value_cases
      | _ -> Ok ()
    in
    let%bind.Result (_ : Variant_match.t), cases =
      List.fold_result
        cases
        ~init:(Variant_match.empty, [])
        ~f:(fun (handled, typed_cases) (pattern, body) ->
          let%bind.Result typed_pattern =
            Variant_match.pattern_type
              t
              scope
              handled
              ~pattern
              ~scrutinee:scrutinee.ty
          in
          let%map.Result ((pattern, _) as typed_case) =
            case ~ty:scrutinee.ty typed_pattern body
          in
          Variant_match.add_case handled pattern, typed_case :: typed_cases)
    in
    let cases = List.rev cases in
    let%bind.Result exception_cases =
      List.fold_result
        exception_cases
        ~init:[]
        ~f:(fun typed_cases (pattern, body) ->
          let%bind.Result typed_pattern =
            pattern_type t scope ~pattern ~expected:Type.exn
          in
          let%map.Result typed_case = case ~ty:Type.exn typed_pattern body in
          typed_case :: typed_cases)
      |> Result.map ~f:List.rev
    in
    let%map.Result () =
      match expr, cases with
      | Generated _, [] ->
        (* Its scrutinee was closed, unless of an empty nominal type, which
           may have been known only from an annotation. *)
        Ok ()
      | _ ->
        Variant_match.close
          t
          scope
          ~scrutinee:scrutinee.ty
          ~loc
          (List.map cases ~f:fst)
    in
    node (Match { scrutinee; cases; exception_cases }) result
  | Poly_record fields ->
    let%map.Result fields = labelled_types t scope fields ~expected in
    node
      (Poly_record fields)
      (Fresh.record t (Poly_row.present (labelled_tys fields) ~tail:REmpty))
  | Poly_field (expr, label) ->
    let ty = Scope.fresh_ty t scope in
    let%map.Result expr, (_ : Type.row) =
      check_open_record t scope expr [ label, ty ]
    in
    node (Poly_field (expr, label)) ty
  | Poly_extend (fields, expr) ->
    let%bind.Result fields = labelled_types t scope fields ~expected in
    let rest = Scope.fresh_row t scope in
    let%map.Result expr = check_expr t scope ~expr ~ty:(Fresh.record t rest) in
    node
      (Poly_extend (fields, expr))
      (Fresh.record t (Poly_row.present (labelled_tys fields) ~tail:rest))
  | Poly_restrict (expr, label) ->
    let%map.Result expr, rest =
      check_open_record t scope expr [ label, Scope.fresh_ty t scope ]
    in
    node (Poly_restrict (expr, label)) (Fresh.record t rest)
  | Poly_update (expr, fields) ->
    let%bind.Result fields = labelled_types t scope fields ~expected in
    let%map.Result expr, rest =
      check_open_record
        t
        scope
        expr
        (List.map fields ~f:(fun (label, _) -> label, Scope.fresh_ty t scope))
    in
    node
      (Poly_update (expr, fields))
      (Fresh.record t (Poly_row.present (labelled_tys fields) ~tail:rest))
  | Poly_variant (tag, arg) ->
    let%map.Result arg =
      match arg with
      | None -> Ok None
      | Some expr ->
        let%map.Result expr =
          expr_type
            t
            scope
            ~expr
            ?expected:(row_entry expected `Variant ~label:tag)
        in
        Some expr
    in
    let arg_ty =
      Option.value_map arg ~default:Type.unit ~f:(fun (expr : Typed.Expr.t) ->
        expr.ty)
    in
    node (Poly_variant (tag, arg)) (Poly_row.variant t scope ~tag ~arg:arg_ty)

(* Runs the toplevel splice [code], then infers the code it generates here,
   with its explicit substitutions bound by lets around it. *)
and expand t (scope : Scope.t) ~code ~subs ~ty ~loc =
  let program = scope.program in
  let bindings, entry =
    match (subs : Typed.Expr.t Typed.Expr.Subs.t) with
    | Implicit providers ->
      ( []
      , fun name ->
          Map.find providers name
          |> Option.map ~f:(fun binder -> Typed.Var_ref.Bound binder) )
    | Explicit subs ->
      let bindings =
        List.map subs ~f:(fun (name, (sub : Typed.Expr.t)) ->
          ( Program_env.bind
              program
              (Name (Located.create ~loc name))
              sub.ty
              ~level:scope.level
          , sub ))
      in
      ( bindings
      , fun name ->
          List.find bindings ~f:(fun ((ident : Typed.Ident.t), _) ->
            String.equal ident.name name)
          |> Option.map ~f:(fun (ident, _) -> Typed.Var_ref.Bound (Local ident))
      )
  in
  let%bind.Result generated =
    at_compile_time
      program
      (fun ~reflect ->
         Treewalk.splice
           program.interpreter
           ~code
           ~level:(scope.level - 1)
           ~entry
           ~reflect)
      ~error:(fun error ->
        Typecheck_error.create ~loc (Splice_evaluation_failed { code; error }))
  in
  let expansion =
    match
      with_monomorphic_bindings
        scope
        (List.map bindings ~f:(fun (ident, (sub : Typed.Expr.t)) ->
           ident, sub.ty))
        ~f:(fun () ->
          check_expr t scope ~expr:(Source.Expr.Generated generated) ~ty)
    with
    | Ok expansion -> expansion
    | Error error ->
      raise_s
        [%message
          "Generated code is ill typed"
            (generated : Typed.Expr.t)
            (error : Typecheck_error.t)]
  in
  Ok
    (List.fold_right bindings ~init:expansion ~f:(fun (ident, body) in_ ->
       { Typed.Expr.desc =
           Let
             { ident
             ; args = []
             ; annots = []
             ; result_annot = None
             ; generalized = false
             ; body
             ; in_
             }
       ; ty = in_.ty
       ; loc
       }))

and labelled_types t scope fields ~expected =
  let%bind.Result () = Poly_row.check_distinct_labels fields in
  List.map fields ~f:(fun ((label : Syntax.Name.t), expr) ->
    let%map.Result expr =
      expr_type
        t
        scope
        ~expr
        ?expected:(row_entry expected `Record ~label:label.txt)
    in
    label.txt, expr)
  |> Result.all

(* Checks [expr] has type [ty], [expected] (by default [ty]) being what it is
   known to be. *)
and check_expr ?expected t scope ~expr ~ty =
  let%bind.Result expr =
    expr_type t scope ~expr ~expected:(Option.value expected ~default:ty)
  in
  let%map.Result () =
    Unify.unify_ty t ~ty1:ty ~ty2:expr.ty |> lift ~loc:expr.loc
  in
  expr

and check_exprs t scope exprs =
  List.fold_result exprs ~init:[] ~f:(fun checked (expr, ty) ->
    let%map.Result expr = check_expr t scope ~expr ~ty in
    expr :: checked)
  |> Result.map ~f:List.rev

(* Checks [expr] has a record type with [entries] first, returning the rest of
   its row. *)
and check_open_record t scope expr entries =
  let row, rest = Poly_row.open_ t scope entries in
  let%map.Result expr = check_expr t scope ~expr ~ty:(Fresh.record t row) in
  expr, rest

(* Returns the binder each entry that may be captured is captured by: entries
   bound in the quote may be captured by their binders if [may_capture]. *)
and substitute_from_scope t (scope : Scope.t) ~context ~loc ~may_capture =
  let rec go context ~seen ~captures =
    match Type.canonical_row context with
    | REmpty -> Ok captures
    | RExtend (name, presence, ty, rest) ->
      let%bind.Result captured =
        match Type.canonical_presence presence with
        | _ when Set.mem seen name -> Ok None
        | Absent -> Ok None
        | Present | PVar _ ->
          substitute_entry t scope ~name ~presence ~ty ~loc ~may_capture
      in
      let captures =
        Option.fold captured ~init:captures ~f:(fun captures binder ->
          (name, binder) :: captures)
      in
      go rest ~seen:(Set.add seen name) ~captures
    | RVar _ as tail ->
      (match scope.quote with
       | None ->
         let%map.Result () =
           Unify.unify_row t ~row1:tail ~row2:REmpty |> lift ~loc
         in
         captures
       | Some quote ->
         let%map.Result captured =
           substitute_tail t scope quote ~tail ~seen ~loc ~may_capture
         in
         captured @ captures)
  in
  let%map.Result captures = go context ~seen:String.Set.empty ~captures:[] in
  String.Map.of_alist_exn captures

and substitute_entry t (scope : Scope.t) ~name ~presence ~ty ~loc ~may_capture =
  let%bind.Result entry =
    match Env.find scope.locals name, scope.quote with
    | Some entry, _ -> Ok (Some entry)
    (* Toplevels are free variables of the quote, like any name not bound in
       it. *)
    | None, Some _ -> Ok None
    | None, None ->
      (* The code is checked and runs now, so if it may use [name], it doesn't.
         Providing it anyway could add a dependency on its toplevel, and would
         depend on whether that is checked yet. *)
      (match
         ( Program_env.find_toplevel scope.program name
         , Type.canonical_presence presence )
       with
       | Some toplevel, Present ->
         toplevel_entry t scope toplevel ~loc |> Result.map ~f:Option.some
       | None, _ | Some _, (Absent | PVar _) -> Ok None)
  in
  match Resolution.of_entry scope ~name entry with
  | Unusable (Not_in_scope _)
    when Option.is_none scope.quote
         && Hashtbl.mem scope.program.unusable_in_quotes name ->
    let unusable = Hashtbl.find_exn scope.program.unusable_in_quotes name in
    let%map.Result () =
      Unify.make_absent
        t
        presence
        ~error:
          (Typecheck_error.create
             ~loc
             (Free_in_spliced_code { name; unusable }))
    in
    None
  | Unusable kind ->
    (* Code that may use [name] can't, so doesn't. *)
    let%map.Result () =
      Unify.make_absent t presence ~error:(Typecheck_error.create ~loc kind)
    in
    None
  | Local entry when may_capture name entry.binder ->
    let%map.Result () =
      Unify.unify_if_present
        t
        ~presence
        ~ty1:ty
        ~ty2:(Scope.instantiate t scope entry.scheme)
      |> lift ~loc
    in
    Some entry.binder
  | Local _ ->
    let%map.Result () =
      Unify.unify_row
        t
        ~row1:(RExtend (name, presence, ty, REmpty))
        ~row2:(RExtend (name, Absent, ty, REmpty))
      |> lift ~loc
    in
    None
  | Outside_quote { quote; _ } ->
    let%map.Result () =
      Unify.constrain_row
        t
        ~row:(RExtend (name, presence, ty, REmpty))
        ~bound:quote.context
        ~shadowed:String.Set.empty
      |> lift ~loc
    in
    None

(* The code's remaining free variables are not known yet, so give the ones that
   would be captured here explicit entries, absent unless [may_capture]. The
   rest must be free variables of the quote. Returns the binders of the ones
   that may be captured. *)
and substitute_tail t scope (quote : Scope.quote) ~tail ~seen ~loc ~may_capture =
  let captured =
    Env.visible scope.locals
    |> List.filter_map ~f:(fun (name, entry) ->
      if Set.mem seen name
      then None
      else (
        match Resolution.of_entry scope ~name (Some entry) with
        | Local entry when may_capture name entry.binder ->
          Some
            ( name
            , Scope.fresh_presence t scope
            , Scope.instantiate t scope entry.scheme
            , Some entry.binder )
        | Local _ | Unusable _ ->
          Some (name, Absent, Scope.fresh_ty t scope, None)
        | Outside_quote _ -> None))
  in
  let rest = Scope.fresh_row t scope in
  let%bind.Result () =
    Unify.unify_row
      t
      ~row1:tail
      ~row2:
        (List.fold_right
           captured
           ~init:rest
           ~f:(fun (name, presence, ty, _) rest ->
             Type.RExtend (name, presence, ty, rest)))
    |> lift ~loc
  in
  let%map.Result () =
    Unify.constrain_row
      t
      ~row:rest
      ~bound:quote.context
      ~shadowed:
        (List.fold captured ~init:seen ~f:(fun seen (name, _, _, _) ->
           Set.add seen name))
    |> lift ~loc
  in
  List.filter_map captured ~f:(fun (name, _, _, binder) ->
    Option.map binder ~f:(fun binder -> name, binder))

and substitute_explicitly t scope ~context ~subs ~loc =
  let%bind.Result () =
    check_no_duplicates (List.map subs ~f:fst) ~error:(fun name ->
      Duplicate_substitution name)
  in
  let%bind.Result provided =
    List.fold_result
      subs
      ~init:[]
      ~f:(fun acc ({ txt = name; loc = name_loc }, expr) ->
        let%map.Result expr =
          match expr with
          | None ->
            let%map.Result ty, var_ref =
              var_type
                t
                scope
                ~path:(Path (Syntax.Path.of_string name))
                ~loc:name_loc
            in
            { Typed.Expr.desc = Var var_ref; ty; loc = name_loc }
          | Some expr -> expr_type t scope ~expr
        in
        (name, expr) :: acc)
  in
  (* Toplevels, free by canonical name, which no sub can name. *)
  let rec toplevels (row : Type.row) =
    match Type.canonical_row row with
    | RExtend (name, presence, _, rest) ->
      (match Type.canonical_presence presence with
       | (Present | PVar _) when String.mem name '.' -> name :: toplevels rest
       | Present | PVar _ | Absent -> toplevels rest)
    | REmpty | RVar _ -> []
  in
  let%bind.Result provided =
    List.fold_result (toplevels context) ~init:provided ~f:(fun acc name ->
      let%map.Result ty, var_ref = resolved_value_type t scope name ~loc in
      (name, { Typed.Expr.desc = Var var_ref; ty; loc }) :: acc)
  in
  let row =
    List.fold provided ~init:Type.REmpty ~f:(fun rest (name, expr) ->
      Type.RExtend (name, Scope.fresh_presence t scope, expr.ty, rest))
  in
  let%map.Result () = Unify.unify_row t ~row1:context ~row2:row |> lift ~loc in
  List.rev provided
;;

module Checked = struct
  type t =
    { signature : Signature.t
    ; program : Typed.Program.t
    }
end

let toplevel_scope t program module_ ~level ~in_expect_test =
  let rank = 1 in
  { Scope.program
  ; level
  ; rank
  ; locals = Env.create ()
  ; quote = None
  ; module_
  ; scc = { Scc_frame.lowlink = Fresh.id t; pending = [] }
  ; annotation_vars = Type_env.Annotation_vars.create t ~rank
  ; in_expect_test
  }
;;

let check_expect_test t program module_ ~name ~body ~loc ~generated =
  let scope = toplevel_scope t program module_ ~level:0 ~in_expect_test:true in
  let%map.Result body =
    check_expr t scope ~expr:(Source.Expr.Syntax body) ~ty:Type.unit
    |> Generated.wrap_result generated
    |> Result.map_error ~f:(Module_scope.within module_)
  in
  { Typed.Expect_test.name; body; loc; generated = Option.is_some generated }
;;

let check_bench t program module_ ~name ~param ~body ~loc ~generated =
  let scope = toplevel_scope t program module_ ~level:0 ~in_expect_test:false in
  Result.map_error ~f:(Module_scope.within module_)
  @@ Generated.wrap_result generated
  @@
  match (param : Syntax.Bench_param.t option) with
  | None ->
    let%map.Result body =
      check_expr
        t
        scope
        ~expr:(Source.Expr.Syntax body)
        ~ty:(Scope.fresh_ty t scope)
    in
    { Typed.Bench.name
    ; param = None
    ; body
    ; loc
    ; generated = Option.is_some generated
    }
  | Some { name = param; args } ->
    let%bind.Result { args = params; res_ty; _ } =
      function_type t scope ~args:[ Source.Binder.Name param, None ] ~annot:None
    in
    let ident, param_ty = List.hd_exn params in
    let%bind.Result args =
      List.map args ~f:(fun arg ->
        check_expr t scope ~expr:(Source.Expr.Syntax arg) ~ty:param_ty)
      |> Result.all
    in
    let%map.Result body =
      check_body t scope ~args:params ~res_ty ~body:(Source.Expr.Syntax body)
    in
    { Typed.Bench.name
    ; param = Some (ident, args)
    ; body
    ; loc
    ; generated = Option.is_some generated
    }
;;

