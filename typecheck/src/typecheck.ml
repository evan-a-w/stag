open! Import

(* A declaration generated by a declaration splice, whose errors are reported at
   the splice, naming the declaration. *)
module Generated = struct
  type t =
    { splice : Loc.t
    ; declaration : string
    ; generated : Syntax.Toplevel.t [@sexp.opaque]
    }
  [@@deriving sexp_of]

  let create splice (toplevel : Syntax.Toplevel.t) =
    let declaration =
      match toplevel.txt with
      | Let (name, _, _, _) -> "let " ^ name.txt
      | Let_mut (name, _, _) -> "let mut " ^ name.txt
      | Type decl -> "type " ^ decl.name.txt
      | Exception (name, _) | Malformed_exception (name, _) ->
        "exception " ^ name.txt
      | External { name; _ } -> "external " ^ name.txt
      | Module (name, _) | Module_splice (name, _, _) -> "module " ^ name.txt
      | Include _ -> "include"
      | Expect_test { name; _ } -> sprintf "let%%expect_test %S" name.txt
      | Bench { name; _ } -> sprintf "let%%bench %S" name.txt
    in
    { splice = Module_scope.Splice.loc splice
    ; declaration
    ; generated = toplevel
    }
  ;;

  (* Errors in generated code are at the splice. Others, eg. of written
     declarations it uses, are left as they are. *)
  let wrap_error t (error : Typecheck_error.t) =
    match error.kind with
    | In_generated_declaration _ -> error
    | _ when not (Loc.equal error.loc t.splice) -> error
    | kind ->
      { error with
        loc = t.splice
      ; kind =
          In_generated_declaration
            { declaration = t.declaration
            ; generated = t.generated
            ; error = kind
            }
      }
  ;;
end

(* The expression a toplevel splice of syntax gave, whose errors are reported at
   the splice. *)
module Syntax_splice = struct
  type t =
    { splice : Loc.t
    ; generated : Syntax.Expr.t
    }

  let wrap_error t (error : Typecheck_error.t) =
    match error.kind with
    | In_syntax_splice _ -> error
    | _ when not (Loc.equal error.loc t.splice) -> error
    | kind ->
      { error with
        kind = In_syntax_splice { generated = t.generated; error = kind }
      }
  ;;
end

module Toplevel = struct
  (** [external name : ty = "symbol"], whose [expr] is a placeholder. *)
  module External = struct
    type t =
      { ty : Syntax.Type_expr.t
      ; symbol : string Located.t
      }
    [@@deriving sexp_of]
  end

  module State = struct
    type t =
      | Unchecked
      | In_progress of
          { index : int
          ; ty : Type.ty
          ; args : Typed.Ident.t list
          ; mode : Binding.t
          ; init_mode : Mode.Var.t
          (** Of its initializer: its [mode], but for a mutable one, whose
              variable is referred to by symbol. *)
          ; held : Binding.t option (** Of the values a mutable one holds. *)
          ; mutable body : Typed.Expr.t option
          ; mutable recursive : bool
          }
      | Done of
          { entry : Env.Entry.t
          ; typed : Typed.Toplevel.t
          ; failed : bool
          (** Its component, or one it uses, had an error, so it is not run at
              compile time. *)
          ; runtime_only : string option
          (** The mutable toplevel it may use when run, if any, so it can't be
              run at compile time, where there is none. *)
          }
    [@@deriving sexp_of]
  end

  type t =
    { ident : Typed.Ident.t
    ; module_ : Module_scope.t
    ; args : Syntax.Binding.t list
    ; annot : Syntax.Type_expr.t option
    ; mode : Syntax.Mode_expr.t option
    ; expr : Syntax.Expr.t
    ; mut : bool
    ; external_ : External.t option
    ; generated : Generated.t option
    ; mutable state : State.t
    }
  [@@deriving sexp_of]

  let is_function t = not (List.is_empty t.args)
end

type t =
  { fresh : Fresh.t
  ; modes : Mode.Id_source.t
  ; stamps : Stamp_counter.t
  ; interpreter : Interpreter.t
  ; const_toplevels : bool
  ; prelude : Syntax.Toplevel.t list Lazy.t
  }

let create ~stamps ~interpreter ?(const_toplevels = false) ?prelude () =
  let fresh = Fresh.create () in
  { fresh
  ; modes = Fresh.modes fresh
  ; stamps
  ; interpreter
  ; const_toplevels
  ; prelude =
      (match prelude with
       | Some prelude -> Lazy.from_val prelude
       | None -> Prelude.toplevels)
  }
;;

let lift ~loc result =
  Result.map_error result ~f:(Typecheck_error.unification_error ~loc)
;;

let error ~loc kind = Error (Typecheck_error.create ~loc kind)

(* Toplevels are checked on demand, so strongly connected components are found
   with Tarjan's algorithm as we go. [pending] are the visited toplevels whose
   component is not yet complete. [id] identifies the errors reported while
   checking the frame's code. *)
module Scc_frame = struct
  type t =
    { id : int
    ; mutable lowlink : int
    ; mutable pending : Toplevel.t list
    ; mutable failed : bool
    }

  let create id ~pending = { id; lowlink = id; pending; failed = false }
end

module Report = struct
  type t =
    { error : Typecheck_error.t
    ; frame : int option
    (** The [Scc_frame.id] of the code it is in, if its checking may be
        abandoned. *)
    }
end

(* What one call of [typecheck] checks. *)
module Program_env = struct
  type t =
    { type_env : Type_env.t
    ; toplevels : Toplevel.t Lazy.t String.Table.t
    (** By canonical name. The prelude's are made when first used, so that those
        unused take no idents. *)
    ; stamps : Stamp_counter.t
    ; interpreter : Interpreter.t
    ; mutable ident_info : Typed.Ident_info.t Typed.Ident.Map.t
    ; sccs : Typed.Scc.t Queue.t
    ; declaration_splices : Typed.Expr.t Queue.t
    ; unusable_in_quotes : Typecheck_error.Unusable_in_quote.t String.Table.t
    (** The latest free variable of a quote that a binding of its name, unusable
        there, did not bind, to explain an error if the code is spliced where
        the name is unbound. *)
    ; unfinished : Type.ty Stack.t
    (** The types of the toplevels and binders of components not yet finished.
        Code checked later can reach them, so once their component is finished,
        the variables not generalized are lowered to rank 0, so that later
        components don't generalize them. *)
    ; mutable reports : Report.t list (** Latest first. *)
    ; mutable reported : int
    (** How many errors were reported, [Already_reported] and forgotten ones
        included. *)
    ; mutable syntax_errors : bool
    (** Whether the program has code that did not parse, reported by the parser. *)
    ; splice_starts : int Stack.t
    (** The index each declaration splice being generated began at, innermost
        first. *)
    ; mutable_idents : Typed.Ident.Hash_set.t
    (** Of the [let mut]s, local and toplevel. *)
    ; modes : Mode.Id_source.t
    ; const_toplevels : bool
    ; mode_limits_reported : String.Hash_set.t
    (** The reasons of the upper bounds of mode errors reported, so that each
        limit is reported once, at what first exceeded it. *)
    ; parameter_modes : Int.Hash_set.t
    (** The ids of the modes of parameters: what they are is decided by each use
        of their function, so is not known while it is checked. *)
    }

  let report ?frame t error =
    t.reported <- t.reported + 1;
    t.reports <- { Report.error; frame } :: t.reports
  ;;

  let errors t =
    List.filter_map t.reports ~f:(fun { error; frame = _ } ->
      Option.some_if (not (Typecheck_error.is_already_reported error)) error)
  ;;

  (* Forgets the errors of the code of [frames], abandoned to be checked anew. *)
  let forget t ~frames =
    t.reports
    <- List.filter t.reports ~f:(fun { error = _; frame } ->
         not
           (Option.value_map
              frame
              ~default:false
              ~f:(List.mem frames ~equal:Int.equal)))
  ;;

  let fresh_ident t name = Typed.Ident.fresh t.stamps name

  let find_toplevel t name =
    Hashtbl.find t.toplevels name |> Option.map ~f:force
  ;;

  let toplevel t name = force (Hashtbl.find_exn t.toplevels name)

  let add_info t ident ~ty ~level =
    let info = { Typed.Ident_info.ty; level } in
    t.ident_info <- Map.add_exn t.ident_info ~key:ident ~data:info;
    Interpreter.add_ident_info t.interpreter ~ident ~info
  ;;

  (* Generated code's binders keep their idents, but get their info anew. *)
  let bind t (binder : Source.Binder.t) ty ~level =
    let ident =
      match binder with
      | Name name -> fresh_ident t name.txt
      | Ident ident -> ident
    in
    add_info t ident ~ty ~level;
    Stack.push t.unfinished ty;
    ident
  ;;

  (* Values a toplevel splice's code embedded in its code. *)
  let embedded t ident =
    Interpreter.global_info t.interpreter ~ident
    |> Option.map ~f:(fun info ->
      t.ident_info <- Map.set t.ident_info ~key:ident ~data:info;
      info)
  ;;

  let is_mutable t ident = Hash_set.mem t.mutable_idents ident
end

(* Raised where code run at compile time by a declaration splice uses a toplevel
   whose checking was underway before the splice began, directly or through
   toplevels in its component, so it is left to be forced again. *)
exception Uses_unfinished

(* Carries why reflection failed, eg. a cycle, through the evaluation, to be the
   error of that evaluation. *)
exception Reflection_failed of Typecheck_error.t

let () =
  Sexplib0.Sexp_conv.Exn_converter.add
    [%extension_constructor Reflection_failed]
    (Basement.Stdlib_shim.Obj.magic_portable (function
      | Reflection_failed error ->
        Sexp.List
          [ Atom "typecheck.ml.Reflection_failed"
          ; Typecheck_error.sexp_of_t error
          ]
      | _ -> assert false))
;;

(* Raised by the interpreter: a bug, eg. ill-typed code that was run. *)
exception Internal of exn

(* Evaluates at compile time, reflecting on the program's types. *)
let at_compile_time (program : Program_env.t) f ~loc ~error =
  let reflect name =
    let%bind.Result decl = Type_env.reflect program.type_env name in
    let%map.Result decl_type =
      Type_env.record_type
        program.type_env
        (Prelude_path.canonical "Stag.Type.Decl.t")
    in
    { Reflected_decl.Reflection.decl; decl_type }
  in
  let reflect name =
    reflect name
    |> Result.map_error ~f:(fun error -> Error.of_exn (Reflection_failed error))
  in
  (match f ~reflect with
   | result -> result
   | exception Uses_unfinished -> raise Uses_unfinished
   | exception exn -> Error (Error.of_exn (Internal exn)))
  |> Result.map_error ~f:(fun runtime_error ->
    match Error.to_exn runtime_error with
    | Reflection_failed reflection_error -> reflection_error
    | Erase.Reached_error -> Typecheck_error.already_reported
    | Internal exn ->
      Typecheck_error.create
        ~loc
        (Internal_error
           (Error.tag_s
              (Error.of_exn exn)
              ~tag:[%message "Evaluating at compile time raised"]))
    | _ -> error runtime_error)
;;

module Scope = struct
  type t =
    { program : Program_env.t
    ; level : Env.Level.t
    ; rank : Type.rank
    ; locals : Env.t
    ; quote : quote option
    ; module_ : Module_scope.t
    ; scc : Scc_frame.t
    ; annotation_vars : Type_env.Annotation_vars.t
    ; in_expect_test : bool
    ; generated : Generated.t option
    ; syntax_splice : Syntax_splice.t option
    ; locks : Env.Lock.t list (** Innermost first. *)
    ; params : Type.ty list
    (** The types of the parameters of the functions being checked, whose modes
        are decided by each use of their function. *)
    }

  and quote =
    { id : int
    ; context : Type.row
    ; outside : t
    ; mode : Mode.Var.t
    (** The code's: of what it embeds from outside, and of the splices run when
        it is built. *)
    }

  let quote_id t = Option.map t.quote ~f:(fun quote -> quote.id)

  let entry
    ?(defining = false)
    ?(held : Binding.t option)
    t
    ~ident
    ~scheme
    ~(mode : Binding.t)
    =
    { Env.Entry.scheme
    ; level = t.level
    ; quote_id = quote_id t
    ; mode
    ; held
    ; locks = t.locks
    ; binder = Local ident
    ; defining
    }
  ;;

  (* What [mode] is at least however the functions being checked are used: with
     the modes of their parameters, those within their types, and those of the
     types of the components not finished yet raised. *)
  let known_stage t mode =
    let raised = Int.Hash_set.create () in
    let iter : Nothing.t Type.Iter.t =
      { ty = (fun ~guarded:_ _ -> Ok ())
      ; row = (fun ~guarded:_ _ -> Ok ())
      ; presence = (fun ~guarded:_ _ -> Ok ())
      ; mode =
          (fun var ->
            Hash_set.add raised (Mode.Var.id var);
            Ok ())
      }
    in
    List.iter
      (t.params @ Stack.to_list t.program.unfinished)
      ~f:(fun ty ->
        match Type.iter_ty iter ty with
        | Ok () -> ()
        | Error _ -> .);
    Mode.Var.lower_assuming mode Stage ~raised:(fun id ->
      Hash_set.mem t.program.parameter_modes id || Hash_set.mem raised id)
  ;;

  let enter_closure ids t mode =
    { t with
      locks = { Env.Lock.id = Fresh.id ids; kind = Closure mode } :: t.locks
    }
  ;;

  (* Plain data may be used at any locality and provenance, and at a stage up to
     [portable]: a copy of it is as good. *)
  let crossing t ty =
    if Type_env.pointer_free t.program.type_env ty
    then Mode.Crossing.immediate
    else Mode.Crossing.none
  ;;

  let fresh_ty ids t = Type.TVar (Fresh.var ids ~rank:t.rank)
  let fresh_row ids t = Type.RVar (Fresh.var ids ~rank:t.rank)
  let fresh_presence ids t = Type.PVar (Fresh.var ids ~rank:t.rank)
  let instantiate ids t = Scheme.instantiate ids ~rank:t.rank

  (* Type splices are evaluated in declarations, not in what is evaluated or
     quoted then. *)
  let splices t = Option.is_none t.quote && t.level >= 0

  let wrap_error t error =
    Module_scope.within
      t.module_
      (let error =
         match t.syntax_splice with
         | None -> error
         | Some splice -> Syntax_splice.wrap_error splice error
       in
       match t.generated with
       | None -> error
       | Some generated -> Generated.wrap_error generated error)
  ;;

  let report t (error : Typecheck_error.t) =
    let frame = t.scc.id in
    if Typecheck_error.is_already_reported error
    then Program_env.report t.program error ~frame
    else Program_env.report t.program ~frame (wrap_error t error)
  ;;

  let report_if_error t = function
    | Ok () -> ()
    | Error error -> report t error
  ;;

  (* Whether the mode constraint held: if not, it is reported. *)
  let mode_holds t ~loc = function
    | Ok () -> true
    | Error (Mode.Error.Mismatch { upper_because; _ } as error) ->
      let key = Sexp.to_string [%sexp (upper_because : Mode.Reason.t list)] in
      if not (Hash_set.mem t.program.mode_limits_reported key)
      then (
        Hash_set.add t.program.mode_limits_reported key;
        report t (Typecheck_error.create ~loc (Mode_error error)));
      false
  ;;

  let modes t =
    Mode_rules.Ctx.create
      ~modes:t.program.modes
      ~rank:t.rank
      ~holds:(mode_holds t)
      ~crossing:(crossing t)
  ;;

  let arrow_mode t = Mode_rules.arrow_mode (modes t)
  let mode_var t = Type_env.Annotation_vars.mode t.annotation_vars

  (* Whether they unify: if not, what checked is to become [Error]. *)
  let unifies ids t ~ty1 ~ty2 ~loc =
    match Unify.unify_ty ids ~ty1 ~ty2 with
    | Ok () -> true
    | Error error ->
      report t (Typecheck_error.unification_error ~loc error);
      false
  ;;

  let elaborate_resolved t annot =
    Type_env.elaborate
      t.program.type_env
      t.module_
      t.annotation_vars
      annot
      ~splices:(splices t)
  ;;

  let elaborate t annot = elaborate_resolved t annot |> Result.map ~f:fst
end

(* Where a name is used, given its entry if it has one. *)
module Resolution = struct
  type t =
    | Local of Env.Entry.t
    (** Usable, and bound in the enclosing quote if there is one. *)
    | Outside_quote of
        { quote : Scope.quote
        ; usable : Env.Entry.t option
        ; unusable : Env.Entry.t option
        }
    (** Not bound in the enclosing [quote], so a free variable of it, unless
        used directly while [usable]. Splices never capture the name. [unusable]
        is the entry of the name, if it has one that isn't [usable]. *)
    | Unusable of Typecheck_error.Kind.t (** The error if the name is used. *)

  let of_entry (scope : Scope.t) ~name (entry : Env.Entry.t option) =
    (* Referred to by symbol, as is the variable code assigns. *)
    let is_mutable_toplevel (entry : Env.Entry.t) =
      match entry.binder with
      | Toplevel ident -> Program_env.is_mutable scope.program ident
      | Local _ -> false
    in
    let is_mutable_local (entry : Env.Entry.t) =
      match entry.binder with
      | Local ident -> Program_env.is_mutable scope.program ident
      | Toplevel _ -> false
    in
    (* A local of plain data may be copied into code whatever its stage, but not
       a mutable one, whose value changes, nor a toplevel, which may not have a
       value yet. *)
    let crosses (entry : Env.Entry.t) =
      match entry.binder with
      | Local _ ->
        (not (is_mutable_local entry))
        && (Scope.crossing scope entry.scheme).stage
      | Toplevel _ -> false
    in
    (* Crossing a quote lock needs [portable]: so far, as only its lower bound
       is final, the constraint being added where it is used. *)
    let usable (entry : Env.Entry.t) =
      (entry.level = scope.level
       && [%equal: int option] entry.quote_id (Scope.quote_id scope))
      || (entry.level <= scope.level
          && (((crosses entry
                || Mode.Stage.le
                     (Scope.known_stage scope (entry.mode :> Mode.Var.t))
                     Portable)
               && not entry.defining)
              || is_mutable_toplevel entry))
    in
    match scope.quote, entry with
    | None, Some entry when usable entry -> Local entry
    | Some quote, Some entry
      when [%equal: int option] entry.quote_id (Some quote.id) -> Local entry
    | _, Some entry when is_mutable_local entry && entry.level <> scope.level ->
      Unusable
        (Mutable_used_outside_its_code
           { name; var_level = entry.level; used_at = scope.level })
    | Some quote, Some entry when entry.level <= scope.level ->
      let usable = usable entry in
      Outside_quote
        { quote
        ; usable = Option.some_if usable entry
        ; unusable = Option.some_if (not usable) entry
        }
    | Some quote, None ->
      Outside_quote { quote; usable = None; unusable = None }
    | _, Some entry ->
      Unusable
        (Variable_used_at_wrong_level
           { name; var_level = entry.level; used_at = scope.level })
    | None, None -> Unusable (Not_in_scope (Path (Syntax.Path.of_string name)))
  ;;
end

(* Errs at the second occurrence of the first name repeated. *)
let check_no_duplicates (names : Syntax.Name.t list) ~error:kind =
  List.fold_result names ~init:String.Set.empty ~f:(fun seen { txt; loc } ->
    if Set.mem seen txt then error ~loc (kind txt) else Ok (Set.add seen txt))
  |> Result.ignore_m
;;

(* Reports each repeated occurrence of a name. *)
let report_duplicates scope (names : Syntax.Name.t list) ~error:kind =
  ignore
    (List.fold names ~init:String.Set.empty ~f:(fun seen { txt; loc } ->
       if Set.mem seen txt
       then (
         Scope.report scope (Typecheck_error.create ~loc (kind txt));
         seen)
       else Set.add seen txt)
     : String.Set.t)
;;

module Function_type = struct
  module Level = struct
    type t =
      { args : (Typed.Ident.t * Type.ty) list
      ; annots : (Typed.Ident.t * Syntax.Annot.t) list
      ; ty : Type.ty
      ; loc : Loc.t
      }
  end

  type t =
    { args : (Typed.Ident.t * Type.ty) list (** The outermost [fun]'s. *)
    ; annots : (Typed.Ident.t * Syntax.Annot.t) list
    ; inner : Level.t list
    (** The [fun]s directly nested in its body, outermost first: one function
        with theirs, as [fun a b -> e] is. *)
    ; body : Source.Expr.t (** The innermost [fun]'s. *)
    ; result_annot : Syntax.Type_expr.t option
    ; res_ty : Type.ty
    ; ty : Type.ty
    ; arg_modes : Mode.Var.t list (** Of every level's arguments. *)
    ; res_mode : Mode.Var.t (** The mode of the body's value. *)
    ; partial_modes : Mode.Var.t list
    (** Those of the closures of partial applications, of all but the last
        argument. *)
    }

  let params t = t.args @ List.concat_map t.inner ~f:(fun level -> level.args)
end

(* [fun]s directly nested in [body], each with its arguments and location, and
   the innermost body. *)
let rec nested_funs (body : Source.Expr.t) =
  match Source.Expr.view body with
  | Fun { args; body = inner } ->
    let levels, innermost = nested_funs inner in
    (args, Source.Expr.loc body) :: levels, innermost
  | _ -> [], body
;;

(* An annotation that fails to elaborate is reported, and ignored. Mode
   annotations on the arguments, and with [res_mode] on the result, bound their
   modes. Unless [merge] is false, [fun]s directly nested in an unannotated body
   are arguments of the same function. *)
let function_type
  ?(merge = true)
  t
  (scope : Scope.t)
  ~(args : (Source.Binder.t * Syntax.Annot.t) list)
  ~annot
  ~res_mode
  ~(body : Source.Expr.t)
  ~loc
  =
  let levels, body =
    match annot, res_mode with
    | None, None when merge && not (List.is_empty args) -> nested_funs body
    | _ -> [], body
  in
  List.iter (args :: List.map levels ~f:fst) ~f:(fun args ->
    report_duplicates
      scope
      (List.filter_map args ~f:(fun ((binder : Source.Binder.t), _) ->
         match binder with
         | Name name when not (String.equal name.txt "_") -> Some name
         | Name _ | Ident _ -> None))
      ~error:(fun name -> Duplicate_parameter name));
  let arity = List.length args in
  let level_arities = List.map levels ~f:(fun (args, _) -> List.length args) in
  let args = args @ List.concat_map levels ~f:fst in
  let annot_type = function
    | None -> Scope.fresh_ty t scope, None
    | Some annot ->
      (match Scope.elaborate_resolved scope annot with
       | Ok (ty, resolved) -> ty, Some resolved
       | Error error ->
         Scope.report scope error;
         Scope.fresh_ty t scope, None)
  in
  let moded annot =
    Mode_rules.annotated (Scope.modes scope) annot ~var:(Scope.mode_var scope)
  in
  let args =
    List.map args ~f:(fun (binder, (annot : Syntax.Annot.t)) ->
      let ty, resolved = annot_type annot.ty in
      let mode = moded annot.mode in
      Hash_set.add scope.program.parameter_modes (Mode.Var.id mode);
      binder, ty, { annot with ty = resolved }, mode)
  in
  let res_ty, result_annot = annot_type annot in
  let res_mode = moded res_mode in
  let partial_modes =
    List.drop_last args
    |> Option.value ~default:[]
    |> List.map ~f:(fun _ -> Scope.arrow_mode scope)
  in
  (* The type after each number of arguments, the full type first. *)
  let tys =
    let results =
      if List.is_empty args
      then []
      else
        List.map partial_modes ~f:(fun partial ->
          partial, Scope.arrow_mode scope)
        @ [ res_mode, Mode_rules.Function.result_curry (Scope.modes scope) ~loc
          ]
    in
    List.fold_right
      (List.zip_exn args results)
      ~init:[ res_ty ]
      ~f:(fun ((_, arg_ty, _, arg_mode), (res_mode, curry)) tys ->
        Type.TArrow
          ( arg_ty
          , List.hd_exn tys
          , { arg = Var arg_mode; res = Var res_mode; curry = Var curry } )
        :: tys)
  in
  let arg_modes = List.map args ~f:(fun (_, _, _, mode) -> mode) in
  let bound =
    List.map args ~f:(fun (binder, ty, resolved, _) ->
      let ident = Program_env.bind scope.program binder ty ~level:scope.level in
      ( (ident, ty)
      , Option.some_if (not (Syntax.Annot.is_none resolved)) (ident, resolved) ))
  in
  let level bound =
    let args, annots = List.unzip bound in
    args, List.filter_opt annots
  in
  let args, annots = level (List.take bound arity) in
  let inner =
    List.folding_map
      (List.zip_exn level_arities (List.map levels ~f:snd))
      ~init:arity
      ~f:(fun start (count, loc) ->
        let args, annots = level (List.sub bound ~pos:start ~len:count) in
        ( start + count
        , { Function_type.Level.args; annots; ty = List.nth_exn tys start; loc }
        ))
  in
  { Function_type.args
  ; annots
  ; inner
  ; body
  ; result_annot
  ; res_ty
  ; ty = List.hd_exn tys
  ; arg_modes
  ; res_mode
  ; partial_modes
  }
;;

let constructor_ref (constructor : Type_env.Constructor.t) =
  { Typed.Constructor_ref.type_name = constructor.type_name
  ; name = constructor.name
  ; index = constructor.index
  }
;;

let field_ref (field : Type_env.Field.t) =
  { Typed.Field_ref.record = field.record_type; index = field.index }
;;

(* Type-directed lookup: the declared type a constructor or field is known to be
   of, by its canonical name, and its members. *)
module Known = struct
  type 'member t =
    { type_name : string
    ; members : 'member list
    }

  let find
    (scope : Scope.t)
    (ty : Type.ty option)
    ~(members : Type_env.t -> string -> ('m list option, _) Result.t)
    =
    match Option.map ty ~f:Type.canonical_ty with
    | Some ty when Type.is_error ty ->
      (* What did not check has no members, nor any errors from them. *)
      Error Typecheck_error.already_reported
    | Some (TCon (type_name, _)) ->
      let%map.Result members = members scope.program.type_env type_name in
      Option.map members ~f:(fun members -> { type_name; members })
    | Some _ | None -> Ok None
  ;;

  let record scope ty = find scope ty ~members:Type_env.record_fields
  let variant scope ty = find scope ty ~members:Type_env.variant_constructors

  (* Only an unqualified name is looked up in the known type: a qualified one or
     a ref names its declaration. *)
  let unqualified : Syntax.Decl_path.t Located.t -> string option = function
    | { txt = Path path; loc = _ } ->
      (match (path :> string list) with
       | [ name ] -> Some name
       | _ -> None)
    | { txt = Root _ | Resolved _; loc = _ } -> None
  ;;

  let unqualified_field : Source.Field.t -> string option = function
    | Path path -> unqualified path
    | Ref _ -> None
  ;;

  let has t name ~member_name =
    List.exists t.members ~f:(fun member ->
      String.equal (Prelude_path.short_name (member_name member)) name)
  ;;

  let member t ~name ~member_name ~loc ~missing =
    match
      List.find t.members ~f:(fun member ->
        String.equal (Prelude_path.short_name (member_name member)) name)
    with
    | Some member -> Ok member
    | None -> error ~loc (missing ~type_name:t.type_name name)
  ;;
end

let find_constructor (scope : Scope.t) ~loc ~known : Source.Constructor.t -> _
  = function
  | Path path ->
    (match Known.unqualified path, known with
     | Some name, Some (known : _ Known.t) ->
       Known.member
         known
         ~name
         ~member_name:(fun (constructor : Type_env.Constructor.t) ->
           constructor.name)
         ~loc:path.loc
         ~missing:(fun ~type_name constructor ->
           No_such_constructor { type_name; constructor })
     | _ -> Type_env.find_constructor scope.program.type_env scope.module_ path)
  | Ref { name; _ } -> Type_env.constructor scope.program.type_env name ~loc
;;

(* Generated code's fields are at [loc], its node's. *)
let field_loc ~loc : Source.Field.t -> Loc.t = function
  | Path path -> path.loc
  | Ref _ -> loc
;;

let find_field (scope : Scope.t) ~loc ~known (field : Source.Field.t) =
  match field with
  | Path path ->
    (match Known.unqualified path, known with
     | Some name, Some (known : _ Known.t) ->
       Known.member
         known
         ~name
         ~member_name:Type_env.Field.name
         ~loc:path.loc
         ~missing:(fun ~type_name field -> No_such_field { type_name; field })
     | _ -> Type_env.find_field scope.program.type_env scope.module_ path)
  | Ref field ->
    Type_env.field scope.program.type_env (Typed.Field_ref.name field) ~loc
;;

(* Unifies [ty], a fresh instance of a declared type, with [expected] if that is
   known to be the same type, so that what is inside is known too. As [expected]
   is always unified with what has [ty] later, it fails only where that would. *)
let unify_known t ~expected ty ~loc =
  match Option.map expected ~f:Type.canonical_ty, Type.canonical_ty ty with
  | Some (TCon (known, _) as expected), TCon (name, _)
    when String.equal known name ->
    Unify.unify_ty t ~ty1:ty ~ty2:expected |> lift ~loc
  | _ -> Ok ()
;;

(* Pairs each of [args] with its instantiated type, along with the constructor
   and the result type. Several [args] of a constructor declared with one are a
   tuple ([tuple]), as in OCaml. *)
let constructor_types
  t
  (scope : Scope.t)
  constructor
  ~args
  ~tuple
  ~expected
  ~loc
  =
  let%bind.Result known = Known.variant scope expected in
  let%bind.Result (constructor : Type_env.Constructor.t) =
    find_constructor scope constructor ~loc ~known
  in
  let args =
    match args, constructor.args with
    | _ :: _ :: _, [ _ ] -> [ tuple args ]
    | _ -> args
  in
  match List.zip args constructor.args with
  | Unequal_lengths ->
    error
      ~loc
      (Constructor_arity_mismatch
         { constructor = constructor.name
         ; expected = List.length constructor.args
         ; got = List.length args
         })
  | Ok args ->
    let inst = Scope.instantiate t scope in
    let result = inst constructor.result in
    let%map.Result () = unify_known t ~expected result ~loc in
    ( constructor_ref constructor
    , List.map2_exn args constructor.global_args ~f:(fun (arg, ty) is_global ->
        arg, inst ty, Modality.of_global is_global)
    , result )
;;

(* The record type [fields] (not empty) are of: [expected] if it is known to be
   a record type, else that of the first qualified field (or ref), else the
   first of the unqualified fields' types in scope that has all of them. *)
let record_type (scope : Scope.t) fields ~expected ~loc =
  let of_field field =
    let%bind.Result (field : Type_env.Field.t) =
      find_field scope field ~loc ~known:None
    in
    let%map.Result known = Known.record scope (Some field.record) in
    Option.value_exn known
  in
  match%bind.Result Known.record scope expected with
  | Some known -> Ok known
  | None ->
    (match
       List.find fields ~f:(fun (field, _) ->
         Option.is_none (Known.unqualified_field field))
     with
     | Some (field, _) -> of_field field
     | None ->
       let names =
         List.filter_map fields ~f:(fun (field, _) ->
           Known.unqualified_field field)
       in
       let has_all known =
         List.for_all
           names
           ~f:(Known.has known ~member_name:Type_env.Field.name)
       in
       (match
          List.find_map fields ~f:(fun (field, _) ->
            match of_field field with
            | Ok known when has_all known -> Some known
            | Ok _ | Error _ -> None)
        with
        | Some known -> Ok known
        | None -> of_field (fst (List.hd_exn fields))))
;;

let is_given fields (member : Type_env.Field.t) =
  List.exists fields ~f:(fun ((field : Type_env.Field.t), _, _) ->
    field.index = member.index)
;;

(* The record type of [fields], and each field with its location and its [x]. A
   missing required field is reported, and [Error] on [complete]. *)
let resolve_record_fields (scope : Scope.t) fields ~all_required ~expected ~loc =
  let%bind.Result () =
    if List.is_empty fields then error ~loc Empty_record else Ok ()
  in
  let%bind.Result (known : Type_env.Field.t Known.t) =
    record_type scope fields ~expected ~loc
  in
  let find (field, x) =
    let%bind.Result (found : Type_env.Field.t) =
      find_field scope field ~loc ~known:(Some known)
    in
    let loc = field_loc field ~loc in
    if String.equal found.record_type.name known.type_name
    then Ok (found, loc, x)
    else
      error
        ~loc
        (Fields_of_different_types
           { field = Type_env.Field.name found
           ; expected_type = known.type_name
           ; actual_type = found.record_type.name
           })
  in
  (* A qualified field of another type is the error, rather than an unqualified
     one the type lacks. *)
  let%bind.Result (_ : _ list) =
    List.filter fields ~f:(fun (field, _) ->
      Option.is_none (Known.unqualified_field field))
    |> List.map ~f:find
    |> Result.all
  in
  let%bind.Result fields = List.map fields ~f:find |> Result.all in
  let%bind.Result () =
    check_no_duplicates
      (List.map fields ~f:(fun (field, loc, _) ->
         { Located.txt = Prelude_path.short_name (Type_env.Field.name field)
         ; loc
         }))
      ~error:(fun name -> Repeated_field name)
  in
  let complete =
    match List.find known.members ~f:(Fn.non (is_given fields)) with
    | Some member when all_required ->
      Scope.report
        scope
        (Typecheck_error.create
           ~loc
           (Missing_field (Type_env.Field.name member)));
      false
    | Some _ | None -> true
  in
  Ok (known, fields, complete)
;;

let declared_record (known : Type_env.Field.t Known.t) =
  (List.hd_exn known.members).record
;;

(* Returns the instantiated record type, and each field with its [x] paired with
   its type. *)
let record_fields t (scope : Scope.t) fields ~all_required ~expected ~loc =
  let%bind.Result known, fields, complete =
    resolve_record_fields scope fields ~all_required ~expected ~loc
  in
  let inst = Scope.instantiate t scope in
  let record = inst (declared_record known) in
  let%map.Result () = unify_known t ~expected record ~loc in
  let fields =
    List.map fields ~f:(fun ((field : Type_env.Field.t), _, x) ->
      field_ref field, (x, inst field.ty))
  in
  record, fields, complete
;;

(* Returns the field, the instantiated record type and the field's type. *)
let field_type t (scope : Scope.t) field ~record ~loc =
  let%bind.Result known = Known.record scope record in
  let%map.Result (field : Type_env.Field.t) =
    find_field scope field ~loc ~known
  in
  let inst = Scope.instantiate t scope in
  let ty = inst field.ty in
  field_ref field, inst field.record, ty
;;

(* Rows of polymorphic records and variants, whose entries are [Present]. *)
module Poly_row = struct
  let present entries ~tail =
    List.fold_right entries ~init:tail ~f:(fun (label, ty) rest ->
      Type.RExtend (label, Present, Absent, ty, rest))
  ;;

  (* [entries] before a fresh tail, which is also returned. *)
  let open_ t scope entries =
    let tail = Scope.fresh_row t scope in
    present entries ~tail, tail
  ;;

  let variant t scope ~tag ~arg =
    Fresh.variant t (fst (open_ t scope [ tag, arg ]))
  ;;

  let report_duplicate_labels scope entries =
    report_duplicates scope (List.map entries ~f:fst) ~error:(fun label ->
      Duplicate_row_entry label)
  ;;
end

module Pattern_var = struct
  type t =
    { ident : Typed.Ident.t
    ; ty : Type.ty
    ; loc : Loc.t
    ; modality : Modality.t (** Of the part of the scrutinee it is bound to. *)
    }

  let under modality =
    List.map ~f:(fun t ->
      { t with modality = Modality.compose modality t.modality })
  ;;
end

(* The components of [expected], if it is known to be a tuple of [n]. *)
let tuple_components (expected : Type.ty option) n =
  match Option.map expected ~f:Type.canonical_ty with
  | Some (TTuple tys) when List.length tys = n -> List.map tys ~f:Option.some
  | Some _ | None -> List.init n ~f:(fun _ -> None)
;;

(* The type of [label] in [expected], if it is known to be a polymorphic record
   ([`Record]) or variant ([`Variant]) with it. *)
let row_entry (expected : Type.ty option) kind ~label =
  let rec find (row : Type.row) =
    match Type.canonical_row row with
    | RExtend (label', _, _, ty, rest) ->
      if String.equal label label' then Some ty else find rest
    | REmpty | RVar _ -> None
  in
  match Option.map expected ~f:Type.canonical_ty, kind with
  | Some (TRecord { row; _ }), `Record | Some (TVariant { row; _ }), `Variant ->
    find row
  | _ -> None
;;

(* [ty] if it is known, else [fallback]. *)
let either_known ty fallback =
  match Type.canonical_ty ty with
  | TVar _ -> fallback
  | _ -> Some ty
;;

(* [expected] is the type the pattern or expression is known to have where it is
   (it is not unified with it here): constructors and fields are looked up in it
   when it is a nominal type (see [Known]). *)
let rec pattern_type ?expected t (scope : Scope.t) ~(pattern : Source.Pattern.t)
  : Typed.Pattern.t * Pattern_var.t list
  =
  let loc = Source.Pattern.loc pattern in
  let node desc ty = { Typed.Pattern.desc; ty; loc } in
  let bind binder ty =
    let ident = Program_env.bind scope.program binder ty ~level:scope.level in
    ( ident
    , { Pattern_var.ident
      ; ty
      ; loc = Source.Binder.loc binder ~enclosing:loc
      ; modality = Id
      } )
  in
  (* Each pattern of type [ty], known to be of [expected] (by default [ty]), of
     a part of the block through [modalities]. *)
  let sub_patterns ?expected patterns ~modalities =
    let expected =
      Option.value
        expected
        ~default:(List.map patterns ~f:(fun (_, ty) -> Some ty))
    in
    let typed =
      List.map3_exn
        patterns
        expected
        modalities
        ~f:(fun (pattern, ty) expected modality ->
          let pattern, bindings = pattern_type t scope ~pattern ?expected in
          ( (if Scope.unifies t scope ~ty1:ty ~ty2:pattern.ty ~loc:pattern.loc
             then pattern
             else Typed.Pattern.error [ pattern ] ~loc:pattern.loc)
          , Pattern_var.under modality bindings ))
    in
    List.map typed ~f:fst, List.concat_map typed ~f:snd
  in
  (* What did not check binds its variables still, so that their uses are not
     errors too. *)
  let fail error patterns =
    Scope.report scope error;
    let patterns, bindings =
      sub_patterns
        (List.map patterns ~f:(fun pattern -> pattern, Scope.fresh_ty t scope))
        ~modalities:(List.map patterns ~f:(fun _ -> Modality.Id))
    in
    Typed.Pattern.error patterns ~loc, bindings
  in
  match Source.Pattern.view pattern with
  | Any -> node Any (Scope.fresh_ty t scope), []
  | Var binder ->
    let ty = Scope.fresh_ty t scope in
    let ident, var = bind binder ty in
    node (Var ident) ty, [ var ]
  | Lit lit -> node (Lit lit) (Syntax.Lit.ty lit), []
  | Deref inner ->
    let expected =
      Option.bind expected ~f:(fun ty ->
        match Type.canonical_ty ty with
        | TCon ("ptr", [ ATy pointee ]) -> Some pointee
        | _ -> None)
    in
    let inner, bindings = pattern_type t scope ~pattern:inner ?expected in
    ( node (Deref inner) (Type.TCon ("ptr", [ ATy inner.ty ]))
    , Pattern_var.under Global bindings )
  | Tuple patterns ->
    let types = List.map patterns ~f:(fun _ -> Scope.fresh_ty t scope) in
    let patterns, bindings =
      sub_patterns
        (List.zip_exn patterns types)
        ~expected:(tuple_components expected (List.length patterns))
        ~modalities:(List.map patterns ~f:(fun _ -> Modality.Id))
    in
    node (Tuple patterns) (Type.TTuple types), bindings
  | Construct (constructor, args) ->
    (match
       constructor_types
         t
         scope
         constructor
         ~args
         ~tuple:Source.Pattern.tuple
         ~expected
         ~loc
     with
     | Error error -> fail error args
     | Ok (constructor, args, result) ->
       let args, bindings =
         sub_patterns
           (List.map args ~f:(fun (arg, ty, _) -> arg, ty))
           ~modalities:(List.map args ~f:(fun (_, _, modality) -> modality))
       in
       node (Construct (constructor, args)) result, bindings)
  | Record fields ->
    (match record_fields t scope fields ~all_required:false ~expected ~loc with
     | Error error -> fail error (List.map fields ~f:snd)
     | Ok (record, fields, (_ : bool)) ->
       let modalities =
         List.map fields ~f:(fun ((field : Typed.Field_ref.t), _) ->
           Type_env.field_modality
             scope.program.type_env
             (Typed.Field_ref.name field))
       in
       let patterns, bindings =
         sub_patterns (List.map fields ~f:snd) ~modalities
       in
       ( node (Record (List.zip_exn (List.map fields ~f:fst) patterns)) record
       , bindings ))
  | Poly_variant (tag, arg) ->
    let arg, bindings =
      match arg with
      | None -> None, []
      | Some pattern ->
        let pattern, bindings =
          pattern_type
            t
            scope
            ~pattern
            ?expected:(row_entry expected `Variant ~label:tag)
        in
        Some pattern, bindings
    in
    let arg_ty =
      Option.value_map arg ~default:Type.unit ~f:(fun pattern -> pattern.ty)
    in
    ( node (Poly_variant (tag, arg)) (Poly_row.variant t scope ~tag ~arg:arg_ty)
    , bindings )
  | Poly_record { fields; rest } ->
    Poly_row.report_duplicate_labels scope fields;
    let fields =
      List.map fields ~f:(fun (label, pattern) ->
        ( label.txt
        , pattern_type
            t
            scope
            ~pattern
            ?expected:(row_entry expected `Record ~label:label.txt) ))
    in
    let bindings =
      List.concat_map fields ~f:(fun (_, (_, bindings)) -> bindings)
    in
    let fields =
      List.map fields ~f:(fun (label, (pattern, _)) -> label, pattern)
    in
    let tail, rest, rest_bindings =
      match rest with
      | Closed -> Type.REmpty, Typed.Pattern.Rest.Closed, []
      | Open -> Scope.fresh_row t scope, Open, []
      | Bind binder ->
        let tail = Scope.fresh_row t scope in
        let ident, var = bind binder (Fresh.record t tail) in
        tail, Bind ident, [ var ]
    in
    let row =
      Poly_row.present
        (List.map fields ~f:(fun (label, (pattern : Typed.Pattern.t)) ->
           label, pattern.ty))
        ~tail
    in
    ( node (Poly_record { fields; rest }) (Fresh.record t row)
    , bindings @ rest_bindings )
  | Exception pattern ->
    fail (Typecheck_error.create ~loc Misplaced_exception_pattern) [ pattern ]
;;

(* Closing of the scrutinee and residuals of catch-alls in matches on
   polymorphic variants. *)
module Variant_match = struct
  (* The tags handled irrefutably by the cases so far, in order, each once. *)
  type t = string list

  let empty = []

  (* A top level variable pattern matches what the handled tags' cases have not:
     the scrutinee without their first entries. *)
  let pattern_type
    t
    (scope : Scope.t)
    handled
    ~(pattern : Source.Pattern.t)
    ~scrutinee
    =
    match Source.Pattern.view pattern, handled with
    | Var binder, _ :: _ ->
      let row, rest =
        Poly_row.open_
          t
          scope
          (List.map handled ~f:(fun tag -> tag, Scope.fresh_ty t scope))
      in
      let rest = Fresh.variant t rest in
      let ident =
        Program_env.bind scope.program binder rest ~level:scope.level
      in
      ( { Typed.Pattern.desc = Var ident
        ; ty = Fresh.variant t row
        ; loc = Source.Pattern.loc pattern
        }
      , [ { Pattern_var.ident
          ; ty = rest
          ; loc =
              Source.Binder.loc binder ~enclosing:(Source.Pattern.loc pattern)
          ; modality = Id
          }
        ] )
    | _ -> pattern_type t scope ~pattern ~expected:scrutinee
  ;;

  let add_case handled ({ desc; ty = _; loc = _ } : Typed.Pattern.t) =
    match desc with
    | Poly_variant (tag, arg)
      when Option.for_all arg ~f:Typed.Pattern.is_irrefutable
           && not (List.mem handled tag ~equal:String.equal) ->
      handled @ [ tag ]
    | _ -> handled
  ;;

  let is_empty_nominal (scope : Scope.t) scrutinee =
    match Type.canonical_ty scrutinee with
    | TCon (name, _) -> Type_env.is_empty_variant scope.program.type_env name
    | _ -> Ok false
  ;;

  (* Without a top level catch-all, a variant scrutinee may only have the tags
     of the cases, and an empty match's none, unless the scrutinee is already
     known to be an empty nominal type. *)
  let close
    t
    (scope : Scope.t)
    ~scrutinee
    ~loc
    (patterns : Typed.Pattern.t list)
    =
    let patterns =
      List.map patterns ~f:(fun (pattern : Typed.Pattern.t) -> pattern.desc)
    in
    let tags =
      List.filter_map patterns ~f:(function
        | Poly_variant (tag, _) -> Some tag
        | _ -> None)
      |> List.stable_dedup ~compare:String.compare
    in
    let has_catch_all =
      List.exists patterns ~f:(function
        | Var _ | Any -> true
        | _ -> false)
    in
    let%bind.Result open_ =
      match patterns with
      | [] -> is_empty_nominal scope scrutinee
      | _ :: _ -> Ok (has_catch_all || List.is_empty tags)
    in
    if open_
    then Ok ()
    else (
      let closed =
        Poly_row.present
          (List.map tags ~f:(fun tag -> tag, Scope.fresh_ty t scope))
          ~tail:REmpty
      in
      Unify.unify_ty t ~ty1:(Fresh.variant t closed) ~ty2:scrutinee |> lift ~loc)
  ;;
end

let use_entry (scope : Scope.t) ~at (entry : Env.Entry.t) ~name ~loc =
  Mode_rules.use
    (Scope.modes scope)
    at
    entry
    ~locks:scope.locks
    ~toplevel:
      (match entry.binder with
       | Toplevel _ -> true
       | Local _ -> false)
    ~name
    ~loc
    ~mutable_captured_in_exclave:(fun () ->
      Scope.report
        scope
        (Typecheck_error.create ~loc (Mutable_captured_in_exclave name)))
;;

let field_modality (scope : Scope.t) field =
  Type_env.field_modality scope.program.type_env (Typed.Field_ref.name field)
;;

let use_free (scope : Scope.t) ~at ~why ~loc =
  Mode_rules.use_free (Scope.modes scope) at ~locks:scope.locks ~loc ~why
;;

(* A closure computes nothing, so is generalized whatever it captures; other
   values only when [const], which is then required of them. *)
let generalizes (scope : Scope.t) mode ~is_function ~loc =
  is_function
  || (Mode.Stage.le (Scope.known_stage scope mode) Const
      && Mode_rules.const (Scope.modes scope) mode ~loc ~why:"it is generalized"
     )
;;

(* [name] is the context entry the variable is provided as, if it becomes a free
   variable of the quote: a local's name or a toplevel's canonical name. *)
let resolution_type t (scope : Scope.t) ~at ~name ~toplevel ~loc
  : Resolution.t -> _
  = function
  | Local entry ->
    use_entry scope ~at entry ~name ~loc;
    Ok (Scope.instantiate t scope entry.scheme, Typed.Var_ref.Bound entry.binder)
  | Outside_quote { usable = Some entry; _ } ->
    use_entry scope ~at entry ~name ~loc;
    Ok (Scope.instantiate t scope entry.scheme, Persistent entry.binder)
  | Outside_quote { quote; usable = None; unusable } ->
    Option.iter unusable ~f:(fun entry ->
      Hashtbl.set
        scope.program.unusable_in_quotes
        ~key:name
        ~data:{ loc; var_level = entry.level; used_at = scope.level });
    use_free
      scope
      ~at
      ~why:(sprintf "%s is a free variable of the quote" name)
      ~loc;
    let%map.Result ty =
      Unify.present_entry t ~row:quote.context ~name ~rank:quote.outside.rank
      |> lift ~loc
    in
    ty, if toplevel then Typed.Var_ref.Free_toplevel name else Free name
  | Unusable kind -> error ~loc kind
;;

(* Calls [f] on each use of a toplevel that evaluating [expr] (at [depth] quotes
   in) may need: not those in a function it only builds, nor in the code a quote
   builds (but those in the splices that run while it does). [built] is whether
   [expr]'s value is only built by what encloses it, rather than maybe called
   (or otherwise looked into): [f ~called:false] uses only need the toplevel's
   value. Returns the locals it may call (or look into). *)
let rec eager_uses (expr : Typed.Expr.t) ~depth ~built ~f : Typed.Ident.Set.t =
  let go = eager_uses ~f in
  let all ~built exprs =
    Typed.Ident.Set.union_list (List.map exprs ~f:(go ~depth ~built))
  in
  let use ~built (binder : Typed.Binder.t) =
    match binder with
    | _ when depth <> 0 -> Typed.Ident.Set.empty
    | Toplevel ident ->
      f ident ~called:(not built) expr.loc;
      Typed.Ident.Set.empty
    | Local ident ->
      if built then Typed.Ident.Set.empty else Typed.Ident.Set.singleton ident
  in
  match expr.desc with
  | Var (Bound binder | Persistent binder) -> use ~built binder
  | Assign ((Bound binder | Persistent binder), value) ->
    Set.union (use ~built:true binder) (go value ~depth ~built:false)
  | Quote body -> go body ~depth:(depth + 1) ~built:false
  | Splice { code; subs } ->
    Set.union
      (go code ~depth:(depth - 1) ~built:false)
      (match subs with
       | Explicit subs -> all ~built:false (List.map subs ~f:snd)
       | Implicit providers ->
         Map.data providers
         |> List.map ~f:(use ~built:false)
         |> Typed.Ident.Set.union_list)
  | Toplevel_splice { expansion; code = _ } -> go expansion ~depth ~built
  | Fun _ when depth = 0 && built -> Typed.Ident.Set.empty
  | Let { ident; args; body; in_; _ } when depth = 0 ->
    let called = go in_ ~depth ~built in
    (* [ident]'s value is only built if [in_] only builds what it uses it in. *)
    let only_built = not (Set.mem called ident) in
    let body =
      if List.is_empty args
      then go body ~depth ~built:only_built
      else if not only_built
      then go body ~depth ~built:false
      else Typed.Ident.Set.empty
    in
    Set.remove (Set.union called body) ident
  | Let_mut { body; in_; _ } ->
    Set.union (go body ~depth ~built:false) (go in_ ~depth ~built)
  | Match { scrutinee; cases; exception_cases } ->
    Set.union
      (go scrutinee ~depth ~built:false)
      (all ~built (List.map (cases @ exception_cases) ~f:snd))
  | Annotated _
  | Tuple _
  | Construct _
  | Record _
  | Poly_record _
  | Poly_variant _ -> all ~built (Typed.Expr.sub_exprs expr)
  | _ -> all ~built:false (Typed.Expr.sub_exprs expr)
;;

(* The toplevels [expr] uses when run, rather than in the code it builds or at
   compile time. *)
let rec run_toplevels (expr : Typed.Expr.t) ~depth ~f =
  let go = run_toplevels ~f in
  match expr.desc with
  | Var (Bound (Toplevel ident) | Persistent (Toplevel ident)) ->
    if depth = 0 then f ident
  | Assign ((Bound (Toplevel ident) | Persistent (Toplevel ident)), value) ->
    if depth = 0 then f ident;
    go value ~depth
  | Quote body -> go body ~depth:(depth + 1)
  | Splice { code; subs } ->
    go code ~depth:(depth - 1);
    (match subs with
     | Explicit subs -> List.iter subs ~f:(fun (_, sub) -> go sub ~depth)
     | Implicit _ -> ())
  | Toplevel_splice { code = _; expansion } -> go expansion ~depth
  | _ -> List.iter (Typed.Expr.sub_exprs expr) ~f:(go ~depth)
;;

module Init_need = struct
  (* A toplevel's value, or everything calling (or looking into) it may need. *)
  type t =
    | Value of Typed.Ident.t
    | Call of Typed.Ident.t
  [@@deriving compare, sexp_of]

  include functor Comparable.Make_plain

  let ident (Value ident | Call ident) = ident
end

(* A toplevel's value is computed when first needed, after its component's
   functions are bound: it can't be if computing it may need it again. Calls are
   assumed to need everything the callee refers to. *)
let check_initialization_cycles
  (program : Program_env.t)
  (members : Typed.Toplevel.t list)
  =
  let member ident =
    List.find members ~f:(fun (member : Typed.Toplevel.t) ->
      Typed.Ident.equal member.ident ident)
  in
  let is_function (member : Typed.Toplevel.t) =
    not (List.is_empty member.args)
  in
  (* Each need's direct needs, with where they are needed. *)
  let needs (need : Init_need.t) =
    let found = Queue.create () in
    let add need loc = Queue.enqueue found (need, loc) in
    (match need with
     | Value ident ->
       let toplevel = Option.value_exn (member ident) in
       if not (is_function toplevel)
       then
         eager_uses
           toplevel.body
           ~depth:0
           ~built:true
           ~f:(fun ident ~called loc ->
             match member ident with
             | None -> ()
             | Some used ->
               if called
               then add (Init_need.Call ident) loc
               else if not (is_function used)
               then add (Init_need.Value ident) loc)
         |> (ignore : Typed.Ident.Set.t -> unit)
     | Call ident ->
       let toplevel = Option.value_exn (member ident) in
       add (Value ident) toplevel.body.loc;
       run_toplevels toplevel.body ~depth:0 ~f:(fun used ->
         if Option.is_some (member used) then add (Call used) toplevel.body.loc));
    Queue.to_list found
  in
  List.fold members ~init:false ~f:(fun failed (toplevel : Typed.Toplevel.t) ->
    if failed || is_function toplevel
    then failed
    else (
      let start = Init_need.Value toplevel.ident in
      (* Breadth first, for the shortest cycle. *)
      let parent = ref Init_need.Map.empty in
      let queue = Queue.create () in
      let found = ref None in
      Queue.enqueue queue start;
      while Option.is_none !found && not (Queue.is_empty queue) do
        let current = Queue.dequeue_exn queue in
        List.iter (needs current) ~f:(fun (need, loc) ->
          if Option.is_none !found
          then
            if [%compare.equal: Init_need.t] need start
            then found := Some (current, loc)
            else if not (Map.mem !parent need)
            then (
              parent := Map.set !parent ~key:need ~data:(current, loc);
              Queue.enqueue queue need))
      done;
      match !found with
      | None -> failed
      | Some (last, last_loc) ->
        let rec path need acc =
          if [%compare.equal: Init_need.t] need start
          then need :: acc
          else path (fst (Map.find_exn !parent need)) (need :: acc)
        in
        let chain = path last [] in
        (* Where the first step is needed, in [toplevel]'s own body. *)
        let loc =
          match chain with
          | _ :: second :: _ -> snd (Map.find_exn !parent second)
          | [ _ ] | [] -> last_loc
        in
        let names =
          List.remove_consecutive_duplicates
            (List.map chain ~f:(fun need -> (Init_need.ident need).name)
             @ [ toplevel.ident.name ])
            ~equal:String.equal
        in
        let names =
          match names with
          | [ name ] -> [ name; name ]
          | names -> names
        in
        Program_env.report
          program
          (Typecheck_error.create ~loc (Toplevel_initialization_cycle names));
        true))
;;

(* The mutable toplevel a component may use when run, if any. *)
let runtime_only (program : Program_env.t) (members : Toplevel.t list) =
  let in_component (ident : Typed.Ident.t) =
    List.exists members ~f:(fun member -> Typed.Ident.equal member.ident ident)
  in
  List.find_map members ~f:(fun member ->
    if member.mut
    then Some member.ident.name
    else (
      match member.state with
      | In_progress { body = Some body; _ } ->
        With_return.with_return (fun { return } ->
          run_toplevels body ~depth:0 ~f:(fun ident ->
            if not (in_component ident)
            then (
              match (Program_env.toplevel program ident.name).state with
              | Done { runtime_only = Some global; _ } -> return (Some global)
              | Done { runtime_only = None; _ } | Unchecked | In_progress _ ->
                ()));
          None)
      | In_progress { body = None; _ } | Unchecked | Done _ -> None))
;;

let finish_scc t (program : Program_env.t) (members : Toplevel.t list) ~failed =
  let failed =
    failed
    || check_initialization_cycles
         program
         (List.filter_map members ~f:(fun member ->
            match member.state with
            | In_progress { ty; args; body = Some body; _ } ->
              Some
                { Typed.Toplevel.ident = member.ident
                ; mut = member.mut
                ; args
                ; scheme = ty
                ; body
                }
            | In_progress { body = None; _ } | Unchecked | Done _ -> None))
  in
  let runtime_only = runtime_only program members in
  let init_mode (member : Toplevel.t) =
    match member.state with
    | In_progress { init_mode; _ } -> init_mode
    | Unchecked | Done _ ->
      raise_s [%message "finish_scc: member not checked" (member : Toplevel.t)]
  in
  let const (member : Toplevel.t) ~why =
    Mode_rules.const
      (Mode_rules.Ctx.create
         ~modes:program.modes
         ~rank:0
         ~holds:(fun ~loc -> function
           | Ok () -> true
           | Error error ->
             Program_env.report
               program
               (Module_scope.within
                  member.module_
                  (Typecheck_error.create ~loc (Mode_error error)));
             false)
         ~crossing:(fun _ -> Mode.Crossing.none))
      (init_mode member)
      ~loc:member.expr.loc
      ~why:(why member.ident.name)
  in
  if program.const_toplevels
  then
    List.iter members ~f:(fun member ->
      ignore (const member ~why:(sprintf "%s is a toplevel") : bool));
  let all_functions = List.for_all members ~f:Toplevel.is_function in
  let recursive =
    List.exists members ~f:(fun member ->
      match member.state with
      | In_progress { recursive; _ } -> recursive
      | Unchecked | Done _ -> false)
  in
  (* Like OCaml's [let rec], a recursive non-function is not generalized. *)
  let generalize =
    (all_functions || not recursive)
    && List.for_all members ~f:(fun member ->
      Toplevel.is_function member
      || ((not member.mut)
          && Mode.Stage.le (Mode.Var.lower (init_mode member)).stage Const))
    && List.for_all members ~f:(fun member ->
      Toplevel.is_function member
      || const member ~why:(sprintf "%s is generalized"))
  in
  if generalize
  then
    Scheme.generalize
      t
      ~rank:0
      (List.map members ~f:(fun member ->
         match member.state with
         | In_progress { ty; _ } -> ty
         | Unchecked | Done _ ->
           raise_s
             [%message "finish_scc: member not checked" (member : Toplevel.t)]));
  let members =
    List.map members ~f:(fun member ->
      match member.state with
      | In_progress { index; ty; args; mode; held; body = Some body; _ } ->
        Program_env.add_info program member.ident ~ty ~level:0;
        let typed =
          { Typed.Toplevel.ident = member.ident
          ; mut = member.mut
          ; args
          ; scheme = ty
          ; body
          }
        in
        member.state
        <- Done
             { entry =
                 Env.Entry.toplevel
                   ~defining:false
                   ~ident:member.ident
                   ~scheme:ty
                   ~mode
                   ~held
             ; typed
             ; failed
             ; runtime_only
             };
        index, typed
      | In_progress { body = None; _ } | Unchecked | Done _ ->
        raise_s
          [%message "finish_scc: member not checked" (member : Toplevel.t)])
    |> List.sort ~compare:(Comparable.lift Int.compare ~f:fst)
    |> List.map ~f:snd
  in
  let idents =
    Typed.Ident.Set.of_list
      (List.map members ~f:(fun (member : Typed.Toplevel.t) -> member.ident))
  in
  let scc =
    { Typed.Scc.members
    ; recursive =
        List.exists members ~f:(fun member ->
          Typed.Expr.refers_to member.body ~f:(function
            | Toplevel ident -> Set.mem idents ident
            | Local _ -> false))
    }
  in
  Queue.enqueue program.sccs scc;
  Interpreter.add_scc program.interpreter scc
;;

let intrinsic_type t (scope : Scope.t) (intrinsic : Intrinsic.t) =
  match intrinsic with
  | Assume_global ->
    (* Only its locality is assumed. *)
    let ty = Scope.fresh_ty t scope in
    let arg, res = Mode_rules.assume_global (Scope.modes scope) in
    Type.TArrow
      ( ty
      , ty
      , { arg = Var arg; res = Var res; curry = Arrow_modes.default_curry } )
  | Ptr_make ->
    let pointee = Scope.fresh_ty t scope in
    let arg, res = Mode_rules.ptr_make (Scope.modes scope) in
    Type.TArrow
      ( pointee
      , TCon ("ptr", [ ATy pointee ])
      , { arg = Var arg; res = Var res; curry = Arrow_modes.default_curry } )
  | _ ->
    Intrinsic.ty
      intrinsic
      ~var:(fun () -> Scope.fresh_ty t scope)
      ~row:(fun () -> Scope.fresh_row t scope)
;;

let is_syntax ty =
  match Type.canonical_ty ty with
  | TCon (name, []) -> String.equal name (Prelude_path.canonical "Stag.Expr.t")
  | _ -> false
;;

let rec var_type t (scope : Scope.t) ~at ~(path : Syntax.Decl_path.t) ~loc =
  let resolve ~name entry =
    resolution_type
      t
      scope
      ~at
      ~name
      ~toplevel:false
      ~loc
      (Resolution.of_entry scope ~name entry)
  in
  let local =
    match path with
    | Path path ->
      (match (path :> string list) with
       | [ name ] ->
         Env.find scope.locals name |> Option.map ~f:(fun entry -> name, entry)
       | _ -> None)
    | Root _ | Resolved _ -> None
  in
  match local with
  | Some (name, entry) -> resolve ~name (Some entry)
  | None ->
    (match%bind.Result Module_scope.find_value scope.module_ path ~loc with
     | Toplevel name ->
       toplevel_type t scope ~at (Program_env.toplevel scope.program name) ~loc
     | Prim prim -> Ok (Prim.ty prim, Typed.Var_ref.Prim prim)
     | Intrinsic intrinsic ->
       Ok (intrinsic_type t scope intrinsic, Typed.Var_ref.Intrinsic intrinsic)
     | Unbound ->
       (match scope.quote with
        | Some _ -> resolve ~name:(Syntax.Decl_path.to_string path) None
        | None -> Error (Module_scope.unbound_value scope.module_ path ~loc)))

and toplevel_type t scope ~at (toplevel : Toplevel.t) ~loc =
  let%bind.Result entry = toplevel_entry t scope toplevel ~loc in
  let name = toplevel.ident.name in
  resolution_type
    t
    scope
    ~at
    ~name
    ~toplevel:true
    ~loc
    (Resolution.of_entry scope ~name (Some entry))

(* A [Stag.Value_ref.t]'s canonical name, resolved where the code it was erased
   from was checked, so not looked up in [scope]. *)
and resolved_value_type t (scope : Scope.t) ~at name ~loc =
  match
    Prim.of_canonical_name name, Program_env.find_toplevel scope.program name
  with
  | Some prim, _ -> Ok (Prim.ty prim, Typed.Var_ref.Prim prim)
  | None, Some toplevel -> toplevel_type t scope ~at toplevel ~loc
  | None, None -> error ~loc (Not_in_scope (Path (Syntax.Path.of_string name)))

(* Generated code's variables are already resolved, so are found by binder
   rather than by name, which may be shadowed. *)
and var_ref_type t (scope : Scope.t) ~at (var_ref : Typed.Var_ref.t) ~loc =
  let resolve ~name ~toplevel entry =
    resolution_type
      t
      scope
      ~at
      ~name
      ~toplevel
      ~loc
      (Resolution.of_entry scope ~name (Some entry))
  in
  let not_in_scope name =
    error ~loc (Not_in_scope (Path (Syntax.Path.of_string name)))
  in
  match var_ref with
  | Prim prim -> Ok (Prim.ty prim, var_ref)
  | Intrinsic intrinsic -> Ok (intrinsic_type t scope intrinsic, var_ref)
  | (Free name | Free_toplevel name) as var_ref ->
    (match scope.quote with
     | Some quote ->
       resolution_type
         t
         scope
         ~at
         ~name
         ~toplevel:
           (match var_ref with
            | Free_toplevel _ -> true
            | _ -> false)
         ~loc
         (Outside_quote { quote; usable = None; unusable = None })
     | None -> not_in_scope name)
  | Bound (Toplevel ident) | Persistent (Toplevel ident) ->
    let%bind.Result entry =
      toplevel_entry
        t
        scope
        (Program_env.toplevel scope.program ident.name)
        ~loc
    in
    resolve ~name:ident.name ~toplevel:true entry
  | Bound (Local ident as binder) | Persistent (Local ident as binder) ->
    (match Env.find_binder scope.locals binder ~name:ident.name with
     | Some entry -> resolve ~name:ident.name ~toplevel:false entry
     | None ->
       (match Program_env.embedded scope.program ident with
        | Some info ->
          use_entry
            scope
            ~at
            { scheme = info.ty
            ; level = 0
            ; quote_id = None
            ; mode =
                Mode_rules.Binding.embedded
                  (Scope.modes scope)
                  ~name:ident.name
                  ~loc
            ; held = None
            ; locks = []
            ; binder
            ; defining = false
            }
            ~name:ident.name
            ~loc;
          Ok (Scope.instantiate t scope info.ty, Typed.Var_ref.Persistent binder)
        | None -> not_in_scope ident.name))

(* Toplevels may be used from code run at compile time, as if bound at its
   level, once they can be evaluated. *)
and toplevel_entry t (scope : Scope.t) (toplevel : Toplevel.t) ~loc =
  let at_scope_level (entry : Env.Entry.t) =
    { entry with level = Int.min entry.level scope.level }
  in
  match toplevel.state with
  | Done { failed = true; _ } when scope.level < 0 && Option.is_none scope.quote
    ->
    (* Code that did not check is not run. *)
    scope.scc.failed <- true;
    Error Typecheck_error.already_reported
  | Done { runtime_only = Some global; _ }
    when scope.level < 0 && Option.is_none scope.quote ->
    error
      ~loc
      (Compile_time_use_of_mutable
         { toplevel = toplevel.ident.name; mutable_ = global })
  | Done { entry; failed; typed = _; runtime_only = _ } ->
    if failed then scope.scc.failed <- true;
    Ok (at_scope_level entry)
  | In_progress in_progress ->
    let entry ?(defining = false) mode =
      Env.Entry.toplevel
        ~defining
        ~ident:toplevel.ident
        ~scheme:in_progress.ty
        ~mode
        ~held:in_progress.held
    in
    (match scope.quote with
     | Some _ when not toplevel.mut ->
       (* Its mode isn't known yet, so it is a free variable of the quote: the
          quote's value doesn't depend on [toplevel]. *)
       Ok
         (at_scope_level
            (entry
               (Mode_rules.Binding.being_checked
                  (Scope.modes scope)
                  ~name:toplevel.ident.name
                  ~loc)))
     | None when scope.level < 0 ->
       (match Stack.top scope.program.splice_starts with
        | Some start when in_progress.index < start || scope.scc.lowlink < start
          -> raise Uses_unfinished
        | Some _ | None ->
          error
            ~loc
            (Compile_time_use_of_toplevel_being_checked toplevel.ident.name))
     | Some _ | None ->
       (* [toplevel] is in the component being checked, so this is a recursive
          reference. A function captures nothing (toplevels are referred to by
          symbol), so its mode is already known. *)
       in_progress.recursive <- true;
       scope.scc.lowlink <- Int.min scope.scc.lowlink in_progress.index;
       Ok
         (entry
            ~defining:(not (Toplevel.is_function toplevel))
            in_progress.mode))
  | Unchecked ->
    let scc = check_toplevel t scope.program toplevel in
    scope.scc.lowlink <- Int.min scope.scc.lowlink scc.lowlink;
    scope.scc.pending <- scc.pending @ scope.scc.pending;
    if scc.failed then scope.scc.failed <- true;
    toplevel_entry t scope toplevel ~loc

and check_toplevel t program (toplevel : Toplevel.t) : Scc_frame.t =
  let index = Fresh.id t in
  let scc = Scc_frame.create index ~pending:[ toplevel ] in
  let unfinished = Stack.length program.unfinished in
  let reported = program.reported in
  let rank = 1 in
  let scope =
    { Scope.program
    ; level = 0
    ; rank
    ; locals = Env.create ()
    ; quote = None
    ; module_ = toplevel.module_
    ; scc
    ; annotation_vars = Type_env.Annotation_vars.create t ~rank
    ; in_expect_test = false
    ; generated = toplevel.generated
    ; syntax_splice = None
    ; locks = []
    ; params = []
    }
  in
  let modes = Scope.modes scope in
  let fn =
    function_type
      t
      scope
      ~args:(List.map toplevel.args ~f:Source.Expr.binding)
      ~annot:toplevel.annot
      ~res_mode:(if Toplevel.is_function toplevel then toplevel.mode else None)
      ~body:(Source.Expr.Syntax toplevel.expr)
      ~loc:toplevel.expr.loc
  in
  let { Function_type.args; res_ty; ty; _ } = fn in
  match toplevel.state with
  | In_progress _ | Done _ ->
    (* Checked while elaborating its annotations, through a type splice that
       uses it: the cycle is reported. *)
    Scc_frame.create index ~pending:[]
  | Unchecked ->
    Stack.push program.unfinished ty;
    let loc = toplevel.expr.loc in
    let name = toplevel.ident.name in
    let rules =
      Mode_rules.Toplevel.create
        modes
        ~is_function:(Toplevel.is_function toplevel)
        ~mut:toplevel.mut
        toplevel.mode
        ~var:(Scope.mode_var scope)
        ~name
        ~loc
    in
    toplevel.state
    <- In_progress
         { index
         ; ty
         ; args = List.map args ~f:fst
         ; mode = rules.binding
         ; init_mode = rules.value
         ; held = rules.held
         ; body = None
         ; recursive = false
         };
    let body =
      match
        match toplevel.external_ with
        | Some external_ -> check_external t scope external_ ~ty:res_ty
        | None when Toplevel.is_function toplevel ->
          check_body t scope ~closure:rules.value ~fn ~loc:toplevel.expr.loc
        | None ->
          check_expr
            t
            scope
            ~at:rules.expected
            ~expr:(Source.Expr.Syntax toplevel.expr)
            ~ty:res_ty
      with
      | body -> body
      | exception Uses_unfinished ->
        abandon program scc ~unfinished;
        raise Uses_unfinished
    in
    Mode_rules.Toplevel.outlives modes rules ~ty ~name ~loc;
    if program.reported > reported then scc.failed <- true;
    (match toplevel.state with
     | In_progress in_progress -> in_progress.body <- Some body
     | Unchecked | Done _ ->
       raise_s
         [%message "check_toplevel: not in progress" (toplevel : Toplevel.t)]);
    if scc.lowlink = index
    then (
      finish_scc t program scc.pending ~failed:scc.failed;
      scc.pending <- [];
      while Stack.length program.unfinished > unfinished do
        Unify.lower_ty ~rank:0 (Stack.pop_exn program.unfinished)
      done);
    scc

(* Its modes are as declared: C code is trusted to keep to them. *)
and check_external
  t
  (scope : Scope.t)
  ({ ty = declared; symbol } : Toplevel.External.t)
  ~ty
  : Typed.Expr.t
  =
  let loc = Loc.merge declared.loc symbol.loc in
  let error error =
    Scope.report scope error;
    ignore (Scope.unifies t scope ~ty1:ty ~ty2:Type.error ~loc : bool);
    { Typed.Expr.desc = Error []; ty; loc }
  in
  match
    Type_env.elaborate_declared scope.program.type_env scope.module_ declared
  with
  | Error e -> error e
  | Ok declared_ty ->
    (match C_signature.of_type declared_ty with
     | Error problem ->
       error
         (Typecheck_error.create
            ~loc:declared.loc
            (Invalid_external { symbol = symbol.txt; problem }))
     | Ok signature ->
       ignore (Scope.unifies t scope ~ty1:ty ~ty2:declared_ty ~loc : bool);
       { desc = External { symbol = symbol.txt; signature }; ty; loc })

(* Abandons the toplevels of [scc] with the splice whose code reached them, to
   be checked anew. *)
and abandon (program : Program_env.t) (scc : Scc_frame.t) ~unfinished =
  Program_env.forget
    program
    ~frames:
      (scc.id
       :: List.filter_map scc.pending ~f:(fun (toplevel : Toplevel.t) ->
         match toplevel.state with
         | In_progress { index; _ } -> Some index
         | Unchecked | Done _ -> None));
  List.iter scc.pending ~f:(fun (toplevel : Toplevel.t) ->
    toplevel.state <- Unchecked);
  scc.pending <- [];
  while Stack.length program.unfinished > unfinished do
    ignore (Stack.pop_exn program.unfinished : Type.ty)
  done

(* A function's body, in a closure of mode [closure]. Its parameters are of the
   modes of its arrows' arguments, and its value of the last one's result. The
   closure of a partial application holds what the function captures and the
   arguments given so far. *)
and check_body t (scope : Scope.t) ~closure ~(fn : Function_type.t) ~loc =
  Mode_rules.Function.partial_applications
    (Scope.modes scope)
    ~closure
    ~arg_modes:fn.arg_modes
    ~partial_modes:fn.partial_modes
    ~loc;
  let fn_params = Function_type.params fn in
  let scope =
    { (Scope.enter_closure t scope closure) with
      params = List.map fn_params ~f:snd @ scope.params
    }
  in
  let modes = Scope.modes scope in
  let body =
    Mode_rules.Function.body
      modes
      ~res_mode:fn.res_mode
      ~ty:fn.res_ty
      (fun at ->
         let params =
           List.map2_exn
             fn_params
             fn.arg_modes
             ~f:(fun ((ident : Typed.Ident.t), ty) arg_mode ->
               let mode =
                 Mode_rules.Function.param modes ~arg_mode ~name:ident.name ~loc
               in
               ident.name, Scope.entry scope ~ident ~scheme:ty ~mode)
         in
         Env.with_bindings scope.locals params ~f:(fun () ->
           check_expr t scope ~at ~expr:fn.body ~ty:fn.res_ty))
  in
  List.fold_right
    fn.inner
    ~init:body
    ~f:(fun { Function_type.Level.args; annots; ty; loc } body ->
      { Typed.Expr.desc = Fun { args = List.map args ~f:fst; annots; body }
      ; ty
      ; loc
      })

and with_monomorphic_bindings (scope : Scope.t) bindings ~f =
  Env.with_bindings
    scope.locals
    (List.map bindings ~f:(fun ((ident : Typed.Ident.t), ty, mode) ->
       ident.name, Scope.entry scope ~ident ~scheme:ty ~mode))
    ~f

(* What fails to check is reported, and becomes [Error] of its parts that did,
   of type [Type.error]. Unless [hint] is [Required], [expected] is only what
   [expr] is likely to be, so it isn't unified with what may turn out to be
   something else. *)
and expr_type
  ?expected
  ?(hint = Expectation.Required)
  t
  (scope : Scope.t)
  ~(at : Mode_rules.Expected.t)
  ~(expr : Source.Expr.t)
  : Typed.Expr.t
  =
  let modes = Scope.modes scope in
  let loc = Source.Expr.loc expr in
  let node desc ty = { Typed.Expr.desc; ty; loc } in
  let fail ?(children = []) error =
    Scope.report scope error;
    node (Error children) Type.error
  in
  (* Only checked for its errors, as what it is part of did not check. *)
  let discarded expr =
    expr_type t scope ~at:(Mode_rules.Expected.fresh modes) ~expr
  in
  let infer exprs = List.map exprs ~f:discarded in
  let part ?ty modality check = Mode_rules.part ?ty modes at modality check in
  let tys = List.map ~f:(fun (expr : Typed.Expr.t) -> expr.ty) in
  let labelled_tys =
    List.map ~f:(fun (label, (expr : Typed.Expr.t)) -> label, expr.ty)
  in
  match Source.Expr.view expr with
  | Lit l -> node (Lit l) (Syntax.Lit.ty l)
  | Error ->
    scope.program.syntax_errors <- true;
    node (Error []) Type.error
  | Expect expected ->
    (* Only where it runs as part of the test: not at compile time nor in code. *)
    if Option.is_some scope.syntax_splice
    then fail (Typecheck_error.create ~loc Expect_in_syntax_splice)
    else if scope.in_expect_test
            && scope.level = 0
            && Option.is_none scope.quote
    then node (Expect expected) Type.unit
    else fail (Typecheck_error.create ~loc Expect_outside_expect_test)
  | Struct_quote toplevels ->
    (match Struct_quote.expand toplevels ~loc with
     | Ok expanded ->
       expr_type ?expected ~hint t scope ~at ~expr:(Source.Expr.Syntax expanded)
     | Error (loc, message) ->
       fail (Typecheck_error.create ~loc (Malformed_struct_quote message)))
  | Type ty ->
    (match
       Type_env.elaborate
         scope.program.type_env
         scope.module_
         (Type_env.Annotation_vars.create t ~rank:scope.rank)
         ty
         ~splices:(Scope.splices scope)
     with
     | Error error -> fail error
     | Ok (elaborated, resolved) ->
       node
         (Type resolved)
         (TCon (Prelude_path.canonical "Stag.Type.t", [ ATy elaborated ])))
  | Var (Path (path, annot)) ->
    (match
       Mode_rules.annotated_use
         modes
         at
         ~annot:annot.mode
         ~var:(Scope.mode_var scope)
         ~loc
         (fun at ->
            let%map.Result ty, var_ref =
              match path with
              | Path _ | Root _ -> var_type t scope ~at ~path ~loc
              | Resolved name -> resolved_value_type t scope ~at name ~loc
            in
            node (Var var_ref) ty)
     with
     | Error error -> fail error
     | Ok var -> annotate t scope var annot ~loc)
  | Marked (Nontail, inner) ->
    let inner =
      expr_type
        ?expected
        ~hint
        t
        scope
        ~at:(Mode_rules.Expected.nontail at)
        ~expr:inner
    in
    node (Marked (Nontail, inner)) inner.ty
  | Marked (Stack, inner) ->
    (match
       Mode_rules.Alloc.stack modes at ~loc (fun at ->
         expr_type ?expected ~hint t scope ~at ~expr:inner)
     with
     | Ok inner -> node (Marked (Stack, inner)) inner.ty
     | Error inner ->
       fail
         ~children:[ inner ]
         (Typecheck_error.create ~loc Stack_not_on_allocation))
  | Marked (Exclave, inner) ->
    (match
       Mode_rules.exclave modes at ~loc (fun at ->
         expr_type
           ?expected
           ~hint
           t
           { scope with
             locks = { Env.Lock.id = Fresh.id t; kind = Exclave } :: scope.locks
           }
           ~at
           ~expr:inner)
     with
     | Some inner -> node (Marked (Exclave, inner)) inner.ty
     | None ->
       fail
         ~children:[ discarded inner ]
         (Typecheck_error.create ~loc Exclave_not_in_tail_position))
  | Annotated (var, annot) ->
    let var =
      Mode_rules.annotated_use
        modes
        at
        ~annot:annot.mode
        ~var:(Scope.mode_var scope)
        ~loc
        (fun at -> Ok (expr_type t scope ~at ~expr:var))
      |> Result.ok_exn
    in
    annotate t scope var annot ~loc
  | Var (Ref var_ref) ->
    (match var_ref_type t scope ~at var_ref ~loc with
     | Error error -> fail error
     | Ok (ty, var_ref) -> node (Var var_ref) ty)
  | App (f, x) ->
    Mode_rules.runs modes at Portable ~loc ~why:"it applies a function";
    let a = Scope.fresh_ty t scope in
    let b = Scope.fresh_ty t scope in
    let arg_mode = Scope.arrow_mode scope in
    let res_mode = Scope.arrow_mode scope in
    let curry = Scope.arrow_mode scope in
    let curried =
      match Source.Expr.view f with
      | App _ -> true
      | _ -> false
    in
    (* The expected result is known before the argument, which may need it:
       [Ptr.make (C x)] resolves [C] in the expected pointee type. A clash is
       left to whoever expects the result to report. A hint is only taken once
       the result is known to be of its form, as a variable may become another
       type: a toplevel splice's code may be syntax. *)
    let result_matches_expected () =
      match expected with
      | Some expected
        when (not (Unify.clash expected b))
             && not
                  ((not (Expectation.is_required hint))
                   &&
                   match Type.canonical_ty b with
                   | TVar _ -> true
                   | _ -> false) ->
        Scope.unifies t scope ~ty1:expected ~ty2:b ~loc
      | Some _ | None -> true
    in
    let result_matches = ref true in
    let f, x =
      Mode_rules.apply
        modes
        at
        ~loc
        ~curried
        ~arg_mode
        ~res_mode
        ~curry
        ~arg_ty:a
        ~res_ty:b
        ~callee:(fun at ->
          check_expr
            t
            scope
            ~at
            ~expr:f
            ~ty:
              (TArrow
                 ( a
                 , b
                 , { arg = Var arg_mode; res = Var res_mode; curry = Var curry }
                 )))
        ~arg:(fun at ->
          result_matches := result_matches_expected ();
          check_expr t scope ~at ~expr:x ~ty:a)
    in
    (match f.desc with
     | Var (Intrinsic Ptr_make) -> Mode_rules.Alloc.pointer at
     | Var (Bound (Toplevel ident) | Persistent (Toplevel ident))
       when String.equal ident.name (Prelude_path.canonical "Ptr.make") ->
       Mode_rules.Alloc.pointer at
     | _ -> ());
    if !result_matches
    then node (App (f, x)) b
    else node (Error [ f; x ]) Type.error
  | Let { binder; args; annot; mode = mode_annot; body; in_ } ->
    let inner = { scope with rank = scope.rank + 1 } in
    let is_function = not (List.is_empty args) in
    let name = Source.Binder.name binder in
    let (fn, ident, body, closure), mode =
      Mode_rules.evaluate
        modes
        at
        ~inner:(Scope.modes inner)
        ~loc
        ~why:(sprintf "%s is bound" name)
        (fun inner_at ->
           let fn =
             function_type
               t
               inner
               ~args
               ~annot
               ~res_mode:(if is_function then mode_annot else None)
               ~body
               ~loc
           in
           let ident =
             Program_env.bind scope.program binder fn.ty ~level:scope.level
           in
           let defining mode ~f =
             Env.with_bindings
               scope.locals
               [ ( name
                 , Scope.entry scope ~defining:true ~ident ~scheme:fn.ty ~mode )
               ]
               ~f
           in
           (* A closure may refer to itself, but a value referring to itself is
              not known yet, as a [let rec]'s isn't. *)
           match fn.args with
           | [] ->
             let body =
               defining
                 (Mode_rules.Binding.defining modes inner_at ~name ~loc)
                 ~f:(fun () ->
                   check_expr t inner ~at:inner_at ~expr:body ~ty:fn.res_ty)
             in
             fn, ident, body, None
           | _ :: _ ->
             Mode_rules.Alloc.closure
               (Scope.modes inner)
               inner_at
               ~loc
               (fun closure ->
                  let body =
                    defining (Mode_rules.Binding.closure closure) ~f:(fun () ->
                      check_body t inner ~closure ~fn ~loc)
                  in
                  fn, ident, body, Some (Mode_rules.Binding.closure closure)))
    in
    let { Function_type.args = arg_types; annots; result_annot; ty; _ } = fn in
    let args = List.map arg_types ~f:fst in
    let generalized = generalizes scope mode ~is_function ~loc in
    if generalized
    then Scheme.generalize t ~rank:scope.rank [ ty ]
    else Unify.lower_ty ~rank:scope.rank ty;
    let in_ =
      Env.with_bindings
        scope.locals
        [ ( name
          , Scope.entry
              scope
              ~ident
              ~scheme:ty
              ~mode:
                (match closure with
                 | Some closure -> closure
                 | None ->
                   Mode_rules.Binding.value
                     modes
                     mode
                     mode_annot
                     ~var:(Scope.mode_var scope)) )
        ]
        ~f:(fun () ->
          expr_type
            t
            scope
            ~at:(Mode_rules.Expected.whole at)
            ~expr:in_
            ?expected
            ~hint)
    in
    node
      (Let
         { ident
         ; args
         ; annots
         ; result_annot
         ; mode = mode_annot
         ; body
         ; in_
         ; generalized
         })
      in_.ty
  | Let_mut { binder; annot; mode = held_annot; body; in_ } ->
    let ty, annot =
      match annot with
      | None -> Scope.fresh_ty t scope, None
      | Some annot ->
        (match Scope.elaborate_resolved scope annot with
         | Ok (ty, resolved) -> ty, Some resolved
         | Error error ->
           Scope.report scope error;
           Scope.fresh_ty t scope, None)
    in
    let name = Source.Binder.name binder in
    let (body, ident), value =
      Mode_rules.evaluate
        modes
        at
        ~loc
        ~why:(sprintf "%s is bound" name)
        (fun body_at ->
           let body = check_expr t scope ~at:body_at ~expr:body ~ty in
           let ident =
             Program_env.bind scope.program binder ty ~level:scope.level
           in
           body, ident)
    in
    Hash_set.add scope.program.mutable_idents ident;
    let mode, held =
      Mode_rules.Binding.mutable_
        ~ty
        modes
        ~value
        held_annot
        ~var:(Scope.mode_var scope)
        ~name
        ~loc
    in
    let in_ =
      Env.with_bindings
        scope.locals
        [ name, Scope.entry scope ~ident ~scheme:ty ~mode ~held ]
        ~f:(fun () ->
          expr_type
            t
            scope
            ~at:(Mode_rules.Expected.whole at)
            ~expr:in_
            ?expected
            ~hint)
    in
    node (Let_mut { ident; annot; mode = held_annot; body; in_ }) in_.ty
  | Assign (var, value) ->
    Mode_rules.runs modes at Nonportable ~loc ~why:"it assigns a variable";
    let target, (_ : Mode.Var.t) =
      Mode_rules.evaluate modes at ~loc ~why:"it is assigned to" (fun at ->
        match var with
        | Path (path, _) ->
          (match path with
           | Path _ | Root _ -> var_type t scope ~at ~path ~loc
           | Resolved name -> resolved_value_type t scope ~at name ~loc)
        | Ref var_ref -> var_ref_type t scope ~at var_ref ~loc)
    in
    let name =
      match var with
      | Path (path, _) -> Syntax.Decl_path.to_string path
      | Ref (Bound (Local ident | Toplevel ident))
      | Ref (Persistent (Local ident | Toplevel ident)) -> ident.name
      | Ref (Free name | Free_toplevel name) -> name
      | Ref (Prim prim) -> Prim.canonical_name prim
      | Ref (Intrinsic intrinsic) -> Intrinsic.public_name intrinsic
    in
    let assignable : Typed.Var_ref.t -> _ = function
      | (Bound binder | Persistent binder) as var_ref ->
        let (Local ident | Toplevel ident) = binder in
        if Program_env.is_mutable scope.program ident
        then Ok var_ref
        else error ~loc (Assign_to_immutable name)
      | Free free_name as var_ref ->
        (match scope.quote with
         | None -> error ~loc (Assign_to_immutable name)
         | Some quote ->
           let%map.Result (_ : Type.ty) =
             Unify.present_entry
               ~assigned:true
               t
               ~row:quote.context
               ~name:free_name
               ~rank:quote.outside.rank
             |> lift ~loc
           in
           var_ref)
      | Free_toplevel _ -> error ~loc (Assign_to_immutable name)
      | Prim _ | Intrinsic _ -> error ~loc (Assign_to_immutable name)
    in
    (match
       Result.bind target ~f:(fun (ty, var_ref) ->
         Result.map (assignable var_ref) ~f:(fun var_ref -> ty, var_ref))
     with
     | Error error -> fail ~children:[ discarded value ] error
     | Ok (ty, var_ref) ->
       let assigned, (held, crossed) =
         match var_ref with
         | Bound (Local ident) | Persistent (Local ident) ->
           (match
              Env.find_binder scope.locals (Local ident) ~name:ident.name
            with
            | Some entry ->
              ( ident.name
              , (entry.held, Env.Entry.crossed entry ~locks:scope.locks) )
            | None ->
              raise_s
                [%message "Assigned local not in scope" (ident : Typed.Ident.t)])
         | Bound (Toplevel ident) | Persistent (Toplevel ident) ->
           ( ident.name
           , ( (match (Program_env.toplevel scope.program ident.name).state with
                | In_progress { held; _ } -> held
                | Done { entry; _ } -> entry.held
                | Unchecked ->
                  raise_s
                    [%message
                      "Assigned toplevel not checked" (ident : Typed.Ident.t)])
             , [] ) )
         | Free _ -> name, (None, [])
         | Free_toplevel _ | Prim _ | Intrinsic _ ->
           raise_s [%message "Assigned to an immutable" name]
       in
       let value =
         Mode_rules.assign
           modes
           at
           ~held
           ~crossed
           ~ty
           ~name:assigned
           ~loc
           (fun at -> check_expr t scope ~at ~expr:value ~ty)
       in
       node (Assign (var_ref, value)) Type.unit)
  | Fun { args; body } ->
    let fn =
      function_type t scope ~args ~annot:None ~res_mode:None ~body ~loc
    in
    let { Function_type.args; annots; ty; _ } = fn in
    (* The parameters' types are known before the body is checked where they are
       expected, so that what crosses modes by its type does: [f (fun x -> ...)]
       with [f]'s type known. A mismatch is left to the caller to report. *)
    (match expected with
     | Some expected
       when Expectation.is_required hint && not (Unify.clash expected ty) ->
       ignore (Unify.unify_ty t ~ty1:expected ~ty2:ty : (unit, _) Result.t)
     | Some _ | None -> ());
    let body =
      Mode_rules.Alloc.closure modes at ~loc (fun closure ->
        check_body t scope ~closure ~fn ~loc)
    in
    node (Fun { args = List.map args ~f:fst; annots; body }) ty
  | Quote expr ->
    let quote =
      { Scope.id = Fresh.id t
      ; context = Scope.fresh_row t scope
      ; outside = scope
      ; mode = Mode_rules.Alloc.code modes at ~loc
      }
    in
    let expected =
      match Option.map expected ~f:Type.canonical_ty with
      | Some (TCode { inner; context = _ }) -> Some inner
      | Some _ | None -> None
    in
    let inner =
      expr_type
        t
        { scope with
          level = scope.level + 1
        ; quote = Some quote
        ; locks = { id = Fresh.id t; kind = Quote quote.mode } :: scope.locks
        }
        ~at:(Mode_rules.Expected.quoted modes)
        ~expr
        ?expected
        ~hint:(Expectation.quoted hint)
    in
    node (Quote inner) (TCode { inner = inner.ty; context = quote.context })
  | Splice { code; subs } ->
    let source_subs = subs in
    (match scope.quote, expr with
     | None, Generated _ ->
       raise_s [%message "Generated code has a splice outside any quote"]
     | None, Syntax _ | Some _, _ -> ());
    let (outside : Scope.t), check_code =
      match scope.quote with
      | Some quote ->
        Mode_rules.runs
          modes
          at
          Nonportable
          ~loc
          ~why:"the mode of spliced code is not known";
        ( { quote.outside with
            rank = scope.rank
          ; locks = { id = Fresh.id t; kind = Splice } :: scope.locks
          }
        , fun check -> Mode_rules.Splice.code ~code:quote.mode check )
      | None ->
        ( { scope with level = scope.level - 1 }
        , fun check -> check (Mode_rules.Expected.fresh modes) )
    in
    let reported = scope.program.reported in
    let inner = Scope.fresh_ty t scope in
    let context = Scope.fresh_row t scope in
    let code_expected =
      Option.map expected ~f:(fun inner ->
        Type.TCode { inner; context = Scope.fresh_row t outside })
    in
    let substitutions () =
      match subs with
      | Implicit ->
        let%map.Result captures =
          substitute_from_scope
            t
            scope
            ~at:(Mode_rules.Splice.captured at)
            ~context
            ~loc
            ~may_capture:(fun _ _ -> true)
        in
        Typed.Expr.Subs.Implicit captures, String.Map.empty
      | Providers providers ->
        let%map.Result captures =
          substitute_from_scope
            t
            scope
            ~at:(Mode_rules.Splice.captured at)
            ~context
            ~loc
            ~may_capture:(fun name binder ->
              [%equal: Typed.Binder.t option]
                (Map.find providers name)
                (Some binder))
        in
        Typed.Expr.Subs.Implicit captures, String.Map.empty
      | Explicit subs ->
        let%map.Result subs, bindings =
          substitute_explicitly t scope ~at ~context ~subs ~loc
        in
        Typed.Expr.Subs.Explicit subs, bindings
    in
    let failed code =
      scope.program.reported > reported || Typed.Expr.has_error code
    in
    (match scope.quote with
     | Some _ ->
       let code =
         check_code (fun at ->
           check_expr
             t
             outside
             ~at
             ~expr:code
             ~ty:(TCode { inner; context })
             ?expected:code_expected
             ~hint)
       in
       (match substitutions () with
        | Error error -> fail error ~children:[ code ]
        | Ok (subs, (_ : Binding.t String.Map.t)) ->
          node (Splice { code; subs }) inner)
     | None ->
       let code =
         check_code (fun at ->
           expr_type
             t
             outside
             ~at
             ~expr:code
             ?expected:code_expected
             ~hint:(Code_hint hint))
       in
       if is_syntax code.ty
       then (
         match subs with
         | Explicit _ ->
           fail
             (Typecheck_error.create ~loc Syntax_splice_with_substitutions)
             ~children:[ code ]
         | Implicit | Providers _ ->
           if failed code
           then node (Error [ code ]) Type.error
           else (
             match splice_syntax t scope ~at ~code ~loc ?expected ~hint with
             | Error error -> fail error ~children:[ code ]
             | Ok expansion ->
               node (Toplevel_splice { code; expansion }) expansion.ty))
       else (
         match
           Unify.unify_ty t ~ty1:(TCode { inner; context }) ~ty2:code.ty
         with
         | Error _ ->
           fail
             (Typecheck_error.create
                ~loc:code.loc
                (Toplevel_splice_of_neither
                   (Type.Snapshot.ty
                      (Type.Snapshot.create ())
                      (Type.canonical_ty code.ty))))
             ~children:[ code ]
         | Ok () ->
           let listed = listed_entries context in
           (match substitutions () with
            | Error error -> fail error ~children:[ code ]
            | Ok (subs, bindings) ->
              if failed code
              then
                (* Code that did not check is not run. *)
                node
                  (Error
                     (code
                      ::
                      (match subs with
                       | Explicit subs -> List.map subs ~f:snd
                       | Implicit _ -> [])))
                  Type.error
              else (
                let name_locs =
                  match source_subs with
                  | Explicit source_subs ->
                    String.Map.of_alist_reduce
                      (List.map source_subs ~f:(fun ({ Located.txt; loc }, _) ->
                         txt, loc))
                      ~f:(fun first _ -> first)
                  | Implicit | Providers _ -> String.Map.empty
                in
                match
                  expand
                    t
                    scope
                    ~at
                    ~code
                    ~subs
                    ~bindings
                    ~listed
                    ~name_locs
                    ~ty:inner
                    ~loc
                with
                | Error error -> fail error ~children:[ code ]
                | Ok expansion ->
                  node (Toplevel_splice { code; expansion }) inner))))
  | Deref pointer ->
    Mode_rules.runs modes at Nonportable ~loc ~why:"it reads through a pointer";
    let ptr pointee = Type.TCon ("ptr", [ ATy pointee ]) in
    (* What a pointer points to is global, as it is stored global. *)
    let pointee, pointer =
      Mode_rules.project modes at ~loc ~why:"it is dereferenced" (fun at ->
        ( (match expected with
           | Some expected when Expectation.is_required hint ->
             ( expected
             , expr_type t scope ~at ~expr:pointer ~expected:(ptr expected) )
           | Some _ | None ->
             ( Scope.fresh_ty t scope
             , expr_type
                 t
                 scope
                 ~at
                 ~expr:pointer
                 ?expected:(Option.map expected ~f:ptr)
                 ~hint:Hint ))
        , Modality.Global ))
    in
    if Scope.unifies t scope ~ty1:pointer.ty ~ty2:(ptr pointee) ~loc
    then node (Deref pointer) pointee
    else node (Error [ pointer ]) Type.error
  | Store (target, value) ->
    let rec under_deref (expr : Source.Expr.t) =
      match Source.Expr.view expr with
      | Deref _ -> true
      | Field (inner, _) | Poly_field (inner, _) -> under_deref inner
      | _ -> false
    in
    if not (under_deref target)
    then
      fail
        ~children:[ discarded target ]
        (Typecheck_error.create ~loc Store_not_through_pointer)
    else (
      let target, value =
        Mode_rules.store
          modes
          at
          ~loc
          ~target:(fun at -> expr_type t scope ~at ~expr:target)
          ~value:(fun at ~ty -> check_expr t scope ~at ~expr:value ~ty)
      in
      node (Store (target, value)) Type.unit)
  | Tuple exprs ->
    let exprs =
      List.map2_exn
        exprs
        (tuple_components expected (List.length exprs))
        ~f:(fun expr expected ->
          part Id (fun at -> expr_type t scope ~at ~expr ?expected ~hint))
    in
    node (Tuple exprs) (Type.TTuple (tys exprs))
  | Construct (constructor, args) ->
    (match
       constructor_types
         t
         scope
         constructor
         ~args
         ~tuple:Source.Expr.tuple
         ~expected
         ~loc
     with
     | Error error -> fail error ~children:(infer args)
     | Ok (constructor, args, result) ->
       let args =
         List.map args ~f:(fun (expr, ty, modality) ->
           part modality ~ty (fun at -> check_expr t scope ~at ~expr ~ty))
       in
       node (Construct (constructor, args)) result)
  | Record fields ->
    (match record_fields t scope fields ~all_required:true ~expected ~loc with
     | Error error -> fail error ~children:(infer (List.map fields ~f:snd))
     | Ok (record, fields, complete) ->
       let exprs =
         List.map fields ~f:(fun ((field : Typed.Field_ref.t), (expr, ty)) ->
           part (field_modality scope field) ~ty (fun at ->
             check_expr t scope ~at ~expr ~ty))
       in
       if complete
       then node (Record (List.zip_exn (List.map fields ~f:fst) exprs)) record
       else node (Error exprs) record)
  | Field (expr, field) when Option.is_some (Known.unqualified_field field) ->
    let expr, field =
      Mode_rules.project modes at ~loc ~why:"its field is read" (fun at ->
        let expr = expr_type t scope ~at ~expr in
        match field_type t scope field ~record:(Some expr.ty) ~loc with
        | Error error -> (expr, Error error), Modality.Id
        | Ok ((field, _, _) as typed) ->
          (expr, Ok typed), field_modality scope field)
    in
    (match field with
     | Error error -> fail error ~children:[ expr ]
     | Ok (field, record, field_ty) ->
       let field = node (Field (expr, field)) field_ty in
       if Scope.unifies t scope ~ty1:record ~ty2:expr.ty ~loc:expr.loc
       then field
       else node (Error [ field ]) Type.error)
  | Field (expr, field) ->
    (match field_type t scope field ~record:None ~loc with
     | Error error -> fail error ~children:(infer [ expr ])
     | Ok (field, record, field_ty) ->
       let expr =
         Mode_rules.project modes at ~loc ~why:"its field is read" (fun at ->
           check_expr t scope ~at ~expr ~ty:record, field_modality scope field)
       in
       node (Field (expr, field)) field_ty)
  | Record_update (expr, fields) ->
    (* As in OCaml, the result's type parameters are those of [expr]'s type but
       for the ones only in the updated fields' types. *)
    (match Known.record scope expected with
     | Error error ->
       fail error ~children:(infer (expr :: List.map fields ~f:snd))
     | Ok known_expected ->
       (* What it does not update is copied. *)
       let expr =
         part Id (fun at ->
           expr_type
             t
             scope
             ~at
             ~expr
             ?expected:
               (Option.map known_expected ~f:(fun known ->
                  Scope.instantiate t scope (declared_record known))))
       in
       (match
          resolve_record_fields
            scope
            fields
            ~all_required:false
            ~expected:(either_known expr.ty expected)
            ~loc
        with
        | Error error ->
          fail error ~children:(expr :: infer (List.map fields ~f:snd))
        | Ok (known, fields, (_ : bool)) ->
          let inst_in = Scope.instantiate t scope in
          let inst_out = Scope.instantiate t scope in
          let unified =
            Scope.unifies
              t
              scope
              ~ty1:(inst_in (declared_record known))
              ~ty2:expr.ty
              ~loc:expr.loc
          in
          let record = inst_out (declared_record known) in
          let unified =
            match unify_known t ~expected record ~loc with
            | Ok () -> unified
            | Error error ->
              Scope.report scope error;
              false
          in
          let unified =
            List.filter known.members ~f:(Fn.non (is_given fields))
            |> List.fold ~init:unified ~f:(fun unified member ->
              Scope.unifies
                t
                scope
                ~ty1:(inst_in member.ty)
                ~ty2:(inst_out member.ty)
                ~loc
              && unified)
          in
          let exprs =
            List.map fields ~f:(fun (field, _, expr) ->
              let ty = inst_out field.ty in
              part
                (field_modality scope (field_ref field))
                ~ty
                (fun at -> check_expr t scope ~at ~expr ~ty))
          in
          let update =
            node
              (Record_update
                 ( expr
                 , List.zip_exn
                     (List.map fields ~f:(fun (field, _, _) -> field_ref field))
                     exprs ))
              record
          in
          if unified then update else node (Error [ update ]) Type.error))
  | Match { scrutinee = expr; cases; exception_cases } ->
    let scrutinee, scrutinee_mode =
      Mode_rules.evaluate modes at ~loc ~why:"it is matched on" (fun at ->
        expr_type t scope ~at ~expr)
    in
    let result = Scope.fresh_ty t scope in
    (* Closing the scrutinee to patterns in error would only add errors. *)
    let patterns_failed = ref false in
    let counting_errors f =
      let before = scope.program.reported in
      let result = f () in
      if scope.program.reported > before then patterns_failed := true;
      result
    in
    (* A case of [pattern], typed with its [bindings], of type [ty], and whether
       the pattern is of [ty]. *)
    let case ~ty ~mode ((pattern : Typed.Pattern.t), bindings) body =
      let pattern, unified =
        counting_errors (fun () ->
          let before = scope.program.reported in
          report_duplicates
            scope
            (List.map bindings ~f:(fun (var : Pattern_var.t) ->
               { Located.txt = var.ident.name; loc = var.loc }))
            ~error:(fun name -> Duplicate_pattern_variable name);
          let unified =
            Scope.unifies t scope ~ty1:ty ~ty2:pattern.ty ~loc:pattern.loc
          in
          ( (if unified && scope.program.reported = before
             then pattern
             else Typed.Pattern.error [ pattern ] ~loc:pattern.loc)
          , unified ))
      in
      let body =
        Env.with_bindings
          scope.locals
          (List.map bindings ~f:(fun (var : Pattern_var.t) ->
             let mode =
               Mode_rules.Binding.project
                 modes
                 ~block:mode
                 var.modality
                 ~loc:var.loc
             in
             ( var.ident.name
             , Scope.entry scope ~ident:var.ident ~scheme:var.ty ~mode )))
          ~f:(fun () ->
            check_expr
              t
              scope
              ~at:(Mode_rules.Expected.whole at)
              ~expr:body
              ~ty:result
              ?expected:(either_known result expected)
              ~hint:
                (match Type.canonical_ty result with
                 | TVar _ -> hint
                 | _ ->
                   (* An earlier case's type, which this one must have. *)
                   Required))
      in
      (pattern, body), unified
    in
    (match cases, exception_cases with
     | [], _ :: _ ->
       patterns_failed := true;
       Scope.report
         scope
         (Typecheck_error.create ~loc Match_without_value_cases)
     | _ -> ());
    let (_ : Variant_match.t), (_ : Type.ty), cases =
      List.fold
        cases
        ~init:(Variant_match.empty, scrutinee.ty, [])
        ~f:(fun (handled, ty, typed_cases) (pattern, body) ->
          let typed_pattern =
            counting_errors (fun () ->
              Variant_match.pattern_type t scope handled ~pattern ~scrutinee:ty)
          in
          let ((pattern, _) as typed_case), unified =
            case ~ty ~mode:scrutinee_mode typed_pattern body
          in
          (* So that later cases don't report the same mismatch. *)
          let ty = if unified then ty else Scope.fresh_ty t scope in
          Variant_match.add_case handled pattern, ty, typed_case :: typed_cases)
    in
    let cases = List.rev cases in
    let exception_cases =
      List.map exception_cases ~f:(fun (pattern, body) ->
        fst
          (case
             ~ty:Type.exn
             ~mode:(Mode_rules.raised modes ~loc)
             (pattern_type t scope ~pattern ~expected:Type.exn)
             body))
    in
    (match expr, cases with
     | _ when !patterns_failed -> ()
     | Generated _, [] ->
       (* Its scrutinee was closed, unless of an empty nominal type, which may
          have been known only from an annotation. *)
       ()
     | _ ->
       Variant_match.close
         t
         scope
         ~scrutinee:scrutinee.ty
         ~loc
         (List.map cases ~f:fst)
       |> Result.iter_error ~f:(fun error ->
         patterns_failed := true;
         Scope.report scope error));
    let match_ = node (Match { scrutinee; cases; exception_cases }) result in
    if !patterns_failed then node (Error [ match_ ]) result else match_
  | Poly_record fields ->
    let fields = labelled_types t scope ~at fields ~expected ~hint in
    node
      (Poly_record fields)
      (Fresh.record t (Poly_row.present (labelled_tys fields) ~tail:REmpty))
  | Poly_field (expr, label) ->
    let ty = Scope.fresh_ty t scope in
    let row, (_ : Type.row) = Poly_row.open_ t scope [ label, ty ] in
    let expr =
      Mode_rules.project modes at ~loc ~why:"its field is read" (fun at ->
        check_expr t scope ~at ~expr ~ty:(Fresh.record t row), Modality.Id)
    in
    node (Poly_field (expr, label)) ty
  | Poly_extend (fields, expr) ->
    let fields = labelled_types t scope ~at fields ~expected ~hint in
    let rest = Scope.fresh_row t scope in
    let expr =
      part Id (fun at -> check_expr t scope ~at ~expr ~ty:(Fresh.record t rest))
    in
    node
      (Poly_extend (fields, expr))
      (Fresh.record t (Poly_row.present (labelled_tys fields) ~tail:rest))
  | Poly_restrict (expr, label) ->
    let row, rest = Poly_row.open_ t scope [ label, Scope.fresh_ty t scope ] in
    let expr =
      part Id (fun at -> check_expr t scope ~at ~expr ~ty:(Fresh.record t row))
    in
    node (Poly_restrict (expr, label)) (Fresh.record t rest)
  | Poly_update (expr, fields) ->
    let fields = labelled_types t scope ~at fields ~expected ~hint in
    let row, rest =
      Poly_row.open_
        t
        scope
        (List.map fields ~f:(fun (label, _) -> label, Scope.fresh_ty t scope))
    in
    let expr =
      part Id (fun at -> check_expr t scope ~at ~expr ~ty:(Fresh.record t row))
    in
    node
      (Poly_update (expr, fields))
      (Fresh.record t (Poly_row.present (labelled_tys fields) ~tail:rest))
  | Poly_variant (tag, arg) ->
    let arg =
      Option.map arg ~f:(fun expr ->
        part Id (fun at ->
          expr_type
            t
            scope
            ~at
            ~expr
            ?expected:(row_entry expected `Variant ~label:tag)
            ~hint))
    in
    let arg_ty =
      Option.value_map arg ~default:Type.unit ~f:(fun (expr : Typed.Expr.t) ->
        expr.ty)
    in
    node (Poly_variant (tag, arg)) (Poly_row.variant t scope ~tag ~arg:arg_ty)

(* [var] was checked at its mode, by [Mode_rules.annotated_use]. *)
and annotate
  t
  (scope : Scope.t)
  (var : Typed.Expr.t)
  (annot : Syntax.Annot.t)
  ~loc
  : Typed.Expr.t
  =
  match annot.ty with
  | None when Option.is_none annot.mode -> var
  | None -> { var with desc = Annotated (var, annot); loc }
  | Some ty ->
    (match Scope.elaborate_resolved scope ty with
     | Ok (annot_ty, resolved) ->
       let annotated =
         { var with
           desc = Annotated (var, { annot with ty = Some resolved })
         ; loc
         }
       in
       if Scope.unifies t scope ~ty1:var.ty ~ty2:annot_ty ~loc
       then annotated
       else { desc = Error [ annotated ]; ty = Type.error; loc }
     | Error error ->
       Scope.report scope error;
       var)

(* Runs the toplevel splice [code] of a [Stag.Expr.t], then infers the
   expression it gives here, checking it against [expected] so that a mismatch
   is reported as the expression's. *)
and splice_syntax ?expected ~hint t (scope : Scope.t) ~at ~code ~loc =
  let program = scope.program in
  let%bind.Result value =
    at_compile_time
      ~loc
      program
      (fun ~reflect ->
        Interpreter.run
          program.interpreter
          code
          ~level:(scope.level - 1)
          ~reflect)
      ~error:(fun error ->
        Typecheck_error.create ~loc (Splice_evaluation_failed { code; error }))
  in
  let%map.Result generated =
    Interpreter.Value.to_syntax value Generated_syntax.Expr ~loc
    |> Result.map_error ~f:(fun error ->
      Typecheck_error.create ~loc (Malformed_syntax_splice error))
  in
  let scope = { scope with syntax_splice = Some { splice = loc; generated } } in
  let expr = Source.Expr.Syntax generated in
  match expected with
  | Some ty when Expectation.is_required hint ->
    check_expr t scope ~at ~expr ~ty
  | Some _ | None -> expr_type t scope ~at ~expr ?expected ~hint

(* The names [row] has an entry for that may be present. *)
and listed_entries (row : Type.row) =
  match Type.canonical_row row with
  | REmpty | RVar _ -> String.Set.empty
  | RExtend (name, presence, _, _, rest) ->
    (match Type.canonical_presence presence with
     | Present | PVar _ -> Set.add (listed_entries rest) name
     | Absent -> listed_entries rest)

(* Runs the toplevel splice [code], then infers the code it generates here, with
   its explicit substitutions bound by lets around it. An explicit substitution
   of a name not [listed] in the code's context must be of a free variable of
   the code generated. *)
and expand
  t
  (scope : Scope.t)
  ~at
  ~code
  ~subs
  ~bindings:modes
  ~listed
  ~name_locs
  ~ty
  ~loc
  =
  let program = scope.program in
  let bindings, entry =
    match (subs : Typed.Expr.t Typed.Expr.Subs.t) with
    | Implicit providers ->
      ( []
      , fun name ->
          Map.find providers name
          |> Option.map ~f:(fun binder -> Typed.Var_ref.Bound binder) )
    | Explicit subs ->
      (* As [Interpreter_intf.S.splice] does: a variable is substituted as
         itself, so that the code may assign it. *)
      let subs =
        List.map subs ~f:(fun (name, (sub : Typed.Expr.t)) ->
          match sub.desc with
          | Var ((Bound _ | Persistent _) as var_ref) -> name, First var_ref
          | _ ->
            ( name
            , Second
                ( Program_env.bind
                    program
                    (Name (Located.create ~loc name))
                    sub.ty
                    ~level:scope.level
                , sub ) ))
      in
      let entries =
        String.Map.of_alist_reduce
          (List.map subs ~f:(fun (name, sub) ->
             ( name
             , match sub with
               | First var_ref -> var_ref
               | Second ((ident : Typed.Ident.t), _) ->
                 Typed.Var_ref.Bound (Local ident) )))
          ~f:(fun first _ -> first)
      in
      ( List.filter_map subs ~f:(fun (_, sub) -> Either.Second.to_option sub)
      , Map.find entries )
  in
  let used = String.Hash_set.create () in
  let entry name =
    Hash_set.add used name;
    entry name
  in
  let%bind.Result generated =
    at_compile_time
      ~loc
      program
      (fun ~reflect ->
        Interpreter.splice
          program.interpreter
          ~code
          ~level:(scope.level - 1)
          ~entry
          ~reflect)
      ~error:(fun error ->
        Typecheck_error.create ~loc (Splice_evaluation_failed { code; error }))
  in
  let%map.Result () =
    match subs with
    | Implicit _ -> Ok ()
    | Explicit subs ->
      List.find subs ~f:(fun (name, _) ->
        not (Set.mem listed name || Hash_set.mem used name))
      |> Option.value_map
           ~default:(Ok ())
           ~f:(fun (name, (sub : Typed.Expr.t)) ->
             error
               ~loc:(Map.find name_locs name |> Option.value ~default:sub.loc)
               (Unused_substitution name))
  in
  let expansion =
    with_monomorphic_bindings
      scope
      (List.map
         bindings
         ~f:(fun ((ident : Typed.Ident.t), (sub : Typed.Expr.t)) ->
           ident, sub.ty, Map.find_exn modes ident.name))
      ~f:(fun () ->
        (* Each expansion's annotations name their own type variables. *)
        let scope =
          { scope with
            annotation_vars = Type_env.Annotation_vars.create t ~rank:scope.rank
          }
        in
        check_expr t scope ~at ~expr:(Source.Expr.Generated generated) ~ty)
  in
  List.fold_right bindings ~init:expansion ~f:(fun (ident, body) in_ ->
    { Typed.Expr.desc =
        Let
          { ident
          ; args = []
          ; annots = []
          ; result_annot = None
          ; mode = None
          ; generalized = false
          ; body
          ; in_
          }
    ; ty = in_.ty
    ; loc
    })

and labelled_types t scope ~at fields ~expected ~hint =
  Poly_row.report_duplicate_labels scope fields;
  List.map fields ~f:(fun ((label : Syntax.Name.t), expr) ->
    ( label.txt
    , Mode_rules.part (Scope.modes scope) at Id (fun at ->
        expr_type
          t
          scope
          ~at
          ~expr
          ?expected:(row_entry expected `Record ~label:label.txt)
          ~hint) ))

(* Checks [expr] has type [ty], [expected] (by default [ty]) being what it is
   known to be. *)
and check_expr ?expected ?hint t scope ~at ~expr ~ty =
  let expr =
    expr_type
      t
      scope
      ~at
      ~expr
      ~expected:(Option.value expected ~default:ty)
      ?hint
  in
  if Scope.unifies t scope ~ty1:ty ~ty2:expr.ty ~loc:expr.loc
  then expr
  else { desc = Error [ expr ]; ty = Type.error; loc = expr.loc }

(* Returns the binder each entry that may be captured is captured by: entries
   bound in the quote may be captured by their binders if [may_capture]. *)
and substitute_from_scope t (scope : Scope.t) ~at ~context ~loc ~may_capture =
  let rec go context ~seen ~captures =
    match Type.canonical_row context with
    | REmpty -> Ok captures
    | RExtend (name, presence, assigned, ty, rest) ->
      let%bind.Result captured =
        match Type.canonical_presence presence with
        | _ when Set.mem seen name -> Ok None
        | Absent -> Ok None
        | Present | PVar _ ->
          substitute_entry
            t
            scope
            ~at
            ~name
            ~presence
            ~assigned
            ~ty
            ~loc
            ~may_capture
      in
      let captures =
        Option.fold captured ~init:captures ~f:(fun captures binder ->
          (name, binder) :: captures)
      in
      go rest ~seen:(Set.add seen name) ~captures
    | RVar _ as tail ->
      (match scope.quote with
       | None ->
         let%map.Result () =
           Unify.unify_row t ~row1:tail ~row2:REmpty |> lift ~loc
         in
         captures
       | Some quote ->
         let%map.Result captured =
           substitute_tail t scope ~at quote ~tail ~seen ~loc ~may_capture
         in
         captured @ captures)
  in
  let%map.Result captures = go context ~seen:String.Set.empty ~captures:[] in
  String.Map.of_alist_exn captures

and substitute_entry
  t
  (scope : Scope.t)
  ~at
  ~name
  ~presence
  ~assigned
  ~ty
  ~loc
  ~may_capture
  =
  let%bind.Result entry =
    match Env.find scope.locals name, scope.quote with
    | Some entry, _ -> Ok (Some entry)
    (* Toplevels are free variables of the quote, like any name not bound in it. *)
    | None, Some _ -> Ok None
    | None, None ->
      (* The code is checked and runs now, so if it may use [name], it doesn't.
         Providing it anyway could add a dependency on its toplevel, and would
         depend on whether that is checked yet. *)
      (match
         ( Program_env.find_toplevel scope.program name
         , Type.canonical_presence presence )
       with
       | Some toplevel, Present ->
         toplevel_entry t scope toplevel ~loc |> Result.map ~f:Option.some
       | None, _ | Some _, (Absent | PVar _) -> Ok None)
  in
  match Resolution.of_entry scope ~name entry with
  | Unusable (Not_in_scope _)
    when Option.is_none scope.quote
         && Hashtbl.mem scope.program.unusable_in_quotes name ->
    let unusable = Hashtbl.find_exn scope.program.unusable_in_quotes name in
    let%map.Result () =
      Unify.make_absent
        t
        presence
        ~error:
          (Typecheck_error.create
             ~loc
             (Free_in_spliced_code { name; unusable }))
    in
    None
  | Unusable kind ->
    (* Code that may use [name] can't, so doesn't. *)
    let%map.Result () =
      Unify.make_absent t presence ~error:(Typecheck_error.create ~loc kind)
    in
    None
  | Local entry when may_capture name entry.binder ->
    (* Whether the code uses it may not be known yet: assume it does. *)
    use_entry scope ~at entry ~name ~loc;
    let%bind.Result () =
      provides_assigned
        t
        ~name
        ~assigned
        ~mutable_:(binder_is_mutable scope entry.binder)
        ~loc
    in
    let%map.Result () =
      Unify.unify_if_present
        t
        ~presence
        ~ty1:ty
        ~ty2:(Scope.instantiate t scope entry.scheme)
      |> lift ~loc
    in
    Some entry.binder
  | Local _ ->
    let%map.Result () =
      Unify.unify_row
        t
        ~row1:(RExtend (name, presence, assigned, ty, REmpty))
        ~row2:(RExtend (name, Absent, assigned, ty, REmpty))
      |> lift ~loc
    in
    None
  | Outside_quote { quote; _ } ->
    (match Type.canonical_presence presence with
     | Absent -> ()
     | Present | PVar _ ->
       use_free
         scope
         ~at
         ~why:(sprintf "%s is a free variable of the quote" name)
         ~loc);
    let%map.Result () =
      Unify.constrain_row
        t
        ~row:(RExtend (name, presence, assigned, ty, REmpty))
        ~bound:quote.context
        ~shadowed:String.Set.empty
      |> lift ~loc
    in
    None

(* The code's remaining free variables are not known yet, so give the ones that
   would be captured here explicit entries, absent unless [may_capture]. The
   rest must be free variables of the quote. Returns the binders of the ones
   that may be captured. *)
and substitute_tail
  t
  scope
  ~at
  (quote : Scope.quote)
  ~tail
  ~seen
  ~loc
  ~may_capture
  =
  let captured =
    Env.visible scope.locals
    |> List.filter_map ~f:(fun (name, entry) ->
      if Set.mem seen name
      then None
      else (
        match Resolution.of_entry scope ~name (Some entry) with
        | Local entry when may_capture name entry.binder ->
          (* Whether the code uses it is not known: assume it does. *)
          use_entry scope ~at entry ~name ~loc;
          Some
            ( name
            , Scope.fresh_presence t scope
            , may_be_assigned t scope entry.binder
            , Scope.instantiate t scope entry.scheme
            , Some entry.binder )
        | Local _ | Unusable _ ->
          Some (name, Absent, Absent, Scope.fresh_ty t scope, None)
        | Outside_quote _ -> None))
  in
  let rest = Scope.fresh_row t scope in
  use_free
    scope
    ~at
    ~why:"the spliced code may use free variables of the quote"
    ~loc;
  let%bind.Result () =
    Unify.unify_row
      t
      ~row1:tail
      ~row2:
        (List.fold_right
           captured
           ~init:rest
           ~f:(fun (name, presence, assigned, ty, _) rest ->
             Type.RExtend (name, presence, assigned, ty, rest)))
    |> lift ~loc
  in
  let%map.Result () =
    Unify.constrain_row
      t
      ~row:rest
      ~bound:quote.context
      ~shadowed:
        (List.fold captured ~init:seen ~f:(fun seen (name, _, _, _, _) ->
           Set.add seen name))
    |> lift ~loc
  in
  List.filter_map captured ~f:(fun (name, _, _, _, binder) ->
    Option.map binder ~f:(fun binder -> name, binder))

and substitute_explicitly t scope ~at ~context ~subs ~loc =
  let%bind.Result () =
    check_no_duplicates (List.map subs ~f:fst) ~error:(fun name ->
      Duplicate_substitution name)
  in
  let rec lacks (row : Type.row) name =
    match Type.canonical_row row with
    | REmpty -> true
    | RVar _ -> false
    | RExtend (entry, presence, _, _, rest) ->
      if String.equal entry name
      then (
        match Type.canonical_presence presence with
        | Absent -> true
        | Present | PVar _ -> false)
      else lacks rest name
  in
  let%bind.Result () =
    List.find_map subs ~f:(fun ({ txt = name; loc }, _) ->
      Option.some_if (lacks context name) (loc, name))
    |> Option.value_map ~default:(Ok ()) ~f:(fun (loc, name) ->
      error ~loc (Unused_substitution name))
  in
  let bindings = ref String.Map.empty in
  let%bind.Result provided =
    List.fold_result
      subs
      ~init:[]
      ~f:(fun acc ({ txt = name; loc = name_loc }, expr) ->
        let%map.Result expr =
          match expr with
          | None ->
            let%map.Result ty, var_ref =
              var_type
                t
                scope
                ~at:(Mode_rules.Splice.captured at)
                ~path:(Path (Syntax.Path.of_string name))
                ~loc:name_loc
            in
            { Typed.Expr.desc = Var var_ref; ty; loc = name_loc }
          | Some expr ->
            let expr, binding =
              Mode_rules.Splice.substitution
                (Scope.modes scope)
                at
                ~loc:name_loc
                (fun at -> expr_type t scope ~at ~expr)
            in
            bindings := Map.set !bindings ~key:name ~data:binding;
            Ok expr
        in
        (name, expr) :: acc)
  in
  (* Toplevels, free by canonical name, which no sub can name. *)
  let rec toplevels (row : Type.row) =
    match Type.canonical_row row with
    | RExtend (name, presence, _, _, rest) ->
      (match Type.canonical_presence presence with
       | (Present | PVar _) when String.mem name '.' -> name :: toplevels rest
       | Present | PVar _ | Absent -> toplevels rest)
    | REmpty | RVar _ -> []
  in
  let%bind.Result provided =
    List.fold_result (toplevels context) ~init:provided ~f:(fun acc name ->
      let%map.Result ty, var_ref =
        resolved_value_type
          t
          scope
          ~at:(Mode_rules.Splice.captured at)
          name
          ~loc
      in
      (name, { Typed.Expr.desc = Var var_ref; ty; loc }) :: acc)
  in
  (* Only a variable that is mutable can be assigned, as itself. *)
  let assigned (expr : Typed.Expr.t) : Type.presence =
    match expr.desc with
    | Var (Bound binder | Persistent binder) -> may_be_assigned t scope binder
    | _ -> Absent
  in
  let row =
    List.fold provided ~init:Type.REmpty ~f:(fun rest (name, expr) ->
      Type.RExtend
        (name, Scope.fresh_presence t scope, assigned expr, expr.ty, rest))
  in
  let%map.Result () =
    Unify.unify_row t ~row1:context ~row2:row
    |> Result.map_error ~f:(fun (error : Unification_error.t) ->
      match error with
      | Row_mismatch (_, _, Assigned name) ->
        Typecheck_error.create ~loc (Spliced_code_assigns_immutable name)
      | error -> Typecheck_error.unification_error ~loc error)
  in
  List.rev provided, !bindings

and binder_is_mutable (scope : Scope.t) (binder : Typed.Binder.t) =
  let (Local ident | Toplevel ident) = binder in
  Program_env.is_mutable scope.program ident

(* The assignedness of an entry provided by [binder]: code may assign it only if
   it is mutable. *)
and may_be_assigned t scope binder : Type.presence =
  if binder_is_mutable scope binder
  then Scope.fresh_presence t scope
  else Absent

and provides_assigned t ~name ~assigned ~mutable_ ~loc =
  if mutable_
  then Ok ()
  else
    Unify.make_absent
      t
      assigned
      ~error:(Typecheck_error.create ~loc (Spliced_code_assigns_immutable name))
;;

