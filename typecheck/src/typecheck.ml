(* Type-directed lookup: the declared type a constructor or field is known to be
   of, by its canonical name, and its members. *)
module Known = struct
  type 'member t =
    { type_name : string
    ; members : 'member list
    }

  let find
    (scope : Scope.t)
    (ty : Type.ty option)
    ~(members : Type_env.t -> string -> ('m list option, _) Result.t)
    =
    match Option.map ty ~f:Type.canonical_ty with
    | Some ty when Type.is_error ty ->
      (* What did not check has no members, nor any errors from them. *)
      Error Typecheck_error.already_reported
    | Some (TCon (type_name, _)) ->
      let%map.Result members = members scope.program.type_env type_name in
      Option.map members ~f:(fun members -> { type_name; members })
    | Some _ | None -> Ok None
  ;;

  let record scope ty = find scope ty ~members:Type_env.record_fields
  let variant scope ty = find scope ty ~members:Type_env.variant_constructors

  (* Only an unqualified name is looked up in the known type: a qualified one or
     a ref names its declaration. *)
  let unqualified : Syntax.Decl_path.t Located.t -> string option = function
    | { txt = Path path; loc = _ } ->
      (match (path :> string list) with
       | [ name ] -> Some name
       | _ -> None)
    | { txt = Root _ | Resolved _; loc = _ } -> None
  ;;

  let unqualified_field : Source.Field.t -> string option = function
    | Path path -> unqualified path
    | Ref _ -> None
  ;;

  let has t name ~member_name =
    List.exists t.members ~f:(fun member ->
      String.equal (Prelude_path.short_name (member_name member)) name)
  ;;

  let member t ~name ~member_name ~loc ~missing =
    match
      List.find t.members ~f:(fun member ->
        String.equal (Prelude_path.short_name (member_name member)) name)
    with
    | Some member -> Ok member
    | None -> error ~loc (missing ~type_name:t.type_name name)
  ;;
end

let find_constructor (scope : Scope.t) ~loc ~known : Source.Constructor.t -> _
  = function
  | Path path ->
    (match Known.unqualified path, known with
     | Some name, Some (known : _ Known.t) ->
       Known.member
         known
         ~name
         ~member_name:(fun (constructor : Type_env.Constructor.t) ->
           constructor.name)
         ~loc:path.loc
         ~missing:(fun ~type_name constructor ->
           No_such_constructor { type_name; constructor })
     | _ -> Type_env.find_constructor scope.program.type_env scope.module_ path)
  | Ref { name; _ } -> Type_env.constructor scope.program.type_env name ~loc
;;

(* Generated code's fields are at [loc], its node's. *)
let field_loc ~loc : Source.Field.t -> Loc.t = function
  | Path path -> path.loc
  | Ref _ -> loc
;;

let find_field (scope : Scope.t) ~loc ~known (field : Source.Field.t) =
  match field with
  | Path path ->
    (match Known.unqualified path, known with
     | Some name, Some (known : _ Known.t) ->
       Known.member
         known
         ~name
         ~member_name:Type_env.Field.name
         ~loc:path.loc
         ~missing:(fun ~type_name field -> No_such_field { type_name; field })
     | _ -> Type_env.find_field scope.program.type_env scope.module_ path)
  | Ref field ->
    Type_env.field scope.program.type_env (Typed.Field_ref.name field) ~loc
;;

(* Unifies [ty], a fresh instance of a declared type, with [expected] if that is
   known to be the same type, so that what is inside is known too. As [expected]
   is always unified with what has [ty] later, it fails only where that would. *)
let unify_known t ~expected ty ~loc =
  match Option.map expected ~f:Type.canonical_ty, Type.canonical_ty ty with
  | Some (TCon (known, _) as expected), TCon (name, _)
    when String.equal known name ->
    Unify.unify_ty t ~ty1:ty ~ty2:expected |> lift ~loc
  | _ -> Ok ()
;;

(* Pairs each of [args] with its instantiated type, along with the constructor
   and the result type. Several [args] of a constructor declared with one are a
   tuple ([tuple]), as in OCaml. *)
let constructor_types
  t
  (scope : Scope.t)
  constructor
  ~args
  ~tuple
  ~expected
  ~loc
  =
  let%bind.Result known = Known.variant scope expected in
  let%bind.Result (constructor : Type_env.Constructor.t) =
    find_constructor scope constructor ~loc ~known
  in
  let args =
    match args, constructor.args with
    | _ :: _ :: _, [ _ ] -> [ tuple args ]
    | _ -> args
  in
  match List.zip args constructor.args with
  | Unequal_lengths ->
    error
      ~loc
      (Constructor_arity_mismatch
         { constructor = constructor.name
         ; expected = List.length constructor.args
         ; got = List.length args
         })
  | Ok args ->
    let inst = Scope.instantiate t scope in
    let result = inst constructor.result in
    let%map.Result () = unify_known t ~expected result ~loc in
    ( constructor_ref constructor
    , List.map args ~f:(fun (arg, ty) -> arg, inst ty)
    , result )
;;

(* The record type [fields] (not empty) are of: [expected] if it is known to be
   a record type, else that of the first qualified field (or ref), else the
   first of the unqualified fields' types in scope that has all of them. *)
let record_type (scope : Scope.t) fields ~expected ~loc =
  let of_field field =
    let%bind.Result (field : Type_env.Field.t) =
      find_field scope field ~loc ~known:None
    in
    let%map.Result known = Known.record scope (Some field.record) in
    Option.value_exn known
  in
  match%bind.Result Known.record scope expected with
  | Some known -> Ok known
  | None ->
    (match
       List.find fields ~f:(fun (field, _) ->
         Option.is_none (Known.unqualified_field field))
     with
     | Some (field, _) -> of_field field
     | None ->
       let names =
         List.filter_map fields ~f:(fun (field, _) ->
           Known.unqualified_field field)
       in
       let has_all known =
         List.for_all
           names
           ~f:(Known.has known ~member_name:Type_env.Field.name)
       in
       (match
          List.find_map fields ~f:(fun (field, _) ->
            match of_field field with
            | Ok known when has_all known -> Some known
            | Ok _ | Error _ -> None)
        with
        | Some known -> Ok known
        | None -> of_field (fst (List.hd_exn fields))))
;;

let is_given fields (member : Type_env.Field.t) =
  List.exists fields ~f:(fun ((field : Type_env.Field.t), _, _) ->
    field.index = member.index)
;;

(* The record type of [fields], and each field with its location and its [x]. A
   missing required field is reported, and [Error] on [complete]. *)
let resolve_record_fields (scope : Scope.t) fields ~all_required ~expected ~loc =
  let%bind.Result () =
    if List.is_empty fields then error ~loc Empty_record else Ok ()
  in
  let%bind.Result (known : Type_env.Field.t Known.t) =
    record_type scope fields ~expected ~loc
  in
  let find (field, x) =
    let%bind.Result (found : Type_env.Field.t) =
      find_field scope field ~loc ~known:(Some known)
    in
    let loc = field_loc field ~loc in
    if String.equal found.record_type.name known.type_name
    then Ok (found, loc, x)
    else
      error
        ~loc
        (Fields_of_different_types
           { field = Type_env.Field.name found
           ; expected_type = known.type_name
           ; actual_type = found.record_type.name
           })
  in
  (* A qualified field of another type is the error, rather than an unqualified
     one the type lacks. *)
  let%bind.Result (_ : _ list) =
    List.filter fields ~f:(fun (field, _) ->
      Option.is_none (Known.unqualified_field field))
    |> List.map ~f:find
    |> Result.all
  in
  let%bind.Result fields = List.map fields ~f:find |> Result.all in
  let%bind.Result () =
    check_no_duplicates
      (List.map fields ~f:(fun (field, loc, _) ->
         { Located.txt = Prelude_path.short_name (Type_env.Field.name field)
         ; loc
         }))
      ~error:(fun name -> Repeated_field name)
  in
  let complete =
    match List.find known.members ~f:(Fn.non (is_given fields)) with
    | Some member when all_required ->
      Scope.report
        scope
        (Typecheck_error.create
           ~loc
           (Missing_field (Type_env.Field.name member)));
      false
    | Some _ | None -> true
  in
  Ok (known, fields, complete)
;;

let declared_record (known : Type_env.Field.t Known.t) =
  (List.hd_exn known.members).record
;;

(* Returns the instantiated record type, and each field with its [x] paired with
   its type. *)
let record_fields t (scope : Scope.t) fields ~all_required ~expected ~loc =
  let%bind.Result known, fields, complete =
    resolve_record_fields scope fields ~all_required ~expected ~loc
  in
  let inst = Scope.instantiate t scope in
  let record = inst (declared_record known) in
  let%map.Result () = unify_known t ~expected record ~loc in
  let fields =
    List.map fields ~f:(fun ((field : Type_env.Field.t), _, x) ->
      field_ref field, (x, inst field.ty))
  in
  record, fields, complete
;;

(* Returns the field, the instantiated record type and the field's type. *)
let field_type t (scope : Scope.t) field ~record ~loc =
  let%bind.Result known = Known.record scope record in
  let%map.Result (field : Type_env.Field.t) =
    find_field scope field ~loc ~known
  in
  let inst = Scope.instantiate t scope in
  let ty = inst field.ty in
  field_ref field, inst field.record, ty
;;

(* Rows of polymorphic records and variants, whose entries are [Present]. *)
module Poly_row = struct
  let present entries ~tail =
    List.fold_right entries ~init:tail ~f:(fun (label, ty) rest ->
      Type.RExtend (label, Present, Absent, ty, rest))
  ;;

  (* [entries] before a fresh tail, which is also returned. *)
  let open_ t scope entries =
    let tail = Scope.fresh_row t scope in
    present entries ~tail, tail
  ;;

  let variant t scope ~tag ~arg =
    Fresh.variant t (fst (open_ t scope [ tag, arg ]))
  ;;

  let report_duplicate_labels scope entries =
    report_duplicates scope (List.map entries ~f:fst) ~error:(fun label ->
      Duplicate_row_entry label)
  ;;
end

module Pattern_var = struct
  type t =
    { ident : Typed.Ident.t
    ; ty : Type.ty
    ; loc : Loc.t
    }

  let bindings = List.map ~f:(fun t -> t.ident, t.ty)
end

(* The components of [expected], if it is known to be a tuple of [n]. *)
let tuple_components (expected : Type.ty option) n =
  match Option.map expected ~f:Type.canonical_ty with
  | Some (TTuple tys) when List.length tys = n -> List.map tys ~f:Option.some
  | Some _ | None -> List.init n ~f:(fun _ -> None)
;;

(* The type of [label] in [expected], if it is known to be a polymorphic record
   ([`Record]) or variant ([`Variant]) with it. *)
let row_entry (expected : Type.ty option) kind ~label =
  let rec find (row : Type.row) =
    match Type.canonical_row row with
    | RExtend (label', _, _, ty, rest) ->
      if String.equal label label' then Some ty else find rest
    | REmpty | RVar _ -> None
  in
  match Option.map expected ~f:Type.canonical_ty, kind with
  | Some (TRecord { row; _ }), `Record | Some (TVariant { row; _ }), `Variant ->
    find row
  | _ -> None
;;

(* [ty] if it is known, else [fallback]. *)
let either_known ty fallback =
  match Type.canonical_ty ty with
  | TVar _ -> fallback
  | _ -> Some ty
;;

(* [expected] is the type the pattern or expression is known to have where it is
   (it is not unified with it here): constructors and fields are looked up in it
   when it is a nominal type (see [Known]). *)
let rec pattern_type ?expected t (scope : Scope.t) ~(pattern : Source.Pattern.t)
  : Typed.Pattern.t * Pattern_var.t list
  =
  let loc = Source.Pattern.loc pattern in
  let node desc ty = { Typed.Pattern.desc; ty; loc } in
  let bind binder ty =
    let ident = Program_env.bind scope.program binder ty ~level:scope.level in
    ( ident
    , { Pattern_var.ident; ty; loc = Source.Binder.loc binder ~enclosing:loc } )
  in
  (* Each pattern of type [ty], known to be of [expected] (by default [ty]). *)
  let sub_patterns ?expected patterns =
    let expected =
      Option.value
        expected
        ~default:(List.map patterns ~f:(fun (_, ty) -> Some ty))
    in
    let typed =
      List.map2_exn patterns expected ~f:(fun (pattern, ty) expected ->
        let pattern, bindings = pattern_type t scope ~pattern ?expected in
        ( (if Scope.unifies t scope ~ty1:ty ~ty2:pattern.ty ~loc:pattern.loc
           then pattern
           else Typed.Pattern.error [ pattern ] ~loc:pattern.loc)
        , bindings ))
    in
    List.map typed ~f:fst, List.concat_map typed ~f:snd
  in
  (* What did not check binds its variables still, so that their uses are not
     errors too. *)
  let fail error patterns =
    Scope.report scope error;
    let patterns, bindings =
      sub_patterns
        (List.map patterns ~f:(fun pattern -> pattern, Scope.fresh_ty t scope))
    in
    Typed.Pattern.error patterns ~loc, bindings
  in
  match Source.Pattern.view pattern with
  | Any -> node Any (Scope.fresh_ty t scope), []
  | Var binder ->
    let ty = Scope.fresh_ty t scope in
    let ident, var = bind binder ty in
    node (Var ident) ty, [ var ]
  | Lit lit -> node (Lit lit) (Syntax.Lit.ty lit), []
  | Deref inner ->
    let expected =
      Option.bind expected ~f:(fun ty ->
        match Type.canonical_ty ty with
        | TCon ("ptr", [ ATy pointee ]) -> Some pointee
        | _ -> None)
    in
    let inner, bindings = pattern_type t scope ~pattern:inner ?expected in
    node (Deref inner) (Type.TCon ("ptr", [ ATy inner.ty ])), bindings
  | Tuple patterns ->
    let types = List.map patterns ~f:(fun _ -> Scope.fresh_ty t scope) in
    let patterns, bindings =
      sub_patterns
        (List.zip_exn patterns types)
        ~expected:(tuple_components expected (List.length patterns))
    in
    node (Tuple patterns) (Type.TTuple types), bindings
  | Construct (constructor, args) ->
    (match
       constructor_types
         t
         scope
         constructor
         ~args
         ~tuple:Source.Pattern.tuple
         ~expected
         ~loc
     with
     | Error error -> fail error args
     | Ok (constructor, args, result) ->
       let args, bindings = sub_patterns args in
       node (Construct (constructor, args)) result, bindings)
  | Record fields ->
    (match record_fields t scope fields ~all_required:false ~expected ~loc with
     | Error error -> fail error (List.map fields ~f:snd)
     | Ok (record, fields, (_ : bool)) ->
       let patterns, bindings = sub_patterns (List.map fields ~f:snd) in
       ( node (Record (List.zip_exn (List.map fields ~f:fst) patterns)) record
       , bindings ))
  | Poly_variant (tag, arg) ->
    let arg, bindings =
      match arg with
      | None -> None, []
      | Some pattern ->
        let pattern, bindings =
          pattern_type
            t
            scope
            ~pattern
            ?expected:(row_entry expected `Variant ~label:tag)
        in
        Some pattern, bindings
    in
    let arg_ty =
      Option.value_map arg ~default:Type.unit ~f:(fun pattern -> pattern.ty)
    in
    ( node (Poly_variant (tag, arg)) (Poly_row.variant t scope ~tag ~arg:arg_ty)
    , bindings )
  | Poly_record { fields; rest } ->
    Poly_row.report_duplicate_labels scope fields;
    let fields =
      List.map fields ~f:(fun (label, pattern) ->
        ( label.txt
        , pattern_type
            t
            scope
            ~pattern
            ?expected:(row_entry expected `Record ~label:label.txt) ))
    in
    let bindings =
      List.concat_map fields ~f:(fun (_, (_, bindings)) -> bindings)
    in
    let fields =
      List.map fields ~f:(fun (label, (pattern, _)) -> label, pattern)
    in
    let tail, rest, rest_bindings =
      match rest with
      | Closed -> Type.REmpty, Typed.Pattern.Rest.Closed, []
      | Open -> Scope.fresh_row t scope, Open, []
      | Bind binder ->
        let tail = Scope.fresh_row t scope in
        let ident, var = bind binder (Fresh.record t tail) in
        tail, Bind ident, [ var ]
    in
    let row =
      Poly_row.present
        (List.map fields ~f:(fun (label, (pattern : Typed.Pattern.t)) ->
           label, pattern.ty))
        ~tail
    in
    ( node (Poly_record { fields; rest }) (Fresh.record t row)
    , bindings @ rest_bindings )
  | Exception pattern ->
    fail (Typecheck_error.create ~loc Misplaced_exception_pattern) [ pattern ]
;;

(* Closing of the scrutinee and residuals of catch-alls in matches on
   polymorphic variants. *)
module Variant_match = struct
  (* The tags handled irrefutably by the cases so far, in order, each once. *)
  type t = string list

  let empty = []

  (* A top level variable pattern matches what the handled tags' cases have not:
     the scrutinee without their first entries. *)
  let pattern_type
    t
    (scope : Scope.t)
    handled
    ~(pattern : Source.Pattern.t)
    ~scrutinee
    =
    match Source.Pattern.view pattern, handled with
    | Var binder, _ :: _ ->
      let row, rest =
        Poly_row.open_
          t
          scope
          (List.map handled ~f:(fun tag -> tag, Scope.fresh_ty t scope))
      in
      let rest = Fresh.variant t rest in
      let ident =
        Program_env.bind scope.program binder rest ~level:scope.level
      in
      ( { Typed.Pattern.desc = Var ident
        ; ty = Fresh.variant t row
        ; loc = Source.Pattern.loc pattern
        }
      , [ { Pattern_var.ident
          ; ty = rest
          ; loc =
              Source.Binder.loc binder ~enclosing:(Source.Pattern.loc pattern)
          }
        ] )
    | _ -> pattern_type t scope ~pattern ~expected:scrutinee
  ;;

  let add_case handled ({ desc; ty = _; loc = _ } : Typed.Pattern.t) =
    match desc with
    | Poly_variant (tag, arg)
      when Option.for_all arg ~f:Typed.Pattern.is_irrefutable
           && not (List.mem handled tag ~equal:String.equal) ->
      handled @ [ tag ]
    | _ -> handled
  ;;

  let is_empty_nominal (scope : Scope.t) scrutinee =
    match Type.canonical_ty scrutinee with
    | TCon (name, _) -> Type_env.is_empty_variant scope.program.type_env name
    | _ -> Ok false
  ;;

  (* Without a top level catch-all, a variant scrutinee may only have the tags
     of the cases, and an empty match's none, unless the scrutinee is already
     known to be an empty nominal type. *)
  let close
    t
    (scope : Scope.t)
    ~scrutinee
    ~loc
    (patterns : Typed.Pattern.t list)
    =
    let patterns =
      List.map patterns ~f:(fun (pattern : Typed.Pattern.t) -> pattern.desc)
    in
    let tags =
      List.filter_map patterns ~f:(function
        | Poly_variant (tag, _) -> Some tag
        | _ -> None)
      |> List.stable_dedup ~compare:String.compare
    in
    let has_catch_all =
      List.exists patterns ~f:(function
        | Var _ | Any -> true
        | _ -> false)
    in
    let%bind.Result open_ =
      match patterns with
      | [] -> is_empty_nominal scope scrutinee
      | _ :: _ -> Ok (has_catch_all || List.is_empty tags)
    in
    if open_
    then Ok ()
    else (
      let closed =
        Poly_row.present
          (List.map tags ~f:(fun tag -> tag, Scope.fresh_ty t scope))
          ~tail:REmpty
      in
      Unify.unify_ty t ~ty1:(Fresh.variant t closed) ~ty2:scrutinee |> lift ~loc)
  ;;
end

let note_persistent_use (scope : Scope.t) (entry : Env.Entry.t) ~loc =
  match entry.binder with
  | Local ident when entry.level <> scope.level ->
    Queue.enqueue
      scope.program.persistent_uses
      { Persistent_use.ident
      ; loc
      ; used_at = scope.level
      ; wrap_error = Scope.wrap_error scope
      }
  | Local _ | Toplevel _ -> ()
;;

(* [name] is the context entry the variable is provided as, if it becomes a free
   variable of the quote: a local's name or a toplevel's canonical name. *)
let resolution_type t (scope : Scope.t) ~name ~toplevel ~loc : Resolution.t -> _
  = function
  | Local entry ->
    note_persistent_use scope entry ~loc;
    Ok (Scope.instantiate t scope entry.scheme, Typed.Var_ref.Bound entry.binder)
  | Outside_quote { usable = Some entry; _ } ->
    note_persistent_use scope entry ~loc;
    Ok (Scope.instantiate t scope entry.scheme, Persistent entry.binder)
  | Outside_quote { quote; usable = None; unusable } ->
    Option.iter unusable ~f:(fun entry ->
      Hashtbl.set
        scope.program.unusable_in_quotes
        ~key:name
        ~data:{ loc; var_level = entry.level; used_at = scope.level });
    let%map.Result ty =
      Unify.present_entry t ~row:quote.context ~name ~rank:quote.outside.rank
      |> lift ~loc
    in
    ty, if toplevel then Typed.Var_ref.Free_toplevel name else Free name
  | Unusable kind -> error ~loc kind
;;

(* Calls [f] on each use of a toplevel that evaluating [expr] (at [depth] quotes
   in) may need: not those in a function it only builds, nor in the code a quote
   builds (but those in the splices that run while it does). [built] is whether
   [expr]'s value is only built by what encloses it, rather than maybe called
   (or otherwise looked into): [f ~called:false] uses only need the toplevel's
   value. Returns the locals it may call (or look into). *)
let rec eager_uses (expr : Typed.Expr.t) ~depth ~built ~f : Typed.Ident.Set.t =
  let go = eager_uses ~f in
  let all ~built exprs =
    Typed.Ident.Set.union_list (List.map exprs ~f:(go ~depth ~built))
  in
  let use ~built (binder : Typed.Binder.t) =
    match binder with
    | _ when depth <> 0 -> Typed.Ident.Set.empty
    | Toplevel ident ->
      f ident ~called:(not built) expr.loc;
      Typed.Ident.Set.empty
    | Local ident ->
      if built then Typed.Ident.Set.empty else Typed.Ident.Set.singleton ident
  in
  match expr.desc with
  | Var (Bound binder | Persistent binder) -> use ~built binder
  | Assign ((Bound binder | Persistent binder), value) ->
    Set.union (use ~built:true binder) (go value ~depth ~built:false)
  | Quote body -> go body ~depth:(depth + 1) ~built:false
  | Splice { code; subs } ->
    Set.union
      (go code ~depth:(depth - 1) ~built:false)
      (match subs with
       | Explicit subs -> all ~built:false (List.map subs ~f:snd)
       | Implicit providers ->
         Map.data providers
         |> List.map ~f:(use ~built:false)
         |> Typed.Ident.Set.union_list)
  | Toplevel_splice { expansion; code = _ } -> go expansion ~depth ~built
  | Fun _ when depth = 0 && built -> Typed.Ident.Set.empty
  | Let { ident; args; body; in_; _ } when depth = 0 ->
    let called = go in_ ~depth ~built in
    (* [ident]'s value is only built if [in_] only builds what it uses it in. *)
    let only_built = not (Set.mem called ident) in
    let body =
      if List.is_empty args
      then go body ~depth ~built:only_built
      else if not only_built
      then go body ~depth ~built:false
      else Typed.Ident.Set.empty
    in
    Set.remove (Set.union called body) ident
  | Let_mut { body; in_; _ } ->
    Set.union (go body ~depth ~built:false) (go in_ ~depth ~built)
  | Match { scrutinee; cases; exception_cases } ->
    Set.union
      (go scrutinee ~depth ~built:false)
      (all ~built (List.map (cases @ exception_cases) ~f:snd))
  | Annotated _
  | Tuple _
  | Construct _
  | Record _
  | Poly_record _
  | Poly_variant _ -> all ~built (Typed.Expr.sub_exprs expr)
  | _ -> all ~built:false (Typed.Expr.sub_exprs expr)
;;

(* The toplevels [expr] uses when run, rather than in the code it builds or at
   compile time. *)
let rec run_toplevels (expr : Typed.Expr.t) ~depth ~f =
  let go = run_toplevels ~f in
  match expr.desc with
  | Var (Bound (Toplevel ident) | Persistent (Toplevel ident)) ->
    if depth = 0 then f ident
  | Assign ((Bound (Toplevel ident) | Persistent (Toplevel ident)), value) ->
    if depth = 0 then f ident;
    go value ~depth
  | Quote body -> go body ~depth:(depth + 1)
  | Splice { code; subs } ->
    go code ~depth:(depth - 1);
    (match subs with
     | Explicit subs -> List.iter subs ~f:(fun (_, sub) -> go sub ~depth)
     | Implicit _ -> ())
  | Toplevel_splice { code = _; expansion } -> go expansion ~depth
  | _ -> List.iter (Typed.Expr.sub_exprs expr) ~f:(go ~depth)
;;

module Init_need = struct
  (* A toplevel's value, or everything calling (or looking into) it may need. *)
  type t =
    | Value of Typed.Ident.t
    | Call of Typed.Ident.t
  [@@deriving compare, sexp_of]

  include functor Comparable.Make_plain

  let ident (Value ident | Call ident) = ident
end

(* A toplevel's value is computed when first needed, after its component's
   functions are bound: it can't be if computing it may need it again. Calls are
   assumed to need everything the callee refers to. *)
let check_initialization_cycles
  (program : Program_env.t)
  (members : Typed.Toplevel.t list)
  =
  let member ident =
    List.find members ~f:(fun (member : Typed.Toplevel.t) ->
      Typed.Ident.equal member.ident ident)
  in
  let is_function (member : Typed.Toplevel.t) =
    not (List.is_empty member.args)
  in
  (* Each need's direct needs, with where they are needed. *)
  let needs (need : Init_need.t) =
    let found = Queue.create () in
    let add need loc = Queue.enqueue found (need, loc) in
    (match need with
     | Value ident ->
       let toplevel = Option.value_exn (member ident) in
       if not (is_function toplevel)
       then
         eager_uses
           toplevel.body
           ~depth:0
           ~built:true
           ~f:(fun ident ~called loc ->
             match member ident with
             | None -> ()
             | Some used ->
               if called
               then add (Init_need.Call ident) loc
               else if not (is_function used)
               then add (Init_need.Value ident) loc)
         |> (ignore : Typed.Ident.Set.t -> unit)
     | Call ident ->
       let toplevel = Option.value_exn (member ident) in
       add (Value ident) toplevel.body.loc;
       run_toplevels toplevel.body ~depth:0 ~f:(fun used ->
         if Option.is_some (member used) then add (Call used) toplevel.body.loc));
    Queue.to_list found
  in
  List.fold members ~init:false ~f:(fun failed (toplevel : Typed.Toplevel.t) ->
    if failed || is_function toplevel
    then failed
    else (
      let start = Init_need.Value toplevel.ident in
      (* Breadth first, for the shortest cycle. *)
      let parent = ref Init_need.Map.empty in
      let queue = Queue.create () in
      let found = ref None in
      Queue.enqueue queue start;
      while Option.is_none !found && not (Queue.is_empty queue) do
        let current = Queue.dequeue_exn queue in
        List.iter (needs current) ~f:(fun (need, loc) ->
          if Option.is_none !found
          then
            if [%compare.equal: Init_need.t] need start
            then found := Some (current, loc)
            else if not (Map.mem !parent need)
            then (
              parent := Map.set !parent ~key:need ~data:(current, loc);
              Queue.enqueue queue need))
      done;
      match !found with
      | None -> failed
      | Some (last, last_loc) ->
        let rec path need acc =
          if [%compare.equal: Init_need.t] need start
          then need :: acc
          else path (fst (Map.find_exn !parent need)) (need :: acc)
        in
        let chain = path last [] in
        (* Where the first step is needed, in [toplevel]'s own body. *)
        let loc =
          match chain with
          | _ :: second :: _ -> snd (Map.find_exn !parent second)
          | [ _ ] | [] -> last_loc
        in
        let names =
          List.remove_consecutive_duplicates
            (List.map chain ~f:(fun need -> (Init_need.ident need).name)
             @ [ toplevel.ident.name ])
            ~equal:String.equal
        in
        let names =
          match names with
          | [ name ] -> [ name; name ]
          | names -> names
        in
        Program_env.report
          program
          (Typecheck_error.create ~loc (Toplevel_initialization_cycle names));
        true))
;;

(* The mutable toplevel a component may use when run, if any. *)
let runtime_only (program : Program_env.t) (members : Toplevel.t list) =
  let in_component (ident : Typed.Ident.t) =
    List.exists members ~f:(fun member -> Typed.Ident.equal member.ident ident)
  in
  List.find_map members ~f:(fun member ->
    if member.mut
    then Some member.ident.name
    else (
      match member.state with
      | In_progress { body = Some body; _ } ->
        With_return.with_return (fun { return } ->
          run_toplevels body ~depth:0 ~f:(fun ident ->
            if not (in_component ident)
            then (
              match (Program_env.toplevel program ident.name).state with
              | Done { runtime_only = Some global; _ } -> return (Some global)
              | Done { runtime_only = None; _ } | Unchecked | In_progress _ ->
                ()));
          None)
      | In_progress { body = None; _ } | Unchecked | Done _ -> None))
;;

let finish_scc t (program : Program_env.t) (members : Toplevel.t list) ~failed =
  Program_env.check_persistent_uses program;
  let failed =
    failed
    || check_initialization_cycles
         program
         (List.filter_map members ~f:(fun member ->
            match member.state with
            | In_progress { ty; args; body = Some body; _ } ->
              Some
                { Typed.Toplevel.ident = member.ident
                ; mut = member.mut
                ; args
                ; scheme = ty
                ; body
                }
            | In_progress { body = None; _ } | Unchecked | Done _ -> None))
  in
  let runtime_only = runtime_only program members in
  let persistent =
    List.for_all members ~f:(Program_env.is_persistent program)
  in
  let recursive =
    List.exists members ~f:(fun member ->
      match member.state with
      | In_progress { recursive; _ } -> recursive
      | Unchecked | Done _ -> false)
  in
  (* Like OCaml's [let rec], a recursive non-function is not generalized. *)
  let generalize =
    List.for_all members ~f:(fun member ->
      Toplevel.is_function member
      || ((not member.mut)
          &&
          match member.state with
          | In_progress { body = Some body; _ } -> Typed.Expr.is_value body
          | In_progress { body = None; _ } | Unchecked | Done _ -> false))
    && (persistent || not recursive)
  in
  if generalize
  then
    Scheme.generalize
      t
      ~rank:0
      (List.map members ~f:(fun member ->
         match member.state with
         | In_progress { ty; _ } -> ty
         | Unchecked | Done _ ->
           raise_s
             [%message "finish_scc: member not checked" (member : Toplevel.t)]));
  let members =
    List.map members ~f:(fun member ->
      match member.state with
      | In_progress { index; ty; args; body = Some body; _ } ->
        Program_env.add_info program member.ident ~ty ~level:0;
        let typed =
          { Typed.Toplevel.ident = member.ident
          ; mut = member.mut
          ; args
          ; scheme = ty
          ; body
          }
        in
        member.state
        <- Done
             { entry =
                 Env.Entry.toplevel
                   ~ident:member.ident
                   ~scheme:ty
                   ~persistent:(persistent || member.mut)
             ; typed
             ; failed
             ; runtime_only
             };
        index, typed
      | In_progress { body = None; _ } | Unchecked | Done _ ->
        raise_s
          [%message "finish_scc: member not checked" (member : Toplevel.t)])
    |> List.sort ~compare:(Comparable.lift Int.compare ~f:fst)
    |> List.map ~f:snd
  in
  let idents =
    Typed.Ident.Set.of_list
      (List.map members ~f:(fun (member : Typed.Toplevel.t) -> member.ident))
  in
  let scc =
    { Typed.Scc.members
    ; recursive =
        List.exists members ~f:(fun member ->
          Typed.Expr.refers_to member.body ~f:(function
            | Toplevel ident -> Set.mem idents ident
            | Local _ -> false))
    }
  in
  Queue.enqueue program.sccs scc;
  Interpreter.add_scc program.interpreter scc
;;

let intrinsic_type t scope intrinsic =
  Intrinsic.ty
    intrinsic
    ~var:(fun () -> Scope.fresh_ty t scope)
    ~row:(fun () -> Scope.fresh_row t scope)
