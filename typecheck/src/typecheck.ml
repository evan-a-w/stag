open! Import

(* A declaration generated by a declaration splice, whose errors are reported at
   the splice, naming the declaration. *)
module Generated = struct
  type t =
    { splice : Loc.t
    ; declaration : string
    ; generated : Syntax.Toplevel.t [@sexp.opaque]
    }
  [@@deriving sexp_of]

  let create splice (toplevel : Syntax.Toplevel.t) =
    let declaration =
      match toplevel.txt with
      | Let (name, _, _, _) -> "let " ^ name.txt
      | Let_mut (name, _, _) -> "let mut " ^ name.txt
      | Type decl -> "type " ^ decl.name.txt
      | Exception (name, _) | Malformed_exception (name, _) ->
        "exception " ^ name.txt
      | Module (name, _) | Module_splice (name, _, _) -> "module " ^ name.txt
      | Include _ -> "include"
      | Expect_test { name; _ } -> sprintf "let%%expect_test %S" name.txt
      | Bench { name; _ } -> sprintf "let%%bench %S" name.txt
    in
    { splice = Module_scope.Splice.loc splice
    ; declaration
    ; generated = toplevel
    }
  ;;

  (* Errors in generated code are at the splice. Others, eg. of written
     declarations it uses, are left as they are. *)
  let wrap_error t (error : Typecheck_error.t) =
    match error.kind with
    | In_generated_declaration _ -> error
    | _ when not (Loc.equal error.loc t.splice) -> error
    | kind ->
      { error with
        loc = t.splice
      ; kind =
          In_generated_declaration
            { declaration = t.declaration
            ; generated = t.generated
            ; error = kind
            }
      }
  ;;
end

(* The expression a toplevel splice of syntax gave, whose errors are reported at
   the splice. *)
module Syntax_splice = struct
  type t =
    { splice : Loc.t
    ; generated : Syntax.Expr.t
    }

  let wrap_error t (error : Typecheck_error.t) =
    match error.kind with
    | In_syntax_splice _ -> error
    | _ when not (Loc.equal error.loc t.splice) -> error
    | kind ->
      { error with
        kind = In_syntax_splice { generated = t.generated; error = kind }
      }
  ;;
end

module Toplevel = struct
  module State = struct
    type t =
      | Unchecked
      | In_progress of
          { index : int
          ; ty : Type.ty
          ; args : Typed.Ident.t list
          ; mutable body : Typed.Expr.t option
          ; mutable recursive : bool
          }
      | Done of
          { entry : Env.Entry.t
          ; typed : Typed.Toplevel.t
          ; failed : bool
          (** Its component, or one it uses, had an error, so it is not run at
              compile time. *)
          ; runtime_only : string option
          (** The mutable toplevel it may use when run, if any, so it can't be
              run at compile time, where there is none. *)
          }
    [@@deriving sexp_of]
  end

  type t =
    { ident : Typed.Ident.t
    ; module_ : Module_scope.t
    ; args : Syntax.Binding.t list
    ; annot : Syntax.Type_expr.t option
    ; expr : Syntax.Expr.t
    ; mut : bool
    ; generated : Generated.t option
    ; mutable state : State.t
    ; mutable intrinsic_alias : bool option
    (** Whether it is an alias of an intrinsic, once known. *)
    }
  [@@deriving sexp_of]

  let is_function t = not (List.is_empty t.args)

  (* The value it is an alias of, if any. *)
  let aliased t =
    match t.expr.txt with
    | Var (((Path _ | Root _) as path), None)
      when Option.is_none t.annot && (not t.mut) && not (is_function t) ->
      (match Module_scope.find_value t.module_ path ~loc:t.expr.loc with
       | Ok value -> Some value
       | Error _ -> None)
    | _ -> None
  ;;
end

(* Whether a local may reach a mutable local's cell, so that a closure capturing
   it may not be persistent: it is lifted by value into code. *)
module Reach = struct
  type t =
    | Mutable
    | Function of Typed.Ident.Set.t
    (** The locals it captures: it reaches one if one of those does. *)
    | Value of Typed.Ident.Set.t
    (** The locals its definition mentions: if one of those reaches one, it does
        if its type may hold a closure. *)
end

(* A use of a local function at a level other than its own, which it may only be
   if it reaches no mutable local, which is known once the types of what it
   captures are. *)
module Persistent_use = struct
  type t =
    { ident : Typed.Ident.t
    ; loc : Loc.t
    ; used_at : Env.Level.t
    ; wrap_error : Typecheck_error.t -> Typecheck_error.t
    (** As errors where it is used. *)
    }
end

type t =
  { fresh : Fresh.t
  ; stamps : Stamp_counter.t
  ; interpreter : Interpreter.t
  ; prelude : Syntax.Toplevel.t list Lazy.t
  }

let create ~stamps ~interpreter ?prelude () =
  { fresh = Fresh.create ()
  ; stamps
  ; interpreter
  ; prelude =
      (match prelude with
       | Some prelude -> Lazy.from_val prelude
       | None -> Prelude.toplevels)
  }
;;

let lift ~loc result =
  Result.map_error result ~f:(Typecheck_error.unification_error ~loc)
;;

let error ~loc kind = Error (Typecheck_error.create ~loc kind)

(* Toplevels are checked on demand, so strongly connected components are found
   with Tarjan's algorithm as we go. [pending] are the visited toplevels whose
   component is not yet complete. [id] identifies the errors reported while
   checking the frame's code. *)
module Scc_frame = struct
  type t =
    { id : int
    ; mutable lowlink : int
    ; mutable pending : Toplevel.t list
    ; mutable failed : bool
    }

  let create id ~pending = { id; lowlink = id; pending; failed = false }
end

module Report = struct
  type t =
    { error : Typecheck_error.t
    ; frame : int option
    (** The [Scc_frame.id] of the code it is in, if its checking may be
        abandoned. *)
    }
end

(* What one call of [typecheck] checks. *)
module Program_env = struct
  type t =
    { type_env : Type_env.t
    ; toplevels : Toplevel.t Lazy.t String.Table.t
    (** By canonical name. The prelude's are made when first used, so that those
        unused take no idents. *)
    ; stamps : Stamp_counter.t
    ; interpreter : Interpreter.t
    ; mutable ident_info : Typed.Ident_info.t Typed.Ident.Map.t
    ; sccs : Typed.Scc.t Queue.t
    ; declaration_splices : Typed.Expr.t Queue.t
    ; unusable_in_quotes : Typecheck_error.Unusable_in_quote.t String.Table.t
    (** The latest free variable of a quote that a binding of its name, unusable
        there, did not bind, to explain an error if the code is spliced where
        the name is unbound. *)
    ; unfinished : Type.ty Stack.t
    (** The types of the toplevels and binders of components not yet finished.
        Code checked later can reach them, so once their component is finished,
        the variables not generalized are lowered to rank 0, so that later
        components don't generalize them. *)
    ; mutable reports : Report.t list (** Latest first. *)
    ; mutable reported : int
    (** How many errors were reported, [Already_reported] and forgotten ones
        included. *)
    ; mutable syntax_errors : bool
    (** Whether the program has code that did not parse, reported by the parser. *)
    ; splice_starts : int Stack.t
    (** The index each declaration splice being generated began at, innermost
        first. *)
    ; mutable_idents : Typed.Ident.Hash_set.t
    (** Of the [let mut]s, local and toplevel. *)
    ; reach : Reach.t Typed.Ident.Table.t
    (** Of the [let]-bound locals: the others reach a mutable local if their
        type may hold a closure. *)
    ; persistent_uses : Persistent_use.t Queue.t
    }

  let report ?frame t error =
    t.reported <- t.reported + 1;
    t.reports <- { Report.error; frame } :: t.reports
  ;;

  let errors t =
    List.filter_map t.reports ~f:(fun { error; frame = _ } ->
      Option.some_if (not (Typecheck_error.is_already_reported error)) error)
  ;;

  (* Forgets the errors of the code of [frames], abandoned to be checked anew. *)
  let forget t ~frames =
    t.reports
    <- List.filter t.reports ~f:(fun { error = _; frame } ->
         not
           (Option.value_map
              frame
              ~default:false
              ~f:(List.mem frames ~equal:Int.equal)))
  ;;

  let fresh_ident t name = Typed.Ident.fresh t.stamps name

  let find_toplevel t name =
    Hashtbl.find t.toplevels name |> Option.map ~f:force
  ;;

  let toplevel t name = force (Hashtbl.find_exn t.toplevels name)

  (* Such as [Ptr.make], or an alias of one: a builtin, so its value needn't be
     lifted. *)
  let is_intrinsic_alias t toplevel =
    let rec go (toplevel : Toplevel.t) ~visited =
      match toplevel.intrinsic_alias with
      | Some known -> known
      | None ->
        let name = toplevel.ident.name in
        let known =
          (not (Set.mem visited name))
          &&
          match Toplevel.aliased toplevel with
          | Some (Intrinsic _) -> true
          | Some (Toplevel target) ->
            Option.value_map
              (find_toplevel t target)
              ~default:false
              ~f:(go ~visited:(Set.add visited name))
          | Some (Prim _ | Unbound) | None -> false
        in
        toplevel.intrinsic_alias <- Some known;
        known
    in
    go toplevel ~visited:String.Set.empty
  ;;

  (* Usable in quotes once checked: a mutable toplevel is referred to by name,
     like a function, rather than lifted. *)
  let is_persistent t (toplevel : Toplevel.t) =
    Toplevel.is_function toplevel
    || toplevel.mut
    || is_intrinsic_alias t toplevel
  ;;

  let add_info t ident ~ty ~level =
    let info = { Typed.Ident_info.ty; level } in
    t.ident_info <- Map.add_exn t.ident_info ~key:ident ~data:info;
    Interpreter.add_ident_info t.interpreter ~ident ~info
  ;;

  (* Generated code's binders keep their idents, but get their info anew. *)
  let bind t (binder : Source.Binder.t) ty ~level =
    let ident =
      match binder with
      | Name name -> fresh_ident t name.txt
      | Ident ident -> ident
    in
    add_info t ident ~ty ~level;
    Stack.push t.unfinished ty;
    ident
  ;;

  (* Values a toplevel splice's code embedded in its code. *)
  let embedded t ident =
    Interpreter.global_info t.interpreter ~ident
    |> Option.map ~f:(fun info ->
      t.ident_info <- Map.set t.ident_info ~key:ident ~data:info;
      Hashtbl.set t.reach ~key:ident ~data:(Function Typed.Ident.Set.empty);
      info)
  ;;

  let is_mutable t ident = Hash_set.mem t.mutable_idents ident

  (* How [ident] may reach a mutable local, if it may: the locals in between and
     what it reaches. *)
  let reaches_mutable t ident =
    let visited = Typed.Ident.Hash_set.create () in
    let rec reaches ident ~via =
      if Hash_set.Ok_or_duplicate.is_duplicate
           (Hash_set.strict_add visited ident)
      then None
      else (
        let ty = Map.find t.ident_info ident in
        let by_type () =
          match ty with
          | Some { ty; level = _ } -> May_hold_closure.ty t.type_env ty
          | None -> true
        in
        let through idents =
          Set.to_list idents
          |> List.find_map ~f:(reaches ~via:(ident.Typed.Ident.name :: via))
        in
        match Hashtbl.find t.reach ident with
        | Some Mutable -> Some (List.rev via, `Mutable ident.name)
        | Some (Function captures) -> through captures
        | Some (Value mentions) -> if by_type () then through mentions else None
        | None ->
          Option.some_if
            (by_type ())
            ( List.rev via
            , `Variable
                ( ident.name
                , Option.value_map ty ~default:Type.unit ~f:(fun info ->
                    info.ty) ) ))
    in
    reaches ident ~via:[]
  ;;

  (* Reports the uses of local functions at other levels whose functions turn
     out to reach a mutable local. *)
  let check_persistent_uses t =
    Queue.iter
      t.persistent_uses
      ~f:(fun { Persistent_use.ident; loc; used_at; wrap_error } ->
        match reaches_mutable t ident with
        | None -> ()
        | Some (via, reached) ->
          let var_level =
            match Map.find t.ident_info ident with
            | Some { level; ty = _ } -> level
            | None -> used_at
          in
          let via = List.drop via 1 in
          let name = ident.name in
          report
            t
            (wrap_error
               (Typecheck_error.create
                  ~loc
                  (match reached with
                   | `Mutable mutable_ ->
                     Captures_mutable
                       { name; var_level; used_at; via; mutable_ }
                   | `Variable (variable, ty) ->
                     May_capture_mutable
                       { name; var_level; used_at; via; variable; ty }))));
    Queue.clear t.persistent_uses
  ;;
end

(* Raised where code run at compile time by a declaration splice uses a toplevel
   whose checking was underway before the splice began, directly or through
   toplevels in its component, so it is left to be forced again. *)
exception Uses_unfinished

(* Carries why reflection failed, eg. a cycle, through the evaluation, to be the
   error of that evaluation. *)
exception Reflection_failed of Typecheck_error.t

let () =
  Sexplib0.Sexp_conv.Exn_converter.add
    [%extension_constructor Reflection_failed]
    (Basement.Stdlib_shim.Obj.magic_portable (function
      | Reflection_failed error ->
        Sexp.List
          [ Atom "typecheck.ml.Reflection_failed"
          ; Typecheck_error.sexp_of_t error
          ]
      | _ -> assert false))
;;

(* Raised by the interpreter: a bug, eg. ill-typed code that was run. *)
exception Internal of exn

(* Evaluates at compile time, reflecting on the program's types. *)
let at_compile_time (program : Program_env.t) f ~loc ~error =
  let reflect name =
    let%bind.Result decl = Type_env.reflect program.type_env name in
    let%map.Result decl_type =
      Type_env.record_type
        program.type_env
        (Prelude_path.canonical "Stag.Type.Decl.t")
    in
    { Reflected_decl.Reflection.decl; decl_type }
  in
  let reflect name =
    reflect name
    |> Result.map_error ~f:(fun error -> Error.of_exn (Reflection_failed error))
  in
  (match f ~reflect with
   | result -> result
   | exception Uses_unfinished -> raise Uses_unfinished
   | exception exn -> Error (Error.of_exn (Internal exn)))
  |> Result.map_error ~f:(fun runtime_error ->
    match Error.to_exn runtime_error with
    | Reflection_failed reflection_error -> reflection_error
    | Erase.Reached_error -> Typecheck_error.already_reported
    | Internal exn ->
      Typecheck_error.create
        ~loc
        (Internal_error
           (Error.tag_s
              (Error.of_exn exn)
              ~tag:[%message "Evaluating at compile time raised"]))
    | _ -> error runtime_error)
;;

module Scope = struct
  type t =
    { program : Program_env.t
    ; level : Env.Level.t
    ; rank : Type.rank
    ; locals : Env.t
    ; quote : quote option
    ; module_ : Module_scope.t
    ; scc : Scc_frame.t
    ; annotation_vars : Type_env.Annotation_vars.t
    ; in_expect_test : bool
    ; generated : Generated.t option
    ; syntax_splice : Syntax_splice.t option
    }

  and quote =
    { id : int
    ; context : Type.row
    ; outside : t
    }

  let quote_id t = Option.map t.quote ~f:(fun quote -> quote.id)

  let entry t ~ident ~scheme ~persistent =
    { Env.Entry.scheme
    ; level = t.level
    ; quote_id = quote_id t
    ; persistent
    ; binder = Local ident
    }
  ;;

  let fresh_ty ids t = Type.TVar (Fresh.var ids ~rank:t.rank)
  let fresh_row ids t = Type.RVar (Fresh.var ids ~rank:t.rank)
  let fresh_presence ids t = Type.PVar (Fresh.var ids ~rank:t.rank)
  let instantiate ids t = Scheme.instantiate ids ~rank:t.rank

  (* Type splices are evaluated in declarations, not in what is evaluated or
     quoted then. *)
  let splices t = Option.is_none t.quote && t.level >= 0

  let wrap_error t error =
    Module_scope.within
      t.module_
      (let error =
         match t.syntax_splice with
         | None -> error
         | Some splice -> Syntax_splice.wrap_error splice error
       in
       match t.generated with
       | None -> error
       | Some generated -> Generated.wrap_error generated error)
  ;;

  let report t (error : Typecheck_error.t) =
    let frame = t.scc.id in
    if Typecheck_error.is_already_reported error
    then Program_env.report t.program error ~frame
    else Program_env.report t.program ~frame (wrap_error t error)
  ;;

  let report_if_error t = function
    | Ok () -> ()
    | Error error -> report t error
  ;;

  (* Whether they unify: if not, what checked is to become [Error]. *)
  let unifies ids t ~ty1 ~ty2 ~loc =
    match Unify.unify_ty ids ~ty1 ~ty2 with
    | Ok () -> true
    | Error error ->
      report t (Typecheck_error.unification_error ~loc error);
      false
  ;;

  let elaborate_resolved t annot =
    Type_env.elaborate
      t.program.type_env
      t.module_
      t.annotation_vars
      annot
      ~splices:(splices t)
  ;;

  let elaborate t annot = elaborate_resolved t annot |> Result.map ~f:fst
end

(* Where a name is used, given its entry if it has one. *)
module Resolution = struct
  type t =
    | Local of Env.Entry.t
    (** Usable, and bound in the enclosing quote if there is one. *)
    | Outside_quote of
        { quote : Scope.quote
        ; usable : Env.Entry.t option
        ; unusable : Env.Entry.t option
        }
    (** Not bound in the enclosing [quote], so a free variable of it, unless
        used directly while [usable]. Splices never capture the name. [unusable]
        is the entry of the name, if it has one that isn't [usable]. *)
    | Unusable of Typecheck_error.Kind.t (** The error if the name is used. *)

  let of_entry (scope : Scope.t) ~name (entry : Env.Entry.t option) =
    let usable entry =
      Env.Entry.is_allowed_at
        entry
        ~used_at:scope.level
        ~quote_id:(Scope.quote_id scope)
    in
    let is_mutable_local (entry : Env.Entry.t) =
      match entry.binder with
      | Local ident -> Program_env.is_mutable scope.program ident
      | Toplevel _ -> false
    in
    match scope.quote, entry with
    | None, Some entry when usable entry -> Local entry
    | Some quote, Some entry
      when [%equal: int option] entry.quote_id (Some quote.id) -> Local entry
    | _, Some entry when is_mutable_local entry && entry.level <> scope.level ->
      Unusable
        (Mutable_used_outside_its_code
           { name; var_level = entry.level; used_at = scope.level })
    | Some quote, Some entry when entry.level <= scope.level ->
      let usable = usable entry in
      Outside_quote
        { quote
        ; usable = Option.some_if usable entry
        ; unusable = Option.some_if (not usable) entry
        }
    | Some quote, None ->
      Outside_quote { quote; usable = None; unusable = None }
    | _, Some entry ->
      Unusable
        (Variable_used_at_wrong_level
           { name; var_level = entry.level; used_at = scope.level })
    | None, None -> Unusable (Not_in_scope (Path (Syntax.Path.of_string name)))
  ;;
end

(* Errs at the second occurrence of the first name repeated. *)
let check_no_duplicates (names : Syntax.Name.t list) ~error:kind =
  List.fold_result names ~init:String.Set.empty ~f:(fun seen { txt; loc } ->
    if Set.mem seen txt then error ~loc (kind txt) else Ok (Set.add seen txt))
  |> Result.ignore_m
;;

(* Reports each repeated occurrence of a name. *)
let report_duplicates scope (names : Syntax.Name.t list) ~error:kind =
  ignore
    (List.fold names ~init:String.Set.empty ~f:(fun seen { txt; loc } ->
       if Set.mem seen txt
       then (
         Scope.report scope (Typecheck_error.create ~loc (kind txt));
         seen)
       else Set.add seen txt)
     : String.Set.t)
;;

module Function_type = struct
  type t =
    { args : (Typed.Ident.t * Type.ty) list
    ; annots : (Typed.Ident.t * Syntax.Type_expr.t) list
    ; result_annot : Syntax.Type_expr.t option
    ; res_ty : Type.ty
    ; ty : Type.ty
    }
end

(* An annotation that fails to elaborate is reported, and ignored. *)
let function_type
  t
  (scope : Scope.t)
  ~(args : (Source.Binder.t * Syntax.Type_expr.t option) list)
  ~annot
  =
  report_duplicates
    scope
    (List.filter_map args ~f:(fun ((binder : Source.Binder.t), _) ->
       match binder with
       | Name name when not (String.equal name.txt "_") -> Some name
       | Name _ | Ident _ -> None))
    ~error:(fun name -> Duplicate_parameter name);
  let annot_type = function
    | None -> Scope.fresh_ty t scope, None
    | Some annot ->
      (match Scope.elaborate_resolved scope annot with
       | Ok (ty, resolved) -> ty, Some resolved
       | Error error ->
         Scope.report scope error;
         Scope.fresh_ty t scope, None)
  in
  let args =
    List.map args ~f:(fun (binder, annot) ->
      let ty, resolved = annot_type annot in
      binder, ty, resolved)
  in
  let res_ty, result_annot = annot_type annot in
  let ty =
    List.fold_right args ~init:res_ty ~f:(fun (_, arg_ty, _) ty ->
      Type.TArrow (arg_ty, ty))
  in
  let args, annots =
    List.map args ~f:(fun (binder, ty, resolved) ->
      let ident = Program_env.bind scope.program binder ty ~level:scope.level in
      (ident, ty), Option.map resolved ~f:(fun resolved -> ident, resolved))
    |> List.unzip
  in
  { Function_type.args
  ; annots = List.filter_opt annots
  ; result_annot
  ; res_ty
  ; ty
  }
;;

